/// Where the Objective-C sources live, relative to the workspace root.
const DIR: &str = "sdk/objc";

/// The prefix every name in this SDK carries, since Objective-C has no
/// namespaces and two-letter prefixes belong to Apple.
const PREFIX: &str = "OTIO";

/// The root of the OTIO schema ladder, which this SDK spells as upstream
/// does, with the prefix on the front.
const ROOT: &str = "OTIOSerializableObject";

/// Four spaces, which is what Cocoa indents with.
const TAB: &str = "    ";

/// Generates every file of the Objective-C library.
///
/// # Errors
///
/// Fails if two calls would end up with the same selector on one class, or if
/// a call cannot be written mechanically and is not hand-written here.
pub fn generate(api: &Api) -> Result<Vec<File>, String> {
    let backend = Backend::new(api);
    backend.check_names()?;
    let (calls_header, calls_source) = backend.calls()?;
    let (values_header, values_source) = backend.values();
    Ok(vec![
        plain("Makefile", MAKEFILE),
        plain(".gitignore", BUILD_GITIGNORE),
        plain("lib/.gitignore", LIB_GITIGNORE),
        plain("README.md", README),
        header("OpenTimelineIO.h", UMBRELLA.to_string()),
        header("OTIOEnums.h", backend.enums_header()),
        source("OTIOEnums.m", backend.enums_source()),
        header("OTIOValues.h", values_header),
        source("OTIOValues.m", values_source),
        header("OTIORuntime.h", RUNTIME_HEADER.to_string()),
        source("OTIORuntime.m", RUNTIME_SOURCE.to_string()),
        header("OTIOSchema.h", backend.schema_header()),
        source("OTIOSchema.m", backend.schema_source()),
        header("OTIOCalls.h", calls_header),
        source("OTIOCalls.m", calls_source),
        source("OTIOPrivate.h", backend.private_header()),
    ])
}

/// A file whose contents do not depend on the description.
fn plain(name: &str, contents: &str) -> File {
    File {
        path: PathBuf::from(DIR).join(name),
        contents: contents.to_string(),
    }
}

/// A public header, with the generated-code notice on it.
fn header(name: &str, body: String) -> File {
    let mut out =
        String::from("// Code generated by otio-sdk-gen from crates/otio-capi. DO NOT EDIT.\n\n");
    out.push_str("#pragma once\n\n");
    out.push_str(body.trim_end());
    out.push('\n');
    File {
        path: PathBuf::from(DIR).join("include/OpenTimelineIO").join(name),
        contents: out,
    }
}

/// An implementation file, with the generated-code notice on it.
fn source(name: &str, body: String) -> File {
    let mut out =
        String::from("// Code generated by otio-sdk-gen from crates/otio-capi. DO NOT EDIT.\n\n");
    out.push_str(body.trim_end());
    out.push('\n');
    File {
        path: PathBuf::from(DIR).join("src").join(name),
        contents: out,
    }
}

/// The state a backend carries while it writes.
struct Backend<'a> {
    api: &'a Api,
    /// How each interface symbol is spelled here, for the documentation.
    spellings: BTreeMap<String, String>,
}

impl<'a> Backend<'a> {
    fn new(api: &'a Api) -> Self {
        let mut spellings = BTreeMap::new();
        for group in &api.groups {
            for function in &group.functions {
                spellings.insert(function.symbol.clone(), base_name(api, group, function));
            }
        }
        for item in &api.enums {
            for variant in &item.variants {
                spellings.insert(
                    variant.c_name.clone(),
                    variant_name(&item.name, &variant.name),
                );
            }
        }
        Self { api, spellings }
    }

    /// Fails if two calls would land on one class with the same selector.
    ///
    /// Objective-C has no overloading: one selector is one method, and a
    /// method declared on `OTIOItem` is reachable on an `OTIOClip`. Two calls
    /// named the same on `OTIOItem` and on `OTIOEffect` are fine, because
    /// neither derives from the other.
    fn check_names(&self) -> Result<(), String> {
        let mut placed: Vec<(String, String, String)> = Vec::new();
        for (owner, selector) in RESERVED {
            placed.push(((*owner).to_string(), (*selector).to_string(), String::new()));
        }
        let mut clashes = Vec::new();
        for group in &self.api.groups {
            for function in &group.functions {
                if self.skipped(function) {
                    continue;
                }
                let owner = self.owner_of(group, function);
                let selector = self.selector_of(group, function)?;
                for (other_owner, other_selector, other_symbol) in &placed {
                    if *other_selector != selector || !self.meet(&owner, other_owner) {
                        continue;
                    }
                    let first = if other_symbol.is_empty() {
                        format!("the hand-written {other_owner} {other_selector}")
                    } else {
                        format!("`{other_symbol}`")
                    };
                    clashes.push(format!(
                        "{first} and `{}` are both {selector} on {owner}",
                        function.symbol
                    ));
                }
                placed.push((owner, selector, function.symbol.clone()));
            }
        }
        if clashes.is_empty() {
            return Ok(());
        }
        Err(format!(
            "the Objective-C names collide:\n  {}\n\nGive one of each pair another name in \
             `otio-sdk-model/src/overrides.rs`.",
            clashes.join("\n  ")
        ))
    }

    /// Whether this backend leaves a call out of the generated surface.
    fn skipped(&self, function: &Function) -> bool {
        let _ = self;
        matches!(function.role, Role::Plumbing | Role::Destructor)
            || HIDDEN.iter().any(|(symbol, _)| *symbol == function.symbol)
    }

    /// Whether two owners are places a caller could reach the same selector
    /// from, which for a class is anywhere on its line of descent.
    fn meet(&self, left: &str, right: &str) -> bool {
        if left == right {
            return true;
        }
        let (Some(one), Some(other)) =
            (left.strip_prefix("object:"), right.strip_prefix("object:"))
        else {
            return false;
        };
        self.api
            .ancestry(one)
            .iter()
            .any(|schema| schema.name == other)
            || self
                .api
                .ancestry(other)
                .iter()
                .any(|schema| schema.name == one)
    }

    /// Where a call lands: a class, or `function` for the ones that are C
    /// functions rather than methods.
    fn owner_of(&self, group: &Group, function: &Function) -> String {
        if let Some((owner, _)) = rehomed(&function.symbol) {
            return owner.to_string();
        }
        match (&group.receiver, function.role) {
            (Receiver::None, _) | (Receiver::Value(_), _) => "function".to_string(),
            // Nothing hangs off the document, because there is no document to
            // hang it off. Objective-C has no namespace to put what is left
            // in, so it is a C function beside the other free ones.
            (Receiver::Document, _) => "function".to_string(),
            (Receiver::Node(schema), Role::Constructor) => {
                if takes_a_document(function) {
                    // A class method of the schema it builds, which is how
                    // Cocoa spells a constructor that can fail without making
                    // a caller reason about what -init left behind.
                    format!("class:{schema}")
                } else {
                    format!("class:{ROOT}")
                }
            }
            (Receiver::Node(schema), _) => {
                if group.view {
                    group.name.clone()
                } else {
                    format!("object:{schema}")
                }
            }
        }
    }

    /// The whole selector a call is reached by, or its name where it is a C
    /// function.
    fn selector_of(&self, group: &Group, function: &Function) -> Result<String, String> {
        let plan = self.plan(group, function)?;
        Ok(plan.selector())
    }
}

/// Whether a call is given a document to work in.
fn takes_a_document(function: &Function) -> bool {
    function
        .params
        .iter()
        .any(|param| matches!(param.role, ParamRole::DocumentIn | ParamRole::DocumentMut))
}

/// The bare name of a call, before any labels.
fn base_name(api: &Api, group: &Group, function: &Function) -> String {
    let spelled = names::camel(&function.name);
    if let Some((_, name)) = rehomed(&function.symbol) {
        return name.to_string();
    }
    match (&group.receiver, function.role) {
        // A constructor is a class method named after what it builds, as
        // +[NSString stringWithFormat:] is. `new` is a reserved family in
        // Objective-C — a method whose name starts with it must hand back
        // something the caller owns — so the schema's own name is used
        // instead, and `plan` adds the `With` and the first label.
        (Receiver::Node(schema), Role::Constructor) if takes_a_document(function) => {
            let bare = names::uncapitalize(schema);
            if function.name == "new" {
                bare
            } else {
                format!("{bare}{}", names::pascal(&function.name))
            }
        }
        // What the document used to carry is a C function now, and its name
        // carries the prefix as the other free ones do.
        (Receiver::None | Receiver::Document, _) => {
            format!("{PREFIX}{}", names::pascal(&function.name))
        }
        (Receiver::Value(what), _) => {
            let owner = if api.enumeration(what).is_some() {
                enum_name(what)
            } else {
                value_name(what)
            };
            format!("{owner}{}", names::pascal(&function.name))
        }
        _ => spelled,
    }
}

/// The class name of a schema: `Clip` becomes `OTIOClip`.
fn class_name(schema: &str) -> String {
    format!("{PREFIX}{schema}")
}

/// The name of an enum: `OtioNodeKind` becomes `OTIONodeKind`.
fn enum_name(c_name: &str) -> String {
    format!(
        "{PREFIX}{}",
        names::respell(
            c_name.strip_prefix("Otio").unwrap_or(c_name),
            names::INITIALISMS
        )
    )
}

/// The name of a value struct: `OtioRationalTime` becomes
/// `OTIORationalTime`.
fn value_name(c_name: &str) -> String {
    enum_name(c_name)
}

/// The name of one of an enum's constants, which Cocoa spells by putting the
/// type's own name on the front.
fn variant_name(c_enum: &str, variant: &str) -> String {
    format!(
        "{}{}",
        enum_name(c_enum),
        names::respell(variant, names::INITIALISMS)
    )
}

/// The type a value has in this SDK's surface.
fn objc_type(ty: &Type) -> String {
    match ty {
        Type::Bool => "BOOL".to_string(),
        Type::Double => "double".to_string(),
        Type::Int64 => "int64_t".to_string(),
        Type::Uint64 => "uint64_t".to_string(),
        Type::Int32 => "int32_t".to_string(),
        Type::Uint32 => "uint32_t".to_string(),
        // Cocoa counts and indexes with `NSUInteger`, whatever C does.
        Type::Size => "NSUInteger".to_string(),
        Type::Text => "NSString *".to_string(),
        Type::Bytes => "NSData *".to_string(),
        // A whole document read out of a file is, to a caller, the object it
        // is about.
        Type::Node | Type::Document => format!("{ROOT} *"),
        Type::Struct(name) => value_name(name),
        Type::Enum(name) => enum_name(name),
        Type::List(inner) => format!("NSArray<{}> *", element_type(inner)),
    }
}

/// The type of one element of a list, which has to be an object.
///
/// A list of numbers or of value structs is boxed, because an `NSArray` holds
/// objects; a list of handles is not, because a handle is already one.
fn element_type(ty: &Type) -> String {
    match ty {
        Type::Node => format!("{ROOT} *"),
        Type::Text => "NSString *".to_string(),
        Type::Struct(_) => "NSValue *".to_string(),
        _ => "NSNumber *".to_string(),
    }
}

/// Whether a type is an object, and so can be answered as `nil`.
fn is_object(ty: &Type) -> bool {
    matches!(
        ty,
        Type::Text | Type::Bytes | Type::Node | Type::Document | Type::List(_)
    )
}

/// The C type a value crosses the boundary as.
fn c_type(ty: &Type) -> String {
    match ty {
        Type::Bool => "bool".to_string(),
        Type::Double => "double".to_string(),
        Type::Int64 => "int64_t".to_string(),
        Type::Uint64 => "uint64_t".to_string(),
        Type::Int32 => "int32_t".to_string(),
        Type::Uint32 => "uint32_t".to_string(),
        Type::Size => "size_t".to_string(),
        Type::Text | Type::Bytes => "OtioBuffer".to_string(),
        Type::Node => "OtioNode".to_string(),
        Type::Document => "OtioDocument *".to_string(),
        Type::Struct(name) | Type::Enum(name) => name.clone(),
        Type::List(inner) => c_type(inner),
    }
}

/// Turns a value of this SDK into the C one a call wants.
fn to_c(ty: &Type, value: &str) -> String {
    match ty {
        Type::Bool => format!("({value} ? true : false)"),
        Type::Size => format!("(size_t){value}"),
        Type::Node => format!("{value}.handle"),
        Type::Struct(name) => format!("{}ToC({value})", value_name(name)),
        Type::Enum(name) => format!("({name}){value}"),
        _ => value.to_string(),
    }
}

/// Turns the C value a call gave back into one of this SDK's.
fn from_c(ty: &Type, value: &str, owner: &str) -> String {
    match ty {
        Type::Bool => format!("({value} ? YES : NO)"),
        Type::Size => format!("(NSUInteger){value}"),
        Type::Node => format!("OTIOMakeObject({owner}, {value})"),
        Type::Document => format!("OTIORootOf({value}, error)"),
        Type::Text => format!("OTIOStringFromBuffer({value})"),
        Type::Bytes => format!("OTIODataFromBuffer({value})"),
        Type::Struct(name) => format!("{}FromC({value})", value_name(name)),
        Type::Enum(name) => format!("({}){value}", enum_name(name)),
        Type::Double | Type::Int64 | Type::Uint64 | Type::Int32 | Type::Uint32 | Type::List(_) => {
            value.to_string()
        }
    }
}

/// Boxes one element of a list so that an `NSArray` can hold it.
fn box_element(ty: &Type, value: &str, owner: &str) -> String {
    match ty {
        Type::Node | Type::Text | Type::Bytes => from_c(ty, value, owner),
        Type::Struct(name) => format!(
            "{}Boxed({}FromC({value}))",
            value_name(name),
            value_name(name)
        ),
        Type::Bool => format!("[NSNumber numberWithBool:{}]", from_c(ty, value, owner)),
        Type::Double => format!("[NSNumber numberWithDouble:{value}]"),
        Type::Int64 => format!("[NSNumber numberWithLongLong:{value}]"),
        Type::Uint64 => format!("[NSNumber numberWithUnsignedLongLong:{value}]"),
        Type::Int32 => format!("[NSNumber numberWithInt:{value}]"),
        Type::Uint32 => format!("[NSNumber numberWithUnsignedInt:{value}]"),
        Type::Size => format!("[NSNumber numberWithUnsignedLongLong:(uint64_t){value}]"),
        Type::Enum(name) => format!("[NSNumber numberWithInt:(int)({}){value}]", enum_name(name)),
        Type::Document | Type::List(_) => value.to_string(),
    }
}

/// Reads one element of a list back out of whatever boxed it.
fn unbox_element(ty: &Type, value: &str) -> String {
    match ty {
        Type::Node => format!("{value}.handle"),
        Type::Struct(name) => format!(
            "{}ToC({}Unboxed({value}))",
            value_name(name),
            value_name(name)
        ),
        Type::Bool => format!("({value}.boolValue ? true : false)"),
        Type::Double => format!("{value}.doubleValue"),
        Type::Int64 => format!("{value}.longLongValue"),
        Type::Uint64 => format!("{value}.unsignedLongLongValue"),
        Type::Int32 => format!("{value}.intValue"),
        Type::Uint32 => format!("{value}.unsignedIntValue"),
        Type::Size => format!("(size_t){value}.unsignedLongLongValue"),
        Type::Enum(name) => format!("({name}){value}.intValue"),
        _ => value.to_string(),
    }
}

/// The value a call answers with when it has no way to report a mistake.
fn objc_zero(ty: &Type) -> Result<String, String> {
    Ok(match ty {
        Type::Bool => "NO".to_string(),
        Type::Double | Type::Int64 | Type::Uint64 | Type::Int32 | Type::Uint32 | Type::Size => {
            "0".to_string()
        }
        Type::Text => "@\"\"".to_string(),
        Type::List(_) => "@[]".to_string(),
        other => {
            return Err(format!(
                "a call that cannot fail answers with a `{}`, which has no value to stand for \
                 an object from another timeline",
                other.c_name()
            ));
        }
    })
}

/// A run of generated lines, kept at the right indentation.
struct Lines {
    out: Vec<String>,
    depth: usize,
}

impl Lines {
    fn new() -> Self {
        Self {
            out: Vec::new(),
            depth: 0,
        }
    }

    fn push(&mut self, line: &str) {
        if line.is_empty() {
            self.out.push(String::new());
        } else {
            self.out.push(format!("{}{line}", TAB.repeat(self.depth)));
        }
    }

    fn open(&mut self, line: &str) {
        self.push(&format!("{line} {{"));
        self.depth += 1;
    }

    fn close(&mut self) {
        self.depth -= 1;
        self.push("}");
    }
}

/// One argument of a call: what it is labelled, what type it has, and what
/// it is called.
struct Arg {
    /// The label it is reached by, where it is not the first.
    label: String,
    /// Its type, written as Objective-C writes one.
    ty: String,
    /// Its own name.
    name: String,
}

impl Arg {
    /// How it is written in a C function's parameter list.
    fn declared(&self) -> String {
        if self.ty.ends_with('*') {
            format!("{}{}", self.ty, self.name)
        } else {
            format!("{} {}", self.ty, self.name)
        }
    }
}

/// How one call is spelled: its name, its arguments, what it answers with,
/// and whether it is a method at all.
struct Plan {
    /// The bare name, before the first colon.
    base: String,
    /// The arguments, in the order they are written.
    args: Vec<Arg>,
    /// What the call answers with.
    result: String,
    /// Whether it is a C function rather than a method.
    is_function: bool,
    /// Whether it is a class method.
    is_class: bool,
}

impl Plan {
    /// The selector, which is what Objective-C tells two methods apart by.
    ///
    /// A C function has no selector: its name is what it is known by, and two
    /// of them sharing one name is the same collision.
    fn selector(&self) -> String {
        if self.is_function || self.args.is_empty() {
            return self.base.clone();
        }
        let mut out = format!("{}:", self.base);
        for arg in self.args.iter().skip(1) {
            out.push_str(&arg.label);
            out.push(':');
        }
        out
    }

    /// The declaration, without the body.
    fn declaration(&self) -> String {
        if self.is_function {
            let arguments = if self.args.is_empty() {
                "void".to_string()
            } else {
                self.args
                    .iter()
                    .map(Arg::declared)
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let result = if self.result.ends_with('*') {
                self.result.clone()
            } else {
                format!("{} ", self.result)
            };
            return format!("{result}{}({arguments})", self.base);
        }
        let lead = if self.is_class { "+" } else { "-" };
        let Some(first) = self.args.first() else {
            return format!("{lead} ({}){}", self.result, self.base);
        };
        let mut out = format!(
            "{lead} ({}){}:({}){}",
            self.result, self.base, first.ty, first.name
        );
        for arg in self.args.iter().skip(1) {
            let _ = write!(out, " {}:({}){}", arg.label, arg.ty, arg.name);
        }
        out
    }
}

/// Where a call gets the arena it is made in, now that a caller no longer
/// hands one over.
///
/// The description says which object the call is anchored on — see
/// `Param::anchor` — and this is what that looks like here.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Anchor {
    /// The call is a method, and happens where its object is.
    Receiver(String),
    /// The call is a method of an object the C ABI passes as an ordinary
    /// argument. The argument is the receiver and not a parameter.
    Argument(usize),
    /// The call is a C function, made in the arena of one of the objects it
    /// is handed.
    Named(String),
    /// The same, for a call handed a list of objects.
    List(String),
    /// The call writes a timeline out and is handed no object to say which.
    /// It takes one, and writing starts there.
    Root,
    /// The call builds something, so it makes an arena to build it in.
    Fresh,
    /// The call touches no arena at all.
    None,
}

/// The index of the parameter a call is anchored on.
fn anchor_index(function: &Function) -> Result<usize, String> {
    function
        .params
        .iter()
        .position(|param| param.anchor)
        .ok_or_else(|| {
            format!(
                "`{}` is about one of the objects it is handed, and the description does not \
                 say which",
                function.symbol
            )
        })
}

/// One call, being written into one place.
struct Site<'a> {
    api: &'a Api,
    function: &'a Function,
    /// Where the arena the call is made in comes from.
    anchor: Anchor,
    /// The expression for the handle or value the call is about.
    receiver: String,
    /// What the call hands back where it gives up before asking the library:
    /// `nil`, `NO`, or nothing at all for a call that cannot fail.
    failure: String,
    /// The class a constructor builds, since it says so in its declaration
    /// rather than answering a bare object.
    builds: Option<String>,
}

impl<'a> Backend<'a> {
    /// Works out how a call is spelled, without writing its body.
    fn plan(&self, group: &Group, function: &Function) -> Result<Plan, String> {
        let mut base = base_name(self.api, group, function);
        let owner = self.owner_of(group, function);
        let is_function = owner == "function";
        let is_class = owner == "Document+class" || owner.starts_with("class:");

        let anchored = function.params.iter().position(|param| param.anchor);
        let mut inputs: Vec<(String, String)> = Vec::new();
        let mut results: Vec<(String, Type)> = Vec::new();
        for (index, param) in function.params.iter().enumerate() {
            // The object a rehomed call is anchored on became its receiver,
            // so it is not a parameter any more.
            if rehomed(&function.symbol).is_some() && anchored == Some(index) {
                continue;
            }
            match param.role {
                ParamRole::Input | ParamRole::Bytes => {
                    inputs.push(self.declared(param, function)?);
                }
                // Writing a whole timeline is handed no object to say which,
                // so it takes one and starts there.
                ParamRole::DocumentIn | ParamRole::DocumentMut
                    if matches!(group.receiver, Receiver::Document)
                        && rehomed(&function.symbol).is_none()
                        && anchored.is_none()
                        && function.role != Role::Constructor
                        && function.role != Role::Free =>
                {
                    inputs.push((format!("{ROOT} *"), "root".to_string()));
                }
                // A value's calls are C functions, so the value they are
                // about is an argument like any other rather than something
                // already in scope.
                ParamRole::Receiver if matches!(group.receiver, Receiver::Value(_)) => {
                    inputs.push(self.declared(param, function)?);
                }
                ParamRole::Output | ParamRole::OutputList => {
                    let bare = param.name.strip_prefix("out_").unwrap_or(&param.name);
                    results.push((names::camel(bare), param.ty.clone()));
                }
                _ => {}
            }
        }
        // A value the C function returns directly is a result like any other.
        match &function.result {
            CResult::Value(ty) => results.push(("value".to_string(), ty.clone())),
            CResult::StaticText => results.push(("value".to_string(), Type::Text)),
            CResult::Void | CResult::Status => {}
        }

        if matches!(group.receiver, Receiver::Node(_))
            && function.role == Role::Constructor
            && takes_a_document(function)
        {
            if let Some((_, first)) = inputs.first() {
                base = format!("{base}With{}", names::pascal(first));
            }
        }

        let fallible = function.fallible();
        // A call that answers with an object can say "nothing" by answering
        // nil, so the object is what it hands back. Anything else — a number,
        // a struct, or more than one thing — travels through an out-parameter,
        // which is how Cocoa answers with something that is not an object.
        let answered = fallible && results.len() == 1 && is_object(&results[0].1);

        let result = if fallible {
            if answered {
                // A constructor knows the class it built, so it says so
                // rather than making the caller ask.
                let builds = match (&group.receiver, function.role) {
                    (Receiver::Node(schema), Role::Constructor)
                        if takes_a_document(function) && results[0].1 == Type::Node =>
                    {
                        Some(class_name(schema))
                    }
                    _ => None,
                };
                // A class method that answers `instancetype` would lie to a
                // subclass that inherited it, so a constructor says the class
                // it really builds.
                let spelled =
                    builds.map_or_else(|| objc_type(&results[0].1), |class| format!("{class} *"));
                if is_function {
                    format!("{spelled}_Nullable")
                } else {
                    format!("nullable {spelled}")
                }
            } else {
                "BOOL".to_string()
            }
        } else if results.is_empty() {
            "void".to_string()
        } else if results.len() == 1 {
            objc_type(&results[0].1)
        } else {
            return Err(format!(
                "`{}` cannot fail and answers with {} things, which this does not write",
                function.symbol,
                results.len()
            ));
        };

        let mut outs: Vec<Arg> = Vec::new();
        if fallible && !answered {
            for (name, ty) in &results {
                outs.push(Arg {
                    label: name.clone(),
                    ty: out_type(ty),
                    name: format!("out{}", names::pascal(name)),
                });
            }
        }
        let inputs: Vec<Arg> = inputs
            .into_iter()
            .map(|(ty, name)| Arg {
                label: name.clone(),
                ty,
                name,
            })
            .collect();

        // A method names what it hands back before what it is given, and says
        // `get` so that the first colon reads, as `-getResourceValue:forKey:`
        // does. A C function reads the other way round, with its answers at
        // the end, because that is what C does.
        let mut args: Vec<Arg> = Vec::new();
        if is_function {
            args.extend(inputs);
            args.extend(outs);
        } else {
            if !outs.is_empty() && !already_gets(&base) {
                base = format!("get{}", names::pascal(&base));
            }
            args.extend(outs);
            args.extend(inputs);
        }
        if fallible {
            args.push(Arg {
                label: "error".to_string(),
                ty: "NSError **".to_string(),
                name: "error".to_string(),
            });
        }

        Ok(Plan {
            base,
            args,
            result,
            is_function,
            is_class,
        })
    }

    /// How an argument the caller supplies is declared: its type, and its
    /// name.
    fn declared(&self, param: &Param, function: &Function) -> Result<(String, String), String> {
        let name = parameter_name(&param.name);
        let ty = match (&param.ty, param.optional) {
            (Type::Text, true) => "NSString *_Nullable".to_string(),
            (Type::Text, false) => "NSString *".to_string(),
            (Type::Bytes, _) => "NSData *".to_string(),
            (Type::Node, true) => format!("{ROOT} *_Nullable"),
            (Type::Node, false) => format!("{ROOT} *"),
            (Type::Struct(what), true) => format!("const {} *_Nullable", value_name(what)),
            (Type::Struct(what), false) => value_name(what),
            (Type::List(element), _) => format!("NSArray<{}> *", element_type(element)),
            (Type::Document, _) => {
                return Err(format!(
                    "`{}` takes a document as an argument, which this does not write",
                    function.symbol
                ));
            }
            (ty, _) => objc_type(ty),
        };
        let _ = self;
        Ok((ty, name))
    }
}

/// Whether a name already reads as a getter, so that saying `get` again
/// would stutter: `get_color` is spelled `getColor` before this is asked.
fn already_gets(base: &str) -> bool {
    base.strip_prefix("get")
        .is_some_and(|rest| rest.starts_with(|character: char| character.is_ascii_uppercase()))
}

/// The value structs, in an order where each is declared after the structs it
/// holds.
///
/// C reads a header top to bottom, so an `OTIOBox2d` holding two `OTIOV2d`s
/// has to come after them. Nothing here is recursive, so one pass that keeps
/// taking whatever is ready is enough.
fn ordered(api: &Api) -> Vec<&Struct> {
    let wanted: Vec<&Struct> = api
        .structs
        .iter()
        .filter(|item| !item.plumbing && item.name != "OtioNode")
        .collect();
    let mut placed: Vec<&Struct> = Vec::new();
    let mut waiting = wanted;
    while !waiting.is_empty() {
        let ready = |item: &Struct| {
            item.fields.iter().all(|field| match &field.ty {
                Type::Struct(inside) => placed.iter().any(|done| done.name == *inside),
                _ => true,
            })
        };
        let taken: Vec<&Struct> = waiting.iter().copied().filter(|item| ready(item)).collect();
        if taken.is_empty() {
            // Nothing in this interface holds itself, so this cannot happen;
            // if it ever does, the rest is written in the order it came in
            // rather than the loop never ending.
            placed.extend(waiting);
            break;
        }
        waiting.retain(|item| !taken.iter().any(|done| done.name == item.name));
        placed.extend(taken);
    }
    placed
}

/// The type an out-parameter has.
fn out_type(ty: &Type) -> String {
    match ty {
        Type::Text => "NSString *_Nullable *_Nullable".to_string(),
        Type::Bytes => "NSData *_Nullable *_Nullable".to_string(),
        Type::Node | Type::Document => format!("{ROOT} *_Nullable *_Nullable"),
        Type::List(element) => format!("NSArray<{}> *_Nullable *_Nullable", element_type(element)),
        other => format!("{} *", objc_type(other)),
    }
}

