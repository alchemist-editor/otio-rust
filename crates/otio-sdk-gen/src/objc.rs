//! The Objective-C SDK.
//!
//! Objective-C is the sixth target and the third with no upstream
//! OpenTimelineIO binding to copy. What things are *called* still follows
//! upstream — the schema names, the member names, the bare-noun getter and
//! the `set` prefix — and what the binding *is* follows Cocoa, because
//! Objective-C has one house style and a library that ignores it is a library
//! nobody can read:
//!
//! - **A class per schema, deriving as the schemas derive**, prefixed `OTIO`
//!   because the language has no namespaces. `isKindOfClass:` asks what an
//!   object really is, and every handle the library hands back is built as
//!   the class its schema names.
//! - **Values are C structs**, as `NSRange` and `CGRect` are, with
//!   `OTIOMakeRationalTime` to build one and C functions to compute with one.
//!   A value type with no object identity is a struct in this language, and
//!   what you do to it is a function.
//! - **Failure is an `NSError` out-parameter**, in the `OTIOErrorDomain`,
//!   whose code is the `OTIOStatus`. A call that can fail answers `NO` or
//!   `nil` and fills it in, which is what every Cocoa call that can fail
//!   does.
//! - **`OTIO_STATUS_NO_VALUE` is an error you can tell apart**, as it is in
//!   the Go SDK, rather than an optional: a method answering a struct has no
//!   `nil` to answer with, so "there is nothing here" has to travel the same
//!   way in both cases or the SDK would say it two ways.
//! - **ARC, and also manual retain and release.** Everything the SDK owns is
//!   confined to two places in the runtime, so the same sources build under
//!   ARC on Apple's runtime and under manual retain/release on GNUstep's.
//!
//! Every deliberate departure is written down in
//! `docs/adr/0003-sdk-generation.md`.

