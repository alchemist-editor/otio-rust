impl Backend<'_> {
    /// Rewrites a doc comment into this SDK's shape.
    fn doc(
        &self,
        docs: &Docs,
        notes: &[String],
        symbol: Option<&str>,
        indent: &str,
    ) -> Vec<String> {
        let mut paragraphs: Vec<String> = Vec::new();
        let summary = self.rewrite(&docs.summary);
        if summary.is_empty() {
            if symbol.is_some() {
                paragraphs.push("Wraps the interface's call of the same name.".to_string());
            }
        } else {
            paragraphs.push(summary);
        }
        for paragraph in &docs.body {
            paragraphs.push(self.rewrite(paragraph));
        }
        paragraphs.extend(notes.iter().cloned());
        for paragraph in &mut paragraphs {
            *paragraph = nil_for_null(paragraph);
        }
        if let Some(symbol) = symbol {
            paragraphs.push(format!("C: `{symbol}`"));
        }

        let mut lines = Vec::new();
        for (index, paragraph) in paragraphs.iter().enumerate() {
            if index > 0 {
                lines.push(format!("{indent}///"));
            }
            for line in wrap(paragraph, 70) {
                if line.is_empty() {
                    lines.push(format!("{indent}///"));
                } else {
                    lines.push(format!("{indent}/// {line}"));
                }
            }
        }
        lines
    }

    /// Replaces the interface's own names with this SDK's.
    fn rewrite(&self, text: &str) -> String {
        let mut out = text.to_string();
        let mut symbols: Vec<&String> = self.spellings.keys().collect();
        symbols.sort_by_key(|symbol| std::cmp::Reverse(symbol.len()));
        for symbol in symbols {
            if !out.contains(symbol.as_str()) {
                continue;
            }
            let spelled = &self.spellings[symbol];
            out = out.replace(&format!("`{symbol}`"), &format!("`{spelled}`"));
            out = out.replace(symbol.as_str(), spelled);
        }
        out.replace("[`", "`").replace("`]", "`")
    }
}

/// Says `nil` where the interface's prose says `null`.
fn nil_for_null(text: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    for word in text.split(' ') {
        let trimmed = word.trim_end_matches(|character: char| !character.is_alphanumeric());
        if trimmed.eq_ignore_ascii_case("null") {
            words.push(format!("nil{}", &word[trimmed.len()..]));
        } else {
            words.push(word.to_string());
        }
    }
    words.join(" ")
}

/// Wraps a paragraph at a width, on spaces.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines = Vec::new();
    let mut current = String::new();
    for word in text.split_whitespace() {
        if !current.is_empty() && current.len() + 1 + word.len() > width {
            lines.push(std::mem::take(&mut current));
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }
    if !current.is_empty() {
        lines.push(current);
    }
    if lines.is_empty() {
        lines.push(String::new());
    }
    lines
}

/// Whether a line of C uses `name` as an identifier, rather than merely
/// containing those letters — `at` is in `atHandle` and in `OTIOFormat`.
fn mentions(line: &str, name: &str) -> bool {
    line.split(|character: char| !character.is_alphanumeric() && character != '_')
        .any(|word| word == name)
}

impl Site<'_> {
    /// The expression naming the arena an object the call hands back belongs
    /// to. A call made in no arena hands back objects of none.
    fn holder(&self) -> &'static str {
        if self.anchor == Anchor::None {
            "nil"
        } else {
            "at"
        }
    }

    /// The lines that find the arena this call is made in.
    ///
    /// `atHandle` is only declared where the call has a receiver to put in
    /// it, and the arena is only *named* where the body goes on to use it —
    /// a call reading its answer straight out of the handle does not. The
    /// sources are built with `-Werror`, so either local left unused fails
    /// them.
    fn reach(&self, needs_arena: bool) -> Vec<String> {
        let failure = &self.failure;
        let hold = |what: String| {
            if needs_arena {
                format!("OTIOArena *at = {what};")
            } else {
                format!("(void){what};")
            }
        };
        let located = |object: &str| {
            vec![
                "OtioNode atHandle;".to_string(),
                hold(format!("OTIOLocate({object}, &atHandle)")),
            ]
        };
        let made = |what: String| {
            vec![
                format!("OTIOArena *at = {what};"),
                format!("if (at == nil) {{ return {failure}; }}"),
            ]
        };
        match &self.anchor {
            Anchor::None => Vec::new(),
            Anchor::Receiver(object) => located(object),
            // The argument became the receiver, so it is `self` by the time
            // the method is written.
            Anchor::Argument(_) => located("self"),
            Anchor::Named(name) => vec![hold(format!("OTIOLocate({name}, NULL)"))],
            Anchor::List(name) => made(format!("OTIOLocateAll({name}, error)")),
            Anchor::Root => made("OTIORootedAt(root, error)".to_string()),
            Anchor::Fresh => made("OTIOFreshArena(error)".to_string()),
        }
    }

    /// Writes the body of one call.
    #[allow(clippy::too_many_lines)]
    fn render(&self) -> Result<Vec<String>, String> {
        let function = self.function;
        let fallible = function.fallible();
        let mut args: Vec<String> = Vec::new();
        let mut pre: Vec<String> = Vec::new();
        // Each is the name of the out-parameter, the type it holds, and how
        // the answer is read out of it.
        let mut results: Vec<(String, Type, String)> = Vec::new();
        let mut lists: Vec<(String, String, Type)> = Vec::new();
        let mut length: Option<String> = None;
        // The plain question a call that cannot fail asks instead of
        // reporting, since it has no error to report with.
        let mut guarded: Vec<String> = Vec::new();
        // The locals already declared, so an out-parameter named after the
        // same thing as an input does not declare the name twice.
        // `otio_algorithm_track_trimmed_to_range` takes a track and answers
        // one; only an object argument declares a local, so a value argument
        // of the same name is no clash.
        let mut taken: Vec<String> = Vec::new();

        for (index, param) in function.params.iter().enumerate() {
            let local = format!("c{}", names::pascal(&param.name));
            // The object the call is anchored on is the call's receiver here,
            // wherever the C ABI happens to put it.
            if self.anchor == Anchor::Argument(index) {
                args.push(self.receiver.clone());
                continue;
            }
            match param.role {
                ParamRole::DocumentIn | ParamRole::DocumentMut => {
                    args.push("at.pointer".to_string())
                }
                ParamRole::DocumentTaken => {
                    return Err(format!(
                        "`{}` consumes a document, so it cannot be emitted mechanically; write \
                         it and write what a caller needs by hand",
                        function.symbol
                    ));
                }
                ParamRole::Receiver => args.push(self.receiver.clone()),
                ParamRole::Length => {
                    let taken = length.take().ok_or_else(|| {
                        format!(
                            "`{}` states a length with nothing before it",
                            function.symbol
                        )
                    })?;
                    args.push(taken);
                }
                ParamRole::ListCapacity => args.push("{capacity}".to_string()),
                ParamRole::OutputCount => args.push("&count".to_string()),
                ParamRole::Error => args.push("TODO_OUT_ERROR".to_string()),
                ParamRole::OutputList => {
                    let Type::List(element) = &param.ty else {
                        return Err(format!("`{}` has a list that is not one", function.symbol));
                    };
                    let bare = param.name.strip_prefix("out_").unwrap_or(&param.name);
                    args.push(format!("{{list{}}}", lists.len()));
                    lists.push((
                        format!("buffer{}", lists.len()),
                        names::camel(bare),
                        (**element).clone(),
                    ));
                }
                ParamRole::Output => {
                    let bare = param.name.strip_prefix("out_").unwrap_or(&param.name);
                    let mut out = format!("c{}", names::pascal(bare));
                    while taken.contains(&out) {
                        out.push_str("Out");
                    }
                    taken.push(out.clone());
                    pre.push(format!("{} {out};", c_type(&param.ty)));
                    args.push(format!("&{out}"));
                    let made = from_c(&param.ty, &out, self.holder());
                    // A constructor says the class it built, so what it hands
                    // back is spelled as that rather than as a bare object.
                    let read = match (&param.ty, self.builds.as_deref()) {
                        (Type::Node, Some(class)) => format!("({class} *){made}"),
                        _ => made,
                    };
                    results.push((names::camel(bare), param.ty.clone(), read));
                }
                ParamRole::Bytes => {
                    let name = parameter_name(&param.name);
                    args.push(format!("(const uint8_t *){name}.bytes"));
                    length = Some(format!("(size_t){name}.length"));
                }
                ParamRole::Input => {
                    let before = pre.len();
                    self.input(
                        param,
                        &local,
                        &mut pre,
                        &mut args,
                        &mut length,
                        &mut guarded,
                    )?;
                    if pre[before..].iter().any(|line| mentions(line, &local)) {
                        taken.push(local);
                    }
                }
            }
        }

        match &function.result {
            CResult::Value(ty) => {
                results.push((
                    "value".to_string(),
                    ty.clone(),
                    from_c(ty, "cReturned", self.holder()),
                ));
            }
            CResult::StaticText => {
                results.push((
                    "value".to_string(),
                    Type::Text,
                    "OTIOStringFromC(cReturned)".to_string(),
                ));
            }
            CResult::Void | CResult::Status => {}
        }
        for (buffer, label, element) in &lists {
            results.push((
                label.clone(),
                Type::List(Box::new(element.clone())),
                format!("{buffer}Out"),
            ));
        }

        let answered = results.len() == 1 && is_object(&results[0].1) && fallible;
        let failure = self.failure.as_str();

        let mut lines = Lines::new();
        // A call that cannot fail has no error to hand back, so it asks the
        // plain question and answers no rather than reporting.
        for asked in &guarded {
            let zero = match &function.result {
                CResult::Value(ty) => objc_zero(ty)?,
                other => {
                    return Err(format!(
                        "`{}` takes an object and returns `{other:?}`, so it has no way to say \
                         the object came from another timeline",
                        function.symbol
                    ));
                }
            };
            lines.open(&format!("if (!{asked})"));
            lines.push(&format!("return {zero};"));
            lines.close();
        }
        for line in &pre {
            lines.push(line);
        }
        self.invoke(&mut lines, &args, &lists, failure)?;
        for (buffer, _, element) in &lists {
            lines.push(&format!(
                "NSMutableArray *{buffer}Out = [NSMutableArray arrayWithCapacity:count];"
            ));
            lines.open("for (size_t slot = 0; slot < count; slot++)");
            lines.push(&format!(
                "[{buffer}Out addObject:{}];",
                box_element(element, &format!("{buffer}[slot]"), self.holder())
            ));
            lines.close();
            lines.push(&format!("free({buffer});"));
        }

        if !fallible {
            match results.len() {
                0 => {}
                _ => lines.push(&format!("return {};", results[0].2)),
            }
            return Ok(self.reached(lines.out));
        }
        if answered {
            lines.push(&format!("return {};", results[0].2));
            return Ok(self.reached(lines.out));
        }
        for (name, _, read) in &results {
            let out = format!("out{}", names::pascal(name));
            lines.open(&format!("if ({out})"));
            lines.push(&format!("*{out} = {read};"));
            lines.close();
        }
        lines.push("return YES;");
        Ok(self.reached(lines.out))
    }

    /// Puts the lines that find the arena in front of the body that uses it,
    /// naming the arena only if the body mentions it.
    fn reached(&self, body: Vec<String>) -> Vec<String> {
        let needs_arena = body.iter().any(|line| mentions(line, "at"));
        let mut out = self.reach(needs_arena);
        out.extend(body);
        out
    }

    /// Writes an argument the caller supplies.
    fn input(
        &self,
        param: &Param,
        local: &str,
        pre: &mut Vec<String>,
        args: &mut Vec<String>,
        length: &mut Option<String>,
        guarded: &mut Vec<String>,
    ) -> Result<(), String> {
        let name = parameter_name(&param.name);
        let failure = &self.failure;
        // What the call does with an object it is handed is the description's
        // answer and not this backend's: the same question decides the same
        // way in every binding that hides the document. Getting it backwards
        // is silent — moving an object the call was only going to name
        // swallows the timeline it came from.
        let bring = || match param.placement {
            Some(Placement::Adopt) => Ok("Adopt"),
            Some(Placement::Require) => Ok("RequireHere"),
            None => Err(format!(
                "`{}` takes `{}` as an object and the description does not say what it does \
                 with it",
                self.function.symbol, param.name
            )),
        };
        // A handle is an index into one arena, and two arenas issue the same
        // indices, so an object from elsewhere would resolve to an unrelated
        // object here rather than failing. Only the wrapper knows where it
        // came from, so every object a caller supplies is checked. A call that
        // cannot fail has no error to report with, so it is asked the plain
        // question instead.
        if self.anchor != Anchor::None && !self.function.fallible() {
            match &param.ty {
                Type::Node => guarded.push(format!("OTIOHere(at, {name})")),
                Type::List(inner) if **inner == Type::Node => {
                    guarded.push(format!("OTIOHereAll(at, {name})"));
                }
                _ => {}
            }
        }
        if self.anchor != Anchor::None {
            // A call that cannot fail has already asked OTIOHere and answered
            // no where the object came from elsewhere, so by now there is
            // nothing left to refuse and nothing to report with.
            let plain = !self.function.fallible();
            if plain && param.placement == Some(Placement::Adopt) {
                return Err(format!(
                    "`{}` places `{}` and cannot fail, so it has no way to report a move it \
                     could not make",
                    self.function.symbol, param.name
                ));
            }
            match &param.ty {
                Type::Node => {
                    if plain {
                        pre.push(format!("OtioNode {local} = OTIOHandleOf({name});"));
                    } else {
                        pre.push(format!("OtioNode {local};"));
                        pre.push(format!(
                            "if (!OTIO{}(at, {name}, &{local}, error)) {{ return {failure}; }}",
                            bring()?
                        ));
                    }
                    args.push(local.to_string());
                    return Ok(());
                }
                Type::List(inner) if **inner == Type::Node => {
                    if plain {
                        pre.push(format!("OtioNode *{local} = OTIOHandlesOf({name});"));
                    } else {
                        pre.push(format!(
                            "OtioNode *{local} = OTIO{}All(at, {name}, error);",
                            bring()?
                        ));
                    }
                    pre.push(format!("if ({local} == NULL) {{ return {failure}; }}"));
                    args.push(local.to_string());
                    *length = Some(format!("(size_t){name}.count"));
                    return Ok(());
                }
                _ => {}
            }
        }
        match (&param.ty, param.optional) {
            (Type::Text, _) => args.push(format!("OTIOCString({name})")),
            (Type::Node, true) => {
                pre.push(format!(
                    "OtioNode {local} = {name} ? {name}.handle : otio_node_none();"
                ));
                args.push(local.to_string());
            }
            (Type::Node, false) => args.push(format!("{name}.handle")),
            (Type::Struct(what), true) => {
                pre.push(format!("{} {local};", what));
                pre.push(format!("const {} *{local}Pointer = NULL;", what));
                pre.push(format!("if ({name}) {{"));
                pre.push(format!("{TAB}{local} = {}ToC(*{name});", value_name(what)));
                pre.push(format!("{TAB}{local}Pointer = &{local};"));
                pre.push("}".to_string());
                args.push(format!("{local}Pointer"));
            }
            (Type::Struct(_), false) => args.push(to_c(&param.ty, &name)),
            (Type::List(element), _) => {
                let c = c_type(element);
                pre.push(format!(
                    "{c} *{local} = ({c} *)calloc({name}.count ? {name}.count : 1, sizeof({c}));"
                ));
                pre.push(format!(
                    "for (NSUInteger slot = 0; slot < {name}.count; slot++) {{"
                ));
                let fetched = format!("(({})[{name} objectAtIndex:slot])", element_type(element));
                pre.push(format!(
                    "{TAB}{local}[slot] = {};",
                    unbox_element(element, &fetched)
                ));
                pre.push("}".to_string());
                args.push(local.to_string());
                *length = Some(format!("(size_t){name}.count"));
            }
            (Type::Bytes | Type::Document, _) => {
                return Err(format!(
                    "`{}` takes a `{}` as an argument, which this does not write",
                    self.function.symbol,
                    param.ty.c_name()
                ));
            }
            (ty, _) => args.push(to_c(ty, &name)),
        }
        Ok(())
    }

    /// Writes the call itself, and the two-pass dance where it answers with a
    /// list.
    fn invoke(
        &self,
        lines: &mut Lines,
        args: &[String],
        lists: &[(String, String, Type)],
        failure: &str,
    ) -> Result<(), String> {
        let symbol = &self.function.symbol;

        if lists.is_empty() {
            let call = format!("{symbol}({})", args.join(", "));
            match &self.function.result {
                CResult::Status => {
                    lines.push(&format!("OtioStatus status = {call};"));
                    lines.open("if (!OTIOCheck(status, error))");
                    lines.push(&format!("return {failure};"));
                    lines.close();
                }
                CResult::Void => lines.push(&format!("{call};")),
                CResult::Value(ty) => {
                    lines.push(&format!("{} cReturned = {call};", c_type(ty)));
                }
                CResult::StaticText => {
                    lines.push(&format!("const char *cReturned = {call};"));
                }
            }
            return Ok(());
        }

        lines.push("size_t count = 0;");
        let room = if let Some(sizer) = self.function.sized_by.as_deref() {
            // This call empties what it reports, so it cannot be asked twice.
            // Another call says how long the answer will be, and this one is
            // made once into a buffer that size.
            lines.push(&format!(
                "// {symbol} answers and empties in one go, so the buffer is sized first."
            ));
            lines.push("size_t room = 0;");
            lines.push(&format!(
                "OtioStatus sizing = {};",
                self.sizing_call(sizer)?
            ));
            lines.open("if (!OTIOCheck(sizing, error))");
            lines.push(&format!("return {failure};"));
            lines.close();
            "room".to_string()
        } else {
            let sized: Vec<String> = args
                .iter()
                .map(|argument| {
                    if argument.starts_with("{list") {
                        "NULL".to_string()
                    } else if argument == "{capacity}" {
                        "0".to_string()
                    } else {
                        argument.clone()
                    }
                })
                .collect();
            lines.push(&format!(
                "OtioStatus sizing = {symbol}({});",
                sized.join(", ")
            ));
            lines.open("if (!OTIOCheck(sizing, error))");
            lines.push(&format!("return {failure};"));
            lines.close();
            "count".to_string()
        };

        for (buffer, _, element) in lists {
            let c = c_type(element);
            lines.push(&format!(
                "{c} *{buffer} = ({c} *)calloc({room} ? {room} : 1, sizeof({c}));"
            ));
        }
        let filled: Vec<String> = args
            .iter()
            .map(|argument| {
                if let Some(index) = argument
                    .strip_prefix("{list")
                    .and_then(|rest| rest.strip_suffix('}'))
                    .and_then(|digits| digits.parse::<usize>().ok())
                {
                    return lists[index].0.clone();
                }
                if argument == "{capacity}" {
                    return room.clone();
                }
                argument.clone()
            })
            .collect();
        lines.push(&format!(
            "OtioStatus status = {symbol}({});",
            filled.join(", ")
        ));
        lines.open("if (!OTIOCheck(status, error))");
        for (buffer, _, _) in lists {
            lines.push(&format!("free({buffer});"));
        }
        lines.push(&format!("return {failure};"));
        lines.close();
        if room != "count" {
            // The size came from another call, so this is what keeps a
            // mistaken count a short array rather than a walk off the end of
            // the buffer.
            lines.open(&format!("if (count > {room})"));
            lines.push(&format!("count = {room};"));
            lines.close();
        }
        Ok(())
    }

    /// Writes the call that says how long a consuming list call's answer will
    /// be.
    fn sizing_call(&self, sizer: &str) -> Result<String, String> {
        let function = self
            .api
            .functions()
            .find(|candidate| candidate.symbol == sizer)
            .ok_or_else(|| format!("`{sizer}` is not a call this library has"))?;
        let mut args = Vec::new();
        for param in &function.params {
            match param.role {
                ParamRole::DocumentIn | ParamRole::DocumentMut => {
                    args.push("at.pointer".to_string());
                }
                ParamRole::Receiver => args.push(self.receiver.clone()),
                ParamRole::Output => args.push("&room".to_string()),
                _ => {
                    return Err(format!(
                        "`{sizer}` takes a `{}`, so it cannot size another call's answer",
                        param.name
                    ));
                }
            }
        }
        Ok(format!("{sizer}({})", args.join(", ")))
    }
}

impl Backend<'_> {
    /// Writes one call, into a header and into an implementation.
    fn emit_function(
        &self,
        header: &mut String,
        source: &mut String,
        group: &Group,
        function: &Function,
    ) -> Result<(), String> {
        let plan = self.plan(group, function)?;
        // What the call hands back where it gives up before asking the
        // library. A call that answers with an object says nil; one that
        // reports through an error says NO; one that cannot fail never gives
        // up, because there is nothing it could say.
        let failure = if !function.fallible() {
            String::new()
        } else if plan.result == "BOOL" {
            "NO".to_string()
        } else {
            "nil".to_string()
        };

        // Where the object the call is about, and so the arena it is made in,
        // comes from. `at` is that arena, and `atHandle` the object's handle
        // in it.
        let mut anchor = Anchor::None;
        let mut builds: Option<String> = None;
        let receiver = match (&group.receiver, function.role) {
            (Receiver::None, _) => String::new(),
            (Receiver::Value(what), _) => {
                let first = function
                    .params
                    .iter()
                    .find(|param| param.role == ParamRole::Receiver);
                match first {
                    Some(param) if self.api.enumeration(what).is_some() => {
                        format!("({what}){}", parameter_name(&param.name))
                    }
                    Some(param) => {
                        format!("{}ToC({})", value_name(what), parameter_name(&param.name))
                    }
                    None => String::new(),
                }
            }
            (Receiver::Document, Role::Constructor | Role::Free) => String::new(),
            (Receiver::Document, _) if !takes_a_document(function) => String::new(),
            (Receiver::Document, _) => {
                match rehomed(&function.symbol) {
                    // A call the C ABI hangs off the document is about one of
                    // the objects it is handed, so here it hangs off that.
                    Some(_) => anchor = Anchor::Argument(anchor_index(function)?),
                    None => match function.params.iter().position(|param| param.anchor) {
                        Some(index) => {
                            let named = parameter_name(&function.params[index].name);
                            anchor = if matches!(function.params[index].ty, Type::List(_)) {
                                Anchor::List(named)
                            } else {
                                Anchor::Named(named)
                            };
                        }
                        // Writing is the one thing left that wants a whole
                        // timeline and is handed no object to find it by, so
                        // it takes one and starts there.
                        None => anchor = Anchor::Root,
                    },
                }
                "atHandle".to_string()
            }
            // An object is built in an arena of its own, and moves into a
            // timeline's when it is put in one. That is what lets a clip exist
            // before the track it is going to sit on.
            (Receiver::Node(schema), Role::Constructor) if takes_a_document(function) => {
                anchor = Anchor::Fresh;
                builds = Some(class_name(schema));
                String::new()
            }
            (Receiver::Node(_), Role::Constructor) => String::new(),
            (Receiver::Node(_), _) if group.view => {
                anchor = Anchor::Receiver("self.object".to_string());
                "atHandle".to_string()
            }
            (Receiver::Node(_), _) => {
                anchor = Anchor::Receiver("self".to_string());
                "atHandle".to_string()
            }
        };

        let site = Site {
            api: self.api,
            function,
            anchor,
            receiver,
            failure,
            builds,
        };
        let body = site.render()?;

        let said = function.docs.summary.to_lowercase().contains("null")
            || function
                .docs
                .body
                .iter()
                .any(|paragraph| paragraph.to_lowercase().contains("null"));
        let mut notes = Vec::new();
        if !said {
            for param in function.inputs() {
                if param.optional {
                    notes.push(format!("A nil {} means none.", parameter_name(&param.name)));
                }
            }
        }
        let says_no_value = std::iter::once(&function.docs.summary)
            .chain(function.docs.body.iter())
            .any(|paragraph| paragraph.contains("NO_VALUE"));
        if function.optional && !says_no_value {
            notes.push(
                "Where there is nothing to report this fails with OTIOStatusNoValue, which \
                 OTIOIsNoValue tells apart from a real failure."
                    .to_string(),
            );
        }
        for line in self.doc(&function.docs, &notes, Some(&function.symbol), "") {
            let _ = writeln!(header, "{line}");
        }
        let declaration = plan.declaration();
        let _ = writeln!(header, "{declaration};\n");
        let _ = writeln!(source, "{declaration} {{");
        for line in &body {
            if line.is_empty() {
                source.push('\n');
            } else {
                let _ = writeln!(source, "{TAB}{line}");
            }
        }
        let _ = writeln!(source, "}}\n");
        Ok(())
    }

    /// Writes the calls of one group that a filter accepts.
    fn emit_some(
        &self,
        header: &mut String,
        source: &mut String,
        group: &Group,
        wanted: impl Fn(&Function) -> bool,
    ) -> Result<(), String> {
        for function in &group.functions {
            if self.skipped(function) || !wanted(function) {
                continue;
            }
            self.emit_function(header, source, group, function)?;
        }
        Ok(())
    }
}

impl Backend<'_> {
    /// The enums, as `NS_ENUM`s with the C interface's own values.
    fn enums_header(&self) -> String {
        let mut out =
            String::from("#import <Foundation/Foundation.h>\n\nNS_ASSUME_NONNULL_BEGIN\n\n");
        for item in &self.api.enums {
            self.emit_enum_header(&mut out, item);
        }
        out.push_str("NS_ASSUME_NONNULL_END\n");
        out
    }

    fn emit_enum_header(&self, out: &mut String, item: &Enum) {
        let name = enum_name(&item.name);
        for line in self.doc(&item.docs, &[], None, "") {
            let _ = writeln!(out, "{line}");
        }
        let _ = writeln!(out, "typedef NS_ENUM(int32_t, {name}) {{");
        for variant in &item.variants {
            for line in self.doc(&variant.docs, &[], None, TAB) {
                let _ = writeln!(out, "{line}");
            }
            let _ = writeln!(
                out,
                "{TAB}{} = {},",
                variant_name(&item.name, &variant.name),
                variant.value
            );
        }
        let _ = writeln!(out, "}};\n");
        let _ = writeln!(out, "/// The name the C interface spells one of these by.");
        let _ = writeln!(out, "NSString *{name}CName({name} value);\n");
    }

    fn enums_source(&self) -> String {
        let mut out = String::from("#import \"OpenTimelineIO/OTIOEnums.h\"\n\n");
        for item in &self.api.enums {
            let name = enum_name(&item.name);
            let _ = writeln!(out, "NSString *{name}CName({name} value) {{");
            let _ = writeln!(out, "{TAB}switch (value) {{");
            for variant in &item.variants {
                let _ = writeln!(
                    out,
                    "{TAB}case {}: return @\"{}\";",
                    variant_name(&item.name, &variant.name),
                    variant.c_name
                );
            }
            let _ = writeln!(out, "{TAB}}}");
            let _ = writeln!(
                out,
                "{TAB}return [NSString stringWithFormat:@\"{name}(%d)\", (int)value];"
            );
            let _ = writeln!(out, "}}\n");
        }
        out
    }

    /// The value structs and their conversions.
    fn values(&self) -> (String, String) {
        let mut header = String::from(
            "#import <Foundation/Foundation.h>\n\n#import \"OpenTimelineIO/OTIOEnums.h\"\n\n\
             NS_ASSUME_NONNULL_BEGIN\n\n",
        );
        let mut source = String::from(
            "#import \"OpenTimelineIO/OTIOValues.h\"\n\n#import <otio.h>\n\n#import \"OTIOPrivate.h\"\n\n",
        );
        for item in ordered(self.api) {
            self.emit_value(&mut header, &mut source, item);
        }
        header.push_str("NS_ASSUME_NONNULL_END\n");
        (header, source)
    }

    fn emit_value(&self, header: &mut String, source: &mut String, item: &Struct) {
        let name = value_name(&item.name);
        for line in self.doc(&item.docs, &[], None, "") {
            let _ = writeln!(header, "{line}");
        }
        let _ = writeln!(header, "typedef struct {{");
        for field in &item.fields {
            for line in self.doc(&field.docs, &[], None, TAB) {
                let _ = writeln!(header, "{line}");
            }
            let spelled = match &field.ty {
                // A string in a C struct cannot be owned by it, so it is
                // borrowed for the length of the call that reads it.
                Type::Text => "NSString *__unsafe_unretained _Nullable".to_string(),
                ty => objc_type(ty),
            };
            let _ = writeln!(header, "{TAB}{spelled} {};", names::camel(&field.name));
        }
        let _ = writeln!(header, "}} {name};\n");

        let arguments: Vec<String> = item
            .fields
            .iter()
            .map(|field| {
                let spelled = match &field.ty {
                    Type::Text => "NSString *_Nullable".to_string(),
                    ty => objc_type(ty),
                };
                format!("{spelled} {}", names::camel(&field.name))
            })
            .collect();
        let _ = writeln!(header, "/// Makes one from its parts.");
        let _ = writeln!(header, "{name} {name}Make({});\n", arguments.join(", "));
        let _ = writeln!(header, "/// Boxes one so that an NSArray can hold it.");
        let _ = writeln!(header, "NSValue *{name}Boxed({name} value);\n");
        let _ = writeln!(header, "/// Reads one back out of the box.");
        let _ = writeln!(header, "{name} {name}Unboxed(NSValue *value);\n");

        let _ = writeln!(source, "{name} {name}Make({}) {{", arguments.join(", "));
        let _ = writeln!(source, "{TAB}{name} made;");
        for field in &item.fields {
            let spelled = names::camel(&field.name);
            let _ = writeln!(source, "{TAB}made.{spelled} = {spelled};");
        }
        let _ = writeln!(source, "{TAB}return made;");
        let _ = writeln!(source, "}}\n");

        let _ = writeln!(source, "NSValue *{name}Boxed({name} value) {{");
        let _ = writeln!(
            source,
            "{TAB}return [NSValue valueWithBytes:&value objCType:@encode({name})];"
        );
        let _ = writeln!(source, "}}\n");
        let _ = writeln!(source, "{name} {name}Unboxed(NSValue *value) {{");
        let _ = writeln!(source, "{TAB}{name} read;");
        let _ = writeln!(source, "{TAB}[value getValue:&read];");
        let _ = writeln!(source, "{TAB}return read;");
        let _ = writeln!(source, "}}\n");

        // The conversions live beside the calls, where the C interface's own
        // types are in scope.
        let _ = writeln!(source, "{} {name}ToC({name} value) {{", item.name);
        let _ = writeln!(source, "{TAB}{} made;", item.name);
        for field in &item.fields {
            let source_name = format!("value.{}", names::camel(&field.name));
            let converted = match &field.ty {
                Type::Text => format!("OTIOCString({source_name})"),
                Type::Struct(inner) => format!("{}ToC({source_name})", value_name(inner)),
                ty => to_c(ty, &source_name),
            };
            let _ = writeln!(source, "{TAB}made.{} = {converted};", field.name);
        }
        let _ = writeln!(source, "{TAB}return made;");
        let _ = writeln!(source, "}}\n");

        let _ = writeln!(source, "{name} {name}FromC({} value) {{", item.name);
        let _ = writeln!(source, "{TAB}{name} made;");
        for field in &item.fields {
            let source_name = format!("value.{}", field.name);
            let converted = match &field.ty {
                Type::Text => format!("OTIOStringFromC({source_name})"),
                Type::Struct(inner) => format!("{}FromC({source_name})", value_name(inner)),
                ty => from_c(ty, &source_name, "nil"),
            };
            let _ = writeln!(
                source,
                "{TAB}made.{} = {converted};",
                names::camel(&field.name)
            );
        }
        let _ = writeln!(source, "{TAB}return made;");
        let _ = writeln!(source, "}}\n");
    }

    /// The schema ladder, as classes deriving as the schemas derive.
    fn schema_header(&self) -> String {
        let mut out = String::from(
            "#import <Foundation/Foundation.h>\n\n#import \"OpenTimelineIO/OTIORuntime.h\"\n\n\
             NS_ASSUME_NONNULL_BEGIN\n\n",
        );
        for schema in &self.api.schema {
            let Some(parent) = schema.parent.as_deref() else {
                continue;
            };
            for line in self.doc(&schema.docs, &[], None, "") {
                let _ = writeln!(out, "{line}");
            }
            let _ = writeln!(
                out,
                "@interface {} : {}\n@end\n",
                class_name(&schema.name),
                class_name(parent)
            );
        }
        out.push_str("NS_ASSUME_NONNULL_END\n");
        out
    }

    fn schema_source(&self) -> String {
        let mut out = String::from(
            "#import \"OpenTimelineIO/OTIOSchema.h\"\n\n#import <otio.h>\n\n#import \"OTIOPrivate.h\"\n\n",
        );
        for schema in &self.api.schema {
            if schema.parent.is_none() {
                continue;
            }
            let _ = writeln!(out, "@implementation {}\n@end\n", class_name(&schema.name));
        }

        let _ = writeln!(
            out,
            "/// Which schema each one derives from, so that asking whether an object is an\n\
             /// item can say yes for a clip.\n\
             BOOL OTIOSchemaDerives({PREFIX}NodeKind kind, {PREFIX}NodeKind from) {{"
        );
        let _ = writeln!(out, "{TAB}while (YES) {{");
        let _ = writeln!(out, "{TAB}{TAB}if (kind == from) {{ return YES; }}");
        let _ = writeln!(out, "{TAB}{TAB}switch (kind) {{");
        for schema in &self.api.schema {
            let Some(parent) = schema.parent.as_deref() else {
                continue;
            };
            let Some(above) = self.api.schema.iter().find(|item| item.name == parent) else {
                continue;
            };
            let _ = writeln!(
                out,
                "{TAB}{TAB}case {}: kind = {}; continue;",
                variant_name("OtioNodeKind", &schema.kind),
                variant_name("OtioNodeKind", &above.kind)
            );
        }
        let _ = writeln!(out, "{TAB}{TAB}default: return NO;");
        let _ = writeln!(out, "{TAB}{TAB}}}");
        let _ = writeln!(out, "{TAB}}}");
        let _ = writeln!(out, "}}\n");

        let _ = writeln!(
            out,
            "/// Builds the class an object's schema names.\n\
             ///\n\
             /// Every handle that comes back from the library goes through this, so\n\
             /// isKindOfClass: tells the truth. An object whose kind cannot be read comes\n\
             /// back as a plain {ROOT} rather than as a guess.\n\
             {ROOT} *OTIOMakeObject(OTIOArena *_Nullable arena, OtioNode handle) {{"
        );
        let _ = writeln!(out, "{TAB}if (arena == nil || arena.pointer == NULL) {{");
        let _ = writeln!(
            out,
            "{TAB}{TAB}return [{ROOT} objectWithArena:arena handle:handle];"
        );
        let _ = writeln!(out, "{TAB}}}");
        let _ = writeln!(out, "{TAB}OtioNodeKind kind;");
        let _ = writeln!(
            out,
            "{TAB}if (otio_node_kind(arena.pointer, handle, &kind) != OTIO_STATUS_OK) {{"
        );
        let _ = writeln!(
            out,
            "{TAB}{TAB}return [{ROOT} objectWithArena:arena handle:handle];"
        );
        let _ = writeln!(out, "{TAB}}}");
        let _ = writeln!(out, "{TAB}switch (kind) {{");
        for schema in &self.api.schema {
            if schema.parent.is_none() {
                continue;
            }
            let _ = writeln!(
                out,
                "{TAB}case {}: return [{} objectWithArena:arena handle:handle];",
                variant_name("OtioNodeKind", &schema.kind),
                class_name(&schema.name)
            );
        }
        // The root's own kind names no class below the root, and a kind this
        // library was built before does not either.
        let _ = writeln!(out, "{TAB}default: break;");
        let _ = writeln!(out, "{TAB}}}");
        let _ = writeln!(
            out,
            "{TAB}return [{ROOT} objectWithArena:arena handle:handle];"
        );
        let _ = writeln!(out, "}}\n");
        out
    }

    /// Every generated call, as a header of declarations and an
    /// implementation.
    ///
    /// A method body has to sit inside an `@implementation` block, so the
    /// declarations and the bodies of each class are gathered separately and
    /// the block is written around them.
    #[allow(clippy::too_many_lines)]
    fn calls(&self) -> Result<(String, String), String> {
        let mut header = String::from(
            "#import <Foundation/Foundation.h>\n\n\
             #import \"OpenTimelineIO/OTIOEnums.h\"\n\
             #import \"OpenTimelineIO/OTIORuntime.h\"\n\
             #import \"OpenTimelineIO/OTIOSchema.h\"\n\
             #import \"OpenTimelineIO/OTIOValues.h\"\n\n\
             NS_ASSUME_NONNULL_BEGIN\n\n",
        );
        let mut source = String::from(
            "#import \"OpenTimelineIO/OTIOCalls.h\"\n\n\
             #import <stdlib.h>\n\n\
             #import <otio.h>\n\n\
             #import \"OTIOPrivate.h\"\n\n",
        );

        // The free functions, everything that hangs off a value, and what the
        // document used to carry, which are C functions and need no block
        // around them.
        let _ = writeln!(header, "#pragma mark - Functions\n");
        for group in &self.api.groups {
            if matches!(group.receiver, Receiver::None | Receiver::Value(_)) {
                self.emit_some(&mut header, &mut source, group, |_| true)?;
            }
        }
        for group in &self.api.groups {
            if group.receiver == Receiver::Document {
                self.emit_some(&mut header, &mut source, group, |function| {
                    rehomed(&function.symbol).is_none()
                })?;
            }
        }

        // The objects.
        let _ = writeln!(header, "#pragma mark - Objects\n");
        for group in &self.api.groups {
            let Receiver::Node(schema) = &group.receiver else {
                continue;
            };
            if group.view {
                continue;
            }
            let mut declarations = String::new();
            let mut bodies = String::new();
            self.emit_some(&mut declarations, &mut bodies, group, |_| true)?;
            // The four calls the C ABI hung off the document that are really
            // about an object belong here, on the root of the ladder.
            if schema == ROOT.trim_start_matches(PREFIX) {
                for other in &self.api.groups {
                    if other.receiver != Receiver::Document {
                        continue;
                    }
                    self.emit_some(&mut declarations, &mut bodies, other, |function| {
                        rehomed(&function.symbol).is_some()
                    })?;
                }
            }
            if declarations.trim().is_empty() {
                continue;
            }
            let _ = writeln!(
                header,
                "@interface {} (OTIOGenerated)\n",
                class_name(schema)
            );
            header.push_str(declarations.trim_end());
            let _ = writeln!(header, "\n@end\n");
            block(
                &mut source,
                &format!("{} (OTIOGenerated)", class_name(schema)),
                &bodies,
            );
        }

        // The metadata view.
        let _ = writeln!(header, "#pragma mark - Metadata\n");
        for group in &self.api.groups {
            if !group.view {
                continue;
            }
            let Receiver::Node(schema) = &group.receiver else {
                continue;
            };
            let name = format!("{PREFIX}{}", group.name);
            let mut declarations = String::new();
            let mut bodies = String::new();
            self.emit_some(&mut declarations, &mut bodies, group, |_| true)?;

            for line in self.doc(&group.docs, &[], None, "") {
                let _ = writeln!(header, "{line}");
            }
            let _ = writeln!(
                header,
                "@interface {name} : NSObject {{\n\
                 @private\n\
                 {TAB}{ROOT} *_object;\n\
                 }}\n"
            );
            let _ = writeln!(
                header,
                "/// The object whose metadata this is.\n\
                 @property (nonatomic, readonly, strong) {ROOT} *object;\n"
            );
            let _ = writeln!(
                header,
                "/// Makes one for an object. Reach for -[{ROOT} metadata] instead.\n\
                 - (instancetype)initWithObject:({ROOT} *)object;\n\
                 - (instancetype)init NS_UNAVAILABLE;\n"
            );
            header.push_str(declarations.trim_end());
            let _ = writeln!(header, "\n@end\n");

            let _ = writeln!(header, "@interface {} (OTIOMetadata)\n", class_name(schema));
            let _ = writeln!(
                header,
                "/// The object's metadata, which is a dictionary of its own.\n\
                 ///\n\
                 /// A path names a value inside it, a step at a time, separated by dots:\n\
                 /// `cmx_3600.reel` reaches the reel of the dictionary the EDL adapter left\n\
                 /// behind, and `takes[0]` the first entry of a list.\n\
                 ///\n\
                 /// A path is followed, not created. Writing one step deep always works, but\n\
                 /// a deeper one needs its dictionary to exist first.\n\
                 @property (nonatomic, readonly, strong) {name} *metadata;\n"
            );
            let _ = writeln!(header, "@end\n");

            let mut whole = format!(
                "- (instancetype)init {{\n\
                 {TAB}[self doesNotRecognizeSelector:_cmd];\n\
                 {TAB}return nil;\n\
                 }}\n\n\
                 - ({ROOT} *)object {{\n\
                 {TAB}return _object;\n\
                 }}\n\n\
                 - (instancetype)initWithObject:({ROOT} *)object {{\n\
                 {TAB}self = [super init];\n\
                 {TAB}if (self) {{\n\
                 {TAB}{TAB}_object = OTIO_RETAIN(object);\n\
                 {TAB}}}\n\
                 {TAB}return self;\n\
                 }}\n\n\
                 - (void)dealloc {{\n\
                 #if !__has_feature(objc_arc)\n\
                 {TAB}[_object release];\n\
                 {TAB}[super dealloc];\n\
                 #endif\n\
                 }}\n\n"
            );
            whole.push_str(&bodies);
            block(&mut source, &name, &whole);
            block(
                &mut source,
                &format!("{} (OTIOMetadata)", class_name(schema)),
                &format!(
                    "- ({name} *)metadata {{\n\
                     {TAB}return OTIO_AUTORELEASE([[{name} alloc] initWithObject:self]);\n\
                     }}\n"
                ),
            );
        }
        header.push_str("NS_ASSUME_NONNULL_END\n");
        Ok((header, source))
    }
}

/// Writes an `@implementation` block around a run of method bodies.
fn block(source: &mut String, name: &str, bodies: &str) {
    let _ = writeln!(source, "@implementation {name}\n");
    source.push_str(bodies.trim_end());
    let _ = writeln!(source, "\n\n@end\n");
}

