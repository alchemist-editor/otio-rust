/// The C# constant for a status, checked against the library's own enum so a
/// scenario cannot name one that does not exist, and spelled the way the
/// backend spells that enum and its members.
fn status_constant(api: &Api, status: &str) -> Result<String, String> {
    let known = api.enumeration("OtioStatus").is_some_and(|statuses| {
        statuses
            .variants
            .iter()
            .any(|variant| variant.name == status)
    });
    if !known {
        return Err(format!(
            "a conformance scenario expects the status `{status}`, which `OtioStatus` does not have"
        ));
    }
    Ok(format!(
        "{}.{}",
        enum_name("OtioStatus"),
        variant_name(status)
    ))
}

/// What every rendered test leans on. A failed expectation throws, which
/// ends the scenario as the first failure should, and Program.cs reports it.
const HELPERS: &str = "
    /// Insists on an answer.
    private static void Same<T>(T got, T want, string what)
        where T : IEquatable<T>
    {
        if (!got.Equals(want))
        {
            throw new ConformanceFailure($\"{what} is {got}, want {want}\");
        }
    }

    /// Insists on a duration, exactly: every scenario's times are whole frames.
    private static void Lasts(RationalTime got, double value, double rate, string what)
    {
        if (got.Value != value || got.Rate != rate)
        {
            throw new ConformanceFailure(
                $\"{what} is {got.Value} at {got.Rate}, want {value} at {rate}\");
        }
    }

    /// Insists on what an object writes, byte for byte.
    private static void Writes(string got, string want, string what)
    {
        if (!string.Equals(got, want, StringComparison.Ordinal))
        {
            throw new ConformanceFailure($\"{what} wrote\\n{got}\");
        }
    }

    /// Insists the library refused with one status. The binding's own refusal
    /// of an object from another timeline carries a status too, but it is not
    /// the library's answer, so it does not count.
    private static void Refused(string what, Action attempt, Status want)
    {
        try
        {
            attempt();
        }
        catch (OtherTimelineException)
        {
            throw new ConformanceFailure(
                $\"{what}: refused an object from another timeline, want the library to fail with {want.CName()}\");
        }
        catch (OtioException error) when (error.Status == want)
        {
            return;
        }
        catch (OtioException error)
        {
            throw new ConformanceFailure(
                $\"{what}: failed with {error.Status.CName()}, want {want.CName()}\");
        }
        throw new ConformanceFailure($\"{what}: worked, want a failure with {want.CName()}\");
    }

    /// Insists the binding refused an object from another timeline before
    /// asking the library, rather than letting the library fail.
    private static void Foreign(string what, Action attempt)
    {
        try
        {
            attempt();
        }
        catch (OtherTimelineException)
        {
            return;
        }
        catch (OtioException error)
        {
            throw new ConformanceFailure(
                $\"{what}: failed with {error.Status.CName()}, want an OtherTimelineException\");
        }
        throw new ConformanceFailure($\"{what}: worked, want an OtherTimelineException\");
    }
";

/// How a failed expectation ends its scenario.
const FAILURE: &str = "
/// A conformance scenario's expectation that did not hold.
internal sealed class ConformanceFailure : Exception
{
    internal ConformanceFailure(string message)
        : base(message)
    {
    }
}
";
