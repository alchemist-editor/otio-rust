//! The conformance scenarios, as C# tests.
//!
//! The C# tests are a program rather than a framework's suite: `Program.cs`
//! in `sdk/csharp/tests` keeps a list of tests, runs each and exits non-zero
//! if any failed, and the C# job runs it with `dotnet run`. The scenarios
//! land beside it in `sdk/csharp/tests/Conformance.cs`, which the test
//! project compiles because it compiles every file in its directory, as one
//! class whose `Scenarios` list is rendered from the same walk that renders
//! the tests. The program runs that list after its own, so a scenario
//! rendered here is one that runs, and no hand-kept list can leave one out.

use std::fmt::Write as _;
use std::path::PathBuf;

use otio_sdk_model::Api;
use otio_sdk_model::conformance::{self, Attempt, Expect, Failure, Scenario, Step};

use super::{comment, number, quoted};
use crate::csharp::{enum_name, member_case, variant_name};
use crate::emit::File;

/// C# hides the document, so it runs every scenario.
const HIDES_DOCUMENT: bool = true;

/// Renders every scenario C# runs into one file of tests.
///
/// # Errors
///
/// Fails if a scenario names a status the library does not have.
pub fn render(api: &Api) -> Result<File, String> {
    let scenarios: Vec<&Scenario> = conformance::for_target(HIDES_DOCUMENT).collect();
    let mut out = String::new();
    out.push_str(
        "// Code generated by otio-sdk-gen from crates/otio-sdk-model/src/conformance.rs. DO NOT EDIT.\n\n\
         // The conformance scenarios: what every SDK has to agree on, stated once\n\
         // and rendered into each language's own tests. A failure here means this\n\
         // SDK disagrees with the others about what the library does. Program.cs\n\
         // runs every entry of Conformance.Scenarios after its own tests.\n\n\
         using System;\n\
         using OpenTimelineIO;\n\n\
         namespace OpenTimelineIO.Tests;\n\n\
         /// The conformance scenarios, one method each.\n\
         internal static class Conformance\n\
         {\n\
         \x20   /// Every scenario, in the order they are written, for Program.cs to run.\n\
         \x20   internal static readonly (string Name, Action Body)[] Scenarios =\n\
         \x20   {\n",
    );
    for scenario in &scenarios {
        let _ = writeln!(
            out,
            "        ({}, {}),",
            quoted(&format!("conformance: {}", scenario.name)),
            method(scenario)
        );
    }
    out.push_str("    };\n");
    for scenario in &scenarios {
        out.push('\n');
        out.push_str(&test(api, scenario)?);
    }
    out.push_str(HELPERS);
    out.push_str("}\n");
    out.push_str(FAILURE);
    Ok(File {
        path: PathBuf::from("sdk/csharp/tests/Conformance.cs"),
        contents: out,
    })
}

/// The name of the method a scenario is rendered as, spelled as the backend
/// spells a member.
fn method(scenario: &Scenario) -> String {
    member_case(scenario.name)
}

/// One scenario as one method.
fn test(api: &Api, scenario: &Scenario) -> Result<String, String> {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "    /// The scenario {}.",
        quoted(scenario.name)
            .replace('&', "&amp;")
            .replace('<', "&lt;")
    );
    out.push_str("    ///\n");
    for line in comment(scenario, "    /// ", 80) {
        out.push_str(&line.replace('&', "&amp;").replace('<', "&lt;"));
        out.push('\n');
    }
    let _ = writeln!(out, "    private static void {}()", method(scenario));
    out.push_str("    {\n");
    for step in scenario.steps {
        for line in step_lines(api, step)? {
            if line.is_empty() {
                out.push('\n');
            } else {
                out.push_str("        ");
                out.push_str(&line);
                out.push('\n');
            }
        }
    }
    out.push_str("    }\n");
    Ok(out)
}

/// The C# for one step.
fn step_lines(api: &Api, step: &Step) -> Result<Vec<String>, String> {
    Ok(match *step {
        Step::NewTimeline { var, name, .. } => vec![format!(
            "var {} = new Timeline({});",
            local(var),
            quoted(name)
        )],
        Step::Tracks { var, of } => vec![
            format!("if ({}.Tracks() is not Stack {})", local(of), local(var)),
            "{".to_string(),
            format!(
                "    throw new ConformanceFailure({});",
                quoted(&format!("{of}'s tracks are not a stack"))
            ),
            "}".to_string(),
        ],
        Step::NewTrack {
            var, name, kind, ..
        } => vec![format!(
            "var {} = new Track({}, {});",
            local(var),
            quoted(name),
            quoted(kind)
        )],
        Step::NewClip { var, name, .. } => {
            vec![format!("var {} = new Clip({});", local(var), quoted(name))]
        }
        Step::SetSourceRange {
            item,
            start,
            duration,
            rate,
        } => vec![format!(
            "{}.SetSourceRange(new TimeRange({}, {}));",
            local(item),
            time(start, rate),
            time(duration, rate)
        )],
        Step::Append { parent, child } => {
            vec![format!("{}.AppendChild({});", local(parent), local(child))]
        }
        Step::Remove { var } => vec![format!("{}.RemoveFromTimeline();", local(var))],
        Step::Release { var } => vec![format!("{}.Close();", local(var))],
        Step::Expect(expect) => expect_lines(expect),
        Step::Refused { attempt, failure } => {
            let (call, what) = match attempt {
                Attempt::Name { var } => {
                    (format!("{}.Name()", local(var)), format!("{var}.Name()"))
                }
                Attempt::Append { parent, child } => (
                    format!("{}.AppendChild({})", local(parent), local(child)),
                    format!("{parent}.AppendChild({child})"),
                ),
                Attempt::Detach { parent, child } => (
                    format!("{}.DetachChild({})", local(parent), local(child)),
                    format!("{parent}.DetachChild({child})"),
                ),
                Attempt::FlattenTracks { tracks } => {
                    let list: Vec<String> = tracks.iter().map(|track| local(track)).collect();
                    (
                        format!(
                            "Otio.FlattenTracks(new SerializableObject[] {{ {} }})",
                            list.join(", ")
                        ),
                        format!("Otio.FlattenTracks({})", tracks.join(", ")),
                    )
                }
                Attempt::Insert {
                    item,
                    composition,
                    time: at,
                    rate,
                    fill_template,
                } => (
                    format!(
                        "Otio.Insert({}, {}, {}, false, {})",
                        local(item),
                        local(composition),
                        time(at, rate),
                        local(fill_template)
                    ),
                    format!("Otio.Insert({item}, {composition}, {fill_template})"),
                ),
            };
            let check = match failure {
                Failure::OtherTimeline => {
                    format!("Foreign({}, () => {call});", quoted(&what))
                }
                Failure::Status(status) => format!(
                    "Refused({}, () => {call}, {});",
                    quoted(&what),
                    status_constant(api, status)?
                ),
            };
            vec![check]
        }
    })
}

/// The C# for one expectation.
fn expect_lines(expect: Expect) -> Vec<String> {
    match expect {
        Expect::Name { var, is } => vec![format!(
            "Same({}.Name(), {}, {});",
            local(var),
            quoted(is),
            quoted(&format!("{var}.Name()"))
        )],
        Expect::ChildCount { var, is } => vec![format!(
            "Same({}.ChildCount(), {is}, {});",
            local(var),
            quoted(&format!("{var}.ChildCount()"))
        )],
        Expect::Duration { var, value, rate } => vec![format!(
            "Lasts({}.Duration(), {}, {}, {});",
            local(var),
            number(value),
            number(rate),
            quoted(&format!("{var}.Duration()"))
        )],
        Expect::Json { var, is } => vec![format!(
            "Writes({}.ToJson(4), {}, {});",
            local(var),
            quoted(is),
            quoted(&format!("{var}.ToJson(4)"))
        )],
    }
}

/// A time literal.
fn time(value: f64, rate: f64) -> String {
    format!("new RationalTime({}, {})", number(value), number(rate))
}

/// A scenario's variable as a C# local, escaped where it is a keyword so a
/// scenario is never limited to the names C# leaves free.
fn local(var: &str) -> String {
    if KEYWORDS.contains(&var) {
        format!("@{var}")
    } else {
        var.to_string()
    }
}

