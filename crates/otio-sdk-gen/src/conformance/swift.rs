//! The conformance scenarios, as Swift tests.
//!
//! They land in `sdk/swift/Tests/OpenTimelineIOTests/ConformanceTests.swift`,
//! beside the hand-written tests in the same XCTest target, so `swift test`
//! in the Swift job discovers and runs them with everything else.

use std::fmt::Write as _;
use std::path::PathBuf;

use otio_sdk_model::Api;
use otio_sdk_model::conformance::{self, Attempt, Expect, Failure, Scenario, Step};
use otio_sdk_model::names;

use super::{comment, number, quoted};
use crate::emit::File;
use crate::swift::{enum_name, variant_name};

/// Swift hides the document, so it runs every scenario.
const HIDES_DOCUMENT: bool = true;

/// Renders every scenario Swift runs into one test file.
///
/// # Errors
///
/// Fails if a scenario names a status the library does not have.
pub fn render(api: &Api) -> Result<File, String> {
    let mut out = String::new();
    out.push_str(
        "// Code generated by otio-sdk-gen from crates/otio-sdk-model/src/conformance.rs. DO NOT EDIT.\n\n\
         // The conformance scenarios: what every SDK has to agree on, stated once\n\
         // and rendered into each language's own tests. A failure here means this\n\
         // SDK disagrees with the others about what the library does.\n\n\
         import XCTest\n\n\
         import OpenTimelineIO\n\n\
         final class ConformanceTests: XCTestCase {\n",
    );
    for (index, scenario) in conformance::for_target(HIDES_DOCUMENT).enumerate() {
        if index > 0 {
            out.push('\n');
        }
        out.push_str(&test(api, scenario)?);
    }
    out.push_str("}\n");
    out.push_str(HELPERS);
    Ok(File {
        path: PathBuf::from("sdk/swift/Tests/OpenTimelineIOTests/ConformanceTests.swift"),
        contents: out,
    })
}

/// One scenario as one test method.
///
/// Each step runs with `try`, and each expectation throws where it fails, so
/// the first failed expectation ends the test as the scenario says it must.
/// XCTest reports the thrown error as the failure.
fn test(api: &Api, scenario: &Scenario) -> Result<String, String> {
    let name = format!(
        "testConformance{}",
        names::pascal_with(scenario.name, names::INITIALISMS)
    );
    let mut out = String::new();
    let _ = writeln!(out, "    /// The scenario {}.", quoted(scenario.name));
    out.push_str("    ///\n");
    for line in comment(scenario, "    /// ", 80) {
        out.push_str(&line);
        out.push('\n');
    }
    let _ = writeln!(out, "    func {name}() throws {{");
    for step in scenario.steps {
        for line in step_lines(api, step)? {
            out.push_str("        ");
            out.push_str(&line);
            out.push('\n');
        }
    }
    out.push_str("    }\n");
    Ok(out)
}

/// The Swift for one step.
fn step_lines(api: &Api, step: &Step) -> Result<Vec<String>, String> {
    Ok(match *step {
        Step::NewTimeline { var, name, .. } => vec![format!(
            "let {} = try Timeline(name: {})",
            ident(var),
            quoted(name)
        )],
        Step::Tracks { var, of } => vec![format!(
            "let {} = try XCTUnwrap(try {}.tracks() as? Stack, {})",
            ident(var),
            ident(of),
            quoted(&format!("{of}'s tracks are not a stack"))
        )],
        Step::NewTrack {
            var, name, kind, ..
        } => vec![format!(
            "let {} = try Track(name: {}, kind: {})",
            ident(var),
            quoted(name),
            quoted(kind)
        )],
        Step::NewClip { var, name, .. } => vec![format!(
            "let {} = try Clip(name: {})",
            ident(var),
            quoted(name)
        )],
        Step::SetSourceRange {
            item,
            start,
            duration,
            rate,
        } => vec![format!(
            "try {}.setSourceRange(TimeRange(startTime: {}, duration: {}))",
            ident(item),
            time(start, rate),
            time(duration, rate)
        )],
        Step::Append { parent, child } => vec![format!(
            "try {}.appendChild({})",
            ident(parent),
            ident(child)
        )],
        Step::Remove { var } => vec![format!("try {}.removeFromTimeline()", ident(var))],
        Step::Release { var } => vec![format!("{}.close()", ident(var))],
        Step::Expect(expect) => vec![expect_line(expect)],
        Step::Refused { attempt, failure } => {
            let (body, what) = match attempt {
                Attempt::Name { var } => (
                    format!("_ = try {}.name()", ident(var)),
                    format!("{var}.name()"),
                ),
                Attempt::Append { parent, child } => (
                    format!("try {}.appendChild({})", ident(parent), ident(child)),
                    format!("{parent}.appendChild({child})"),
                ),
                Attempt::Detach { parent, child } => (
                    format!("try {}.detachChild({})", ident(parent), ident(child)),
                    format!("{parent}.detachChild({child})"),
                ),
                Attempt::FlattenTracks { tracks } => {
                    let list: Vec<String> = tracks.iter().map(|track| ident(track)).collect();
                    (
                        format!("_ = try OTIO.flattenTracks([{}])", list.join(", ")),
                        format!("OTIO.flattenTracks([{}])", tracks.join(", ")),
                    )
                }
            };
            let check = match failure {
                Failure::OtherTimeline => format!("try conformanceForeign({})", quoted(&what)),
                Failure::Status(status) => format!(
                    "try conformanceRefused({}, status: {})",
                    quoted(&what),
                    status_case(api, status)?
                ),
            };
            vec![format!("{check} {{ {body} }}")]
        }
    })
}

/// The Swift for one expectation.
fn expect_line(expect: Expect) -> String {
    match expect {
        Expect::Name { var, is } => format!(
            "try conformanceText({}, {}.name(), {})",
            quoted(&format!("{var}.name()")),
            ident(var),
            quoted(is)
        ),
        Expect::ChildCount { var, is } => format!(
            "try conformanceEqual({}, {}.childCount(), {is})",
            quoted(&format!("{var}.childCount()")),
            ident(var)
        ),
        // `RationalTime`'s equality is the synthesized one, comparing the
        // value and the rate exactly, which is what the scenario asks.
        Expect::Duration { var, value, rate } => format!(
            "try conformanceEqual({}, {}.duration(), {})",
            quoted(&format!("{var}.duration()")),
            ident(var),
            time(value, rate)
        ),
        Expect::Json { var, is } => format!(
            "try conformanceText({}, {}.toJSON(4), {})",
            quoted(&format!("{var}.toJSON(4)")),
            ident(var),
            quoted(is)
        ),
    }
}

/// A time literal.
fn time(value: f64, rate: f64) -> String {
    format!(
        "RationalTime(value: {}, rate: {})",
        number(value),
        number(rate)
    )
}

/// A scenario's variable as a Swift identifier, escaped where Swift reserves
/// the word.
fn ident(var: &str) -> String {
    if KEYWORDS.split_whitespace().any(|word| word == var) {
        format!("`{var}`")
    } else {
        var.to_string()
    }
}

/// The words Swift will not take as a local's name without backticks.
const KEYWORDS: &str = "Any Self as associatedtype break case catch class continue default defer \
                        deinit do else enum extension fallthrough false fileprivate for func \
                        guard if import in init inout internal is let nil operator private \
                        protocol public repeat rethrows return self static struct subscript \
                        super switch throw throws true try typealias var where while";

/// The Swift case for a status, checked against the library's own enum so a
/// scenario cannot name one that does not exist, and spelled the way the
/// backend spells every enum case.
fn status_case(api: &Api, status: &str) -> Result<String, String> {
    let known = api.enumeration("OtioStatus").is_some_and(|statuses| {
        statuses
            .variants
            .iter()
            .any(|variant| variant.name == status)
    });
    if !known {
        return Err(format!(
            "a conformance scenario expects the status `{status}`, which `OtioStatus` does not have"
        ));
    }
    Ok(format!(
        "{}.{}",
        enum_name("OtioStatus"),
        variant_name(status)
    ))
}

/// What every rendered test leans on.
const HELPERS: &str = r#"
/// Ends a scenario at its first failed expectation. XCTest reports it as the
/// failure, and the `XCTFail` before it points at the line.
private struct ConformanceFailure: Error, CustomStringConvertible {
    let description: String
}

/// Fails the scenario here, at the caller's line.
private func conformanceFail(_ message: String, file: StaticString, line: UInt) -> ConformanceFailure {
    XCTFail(message, file: file, line: line)
    return ConformanceFailure(description: message)
}

/// Insists on an answer.
private func conformanceEqual<T: Equatable>(
    _ what: String, _ got: T, _ want: T, file: StaticString = #filePath, line: UInt = #line
) throws {
    if got != want {
        throw conformanceFail("\(what) = \(got); want \(want)", file: file, line: line)
    }
}

/// Insists on text, byte for byte: Swift's own `==` on strings compares
/// canonical equivalence, which would let two different files pass as one.
private func conformanceText(
    _ what: String, _ got: String, _ want: String, file: StaticString = #filePath, line: UInt = #line
) throws {
    if Array(got.utf8) != Array(want.utf8) {
        throw conformanceFail("\(what) wrote\n\(got)\nwant\n\(want)", file: file, line: line)
    }
}

/// Insists the library refused with one status.
///
/// The binding's own refusal of another timeline's object is not the library
/// refusing, whatever status it carries, so it does not count.
private func conformanceRefused(
    _ what: String, status want: Status, file: StaticString = #filePath, line: UInt = #line,
    _ body: () throws -> Void
) throws {
    do {
        try body()
    } catch let error as OTIOError {
        if error.status == want && !error.isOtherTimeline {
            return
        }
        throw conformanceFail(
            "\(what): failed with \(error.status) (another timeline: \(error.isOtherTimeline)); "
                + "want a failure with status \(want)",
            file: file, line: line)
    } catch {
        throw conformanceFail("\(what): failed with \(error); want an OTIOError", file: file, line: line)
    }
    throw conformanceFail("\(what): did not fail; want status \(want)", file: file, line: line)
}

/// Insists the binding refused an object from another timeline before asking
/// the library, rather than letting the library fail.
private func conformanceForeign(
    _ what: String, file: StaticString = #filePath, line: UInt = #line, _ body: () throws -> Void
) throws {
    do {
        try body()
    } catch let error as OTIOError {
        if error.isOtherTimeline {
            return
        }
        throw conformanceFail(
            "\(what): failed with \(error.status); want the refusal of another timeline's object",
            file: file, line: line)
    } catch {
        throw conformanceFail("\(what): failed with \(error); want an OTIOError", file: file, line: line)
    }
    throw conformanceFail(
        "\(what): did not fail; want the refusal of another timeline's object", file: file, line: line)
}
"#;
