//! The conformance scenarios, as a C++ test program.
//!
//! They land in `sdk/cpp/tests/conformance.cpp`, beside the hand-written
//! tests. The C++ tests use no framework, so the file is a program of its
//! own: one function per scenario, and a table of every one of them that its
//! `main` runs, both rendered here. The CMake file the backend writes builds
//! that program and hands it to `ctest`, which the C++ job already runs, so a
//! scenario reaches the suite by being written and nothing registers it by
//! hand.

use std::fmt::Write as _;
use std::path::PathBuf;

use otio_sdk_model::Api;
use otio_sdk_model::conformance::{self, Attempt, Expect, Failure, Kind, Scenario, Step};

use super::{comment, number, quoted};
use crate::cpp::{constant_name, enum_name, shared_prefix};
use crate::emit::File;

/// C++ hides the document, so it runs every scenario.
const HIDES_DOCUMENT: bool = true;

/// Renders every scenario C++ runs into one test program.
///
/// # Errors
///
/// Fails if a scenario names a status the library does not have.
pub fn render(api: &Api) -> Result<File, String> {
    let mut out = String::new();
    out.push_str(
        "// Code generated by otio-sdk-gen from crates/otio-sdk-model/src/conformance.rs. DO NOT EDIT.\n\n\
         // The conformance scenarios: what every SDK has to agree on, stated once\n\
         // and rendered into each language's own tests. A failure here means this\n\
         // SDK disagrees with the others about what the library does.\n\n\
         #include <cstddef>\n\
         #include <cstdlib>\n\
         #include <iostream>\n\
         #include <optional>\n\
         #include <sstream>\n\
         #include <string>\n\n\
         #include <opentimelineio/otio.hpp>\n\n\
         namespace {\n",
    );
    out.push_str(HELPERS);
    let scenarios: Vec<&Scenario> = conformance::for_target(HIDES_DOCUMENT).collect();
    for scenario in &scenarios {
        out.push('\n');
        out.push_str(&test(api, scenario)?);
    }
    out.push_str(
        "\n/// Every scenario, in the order they are written.\n\
         const ConformanceScenario conformance_scenarios[] = {\n",
    );
    for scenario in &scenarios {
        let _ = writeln!(out, "    {{{}, {}}},", quoted(scenario.name), scenario.name);
    }
    out.push_str("};\n\n}  // namespace\n");
    out.push_str(MAIN);
    Ok(File {
        path: PathBuf::from("sdk/cpp/tests/conformance.cpp"),
        contents: out,
    })
}

/// One scenario as one function, named as the scenario is.
fn test(api: &Api, scenario: &Scenario) -> Result<String, String> {
    let mut out = String::new();
    let _ = writeln!(out, "/// The scenario {}.", quoted(scenario.name));
    out.push_str("///\n");
    for line in comment(scenario, "/// ", 80) {
        out.push_str(&line);
        out.push('\n');
    }
    let _ = writeln!(out, "void {}() {{", scenario.name);
    for step in scenario.steps {
        for line in step_lines(api, step)? {
            out.push_str("    ");
            out.push_str(&line);
            out.push('\n');
        }
    }
    out.push_str("}\n");
    Ok(out)
}

/// The C++ class an object of a kind is held as.
fn class(kind: Kind) -> String {
    format!("otio::{}", kind.schema())
}

/// The C++ for one step.
fn step_lines(api: &Api, step: &Step) -> Result<Vec<String>, String> {
    Ok(match *step {
        Step::NewTimeline { var, name, .. } => vec![format!(
            "{} {var} = {}::create({});",
            class(Kind::Timeline),
            class(Kind::Timeline),
            quoted(name)
        )],
        Step::Tracks { var, of } => vec![format!(
            "{} {var} = conformance_as<{}>({of}.tracks(), {});",
            class(Kind::Stack),
            class(Kind::Stack),
            quoted(&format!("{of}'s tracks are not a stack"))
        )],
        Step::NewTrack {
            var, name, kind, ..
        } => vec![format!(
            "{} {var} = {}::create({}, {});",
            class(Kind::Track),
            class(Kind::Track),
            quoted(name),
            quoted(kind)
        )],
        Step::NewClip { var, name, .. } => vec![format!(
            "{} {var} = {}::create({});",
            class(Kind::Clip),
            class(Kind::Clip),
            quoted(name)
        )],
        Step::SetSourceRange {
            item,
            start,
            duration,
            rate,
        } => vec![format!(
            "{item}.set_source_range(otio::TimeRange({}, {}));",
            time(start, rate),
            time(duration, rate)
        )],
        Step::Append { parent, child } => vec![format!("{parent}.append_child({child});")],
        Step::Remove { var } => vec![format!("{var}.remove_from_timeline();")],
        Step::Release { var } => vec![format!("{var}.close();")],
        Step::Expect(expect) => expect_lines(expect),
        Step::Refused { attempt, failure } => {
            let (body, what) = match attempt {
                Attempt::Name { var } => (format!("(void){var}.name();"), format!("{var}.name()")),
                Attempt::Append { parent, child } => (
                    format!("{parent}.append_child({child});"),
                    format!("{parent}.append_child({child})"),
                ),
                Attempt::Detach { parent, child } => (
                    format!("{parent}.detach_child({child});"),
                    format!("{parent}.detach_child({child})"),
                ),
                Attempt::FlattenTracks { tracks } => {
                    let call = format!("otio::flatten_tracks({{{}}})", tracks.join(", "));
                    (format!("(void){call};"), call)
                }
            };
            vec![match failure {
                Failure::OtherTimeline => {
                    format!("conformance_foreign({}, [&] {{ {body} }});", quoted(&what))
                }
                Failure::Status(status) => format!(
                    "conformance_refused({}, [&] {{ {body} }}, {});",
                    quoted(&what),
                    status_constant(api, status)?
                ),
            }]
        }
    })
}

/// The C++ for one expectation.
fn expect_lines(expect: Expect) -> Vec<String> {
    match expect {
        Expect::Name { var, is } => vec![format!(
            "conformance_expect({}, {var}.name(), std::string({}));",
            quoted(&format!("{var}.name()")),
            quoted(is)
        )],
        Expect::ChildCount { var, is } => vec![format!(
            "conformance_expect({}, {var}.child_count(), std::size_t({is}));",
            quoted(&format!("{var}.child_count()"))
        )],
        Expect::Duration { var, value, rate } => vec![format!(
            "conformance_expect_time({}, {var}.duration(), {}, {});",
            quoted(&format!("{var}.duration()")),
            number(value),
            number(rate)
        )],
        Expect::Json { var, is } => {
            // A line of the file to a literal, so the expectation reads as
            // the file does and no one literal outgrows what a compiler takes.
            let mut lines = vec![format!(
                "conformance_expect_json({}, {var}.to_json(4),",
                quoted(&format!("{var}.to_json(4)"))
            )];
            let pieces: Vec<&str> = is.split_inclusive('\n').collect();
            for (index, piece) in pieces.iter().enumerate() {
                let end = if index + 1 == pieces.len() { ");" } else { "" };
                lines.push(format!("    {}{end}", quoted(piece)));
            }
            if pieces.is_empty() {
                lines.push("    \"\");".to_string());
            }
            lines
        }
    }
}

/// A time literal.
fn time(value: f64, rate: f64) -> String {
    format!("otio::RationalTime({}, {})", number(value), number(rate))
}

/// The C++ constant for a status, checked against the library's own enum so a
/// scenario cannot name one that does not exist, and spelled the way the
/// backend spells that enum's constants.
fn status_constant(api: &Api, status: &str) -> Result<String, String> {
    let statuses = api
        .enumeration("OtioStatus")
        .ok_or("the description has no `OtioStatus` enum")?;
    let variant = statuses
        .variants
        .iter()
        .find(|variant| variant.name == status)
        .ok_or_else(|| {
            format!(
                "a conformance scenario expects the status `{status}`, which `OtioStatus` does not have"
            )
        })?;
    Ok(format!(
        "otio::{}::{}",
        enum_name(&statuses.name),
        constant_name(&variant.c_name, &shared_prefix(statuses))
    ))
}

/// What every rendered scenario leans on.
const HELPERS: &str = r#"
/// Why a scenario stopped. The first failed expectation ends it, as it does
/// in every SDK.
struct ConformanceFailure {
    std::string what;
};

[[noreturn]] void conformance_fail(const std::string &what) {
    throw ConformanceFailure{what};
}

/// Insists on an answer.
template <class T>
void conformance_expect(const char *what, const T &got, const T &want) {
    if (!(got == want)) {
        std::ostringstream out;
        out << what << " is " << got << ", wanted " << want;
        conformance_fail(out.str());
    }
}

/// Insists on a time, exactly: every scenario's times are whole frames.
void conformance_expect_time(
    const char *what, const otio::RationalTime &got, double value, double rate) {
    if (got.value != value || got.rate != rate) {
        std::ostringstream out;
        out << what << " is " << got.value << " at " << got.rate << ", wanted " << value
            << " at " << rate;
        conformance_fail(out.str());
    }
}

/// Insists on the JSON an object writes, byte for byte.
void conformance_expect_json(const char *what, const std::string &got, const char *want) {
    if (got != want) {
        conformance_fail(std::string(what) + " wrote\n" + got);
    }
}

/// The object as a `T`, which it has to be.
template <class T>
T conformance_as(const std::optional<otio::SerializableObject> &node, const char *what) {
    if (node.has_value()) {
        if (std::optional<T> typed = node->as<T>()) {
            return *typed;
        }
    }
    conformance_fail(what);
}

/// Insists the library refused with one status. The binding's own refusal of
/// an object from another timeline is not the library's answer, so it does
/// not count, whatever status it carries.
template <class Body>
void conformance_refused(const char *what, Body body, otio::Status want) {
    try {
        body();
    } catch (const otio::OtherTimelineError &) {
        conformance_fail(
            std::string(what) + ": the binding refused an object from another timeline, want "
            + "a failure with status " + otio::to_string(want));
    } catch (const otio::Error &error) {
        if (error.status() == want) {
            return;
        }
        conformance_fail(
            std::string(what) + ": failed with status " + otio::to_string(error.status())
            + ", want " + otio::to_string(want));
    }
    conformance_fail(
        std::string(what) + ": succeeded, want a failure with status " + otio::to_string(want));
}

/// Insists the binding refused an object from another timeline before asking
/// the library, rather than letting the library fail.
template <class Body>
void conformance_foreign(const char *what, Body body) {
    try {
        body();
    } catch (const otio::OtherTimelineError &) {
        return;
    } catch (const otio::Error &error) {
        conformance_fail(
            std::string(what) + ": failed with status " + otio::to_string(error.status())
            + ", want otio::OtherTimelineError");
    }
    conformance_fail(std::string(what) + ": succeeded, want otio::OtherTimelineError");
}

/// A scenario, by name.
struct ConformanceScenario {
    const char *name;
    void (*body)();
};
"#;

/// The program: every scenario in the table, each reported, and a non-zero
/// exit if any failed.
const MAIN: &str = r#"
int main() {
    int failed = 0;
    for (const ConformanceScenario &scenario : conformance_scenarios) {
        std::cout << scenario.name << "\n";
        try {
            scenario.body();
            std::cout << "  ok\n";
        } catch (const ConformanceFailure &failure) {
            std::cout << "  FAIL " << failure.what << "\n";
            failed += 1;
        } catch (const otio::Error &error) {
            std::cout << "  FAIL threw " << otio::to_string(error.status()) << ": "
                      << error.what() << "\n";
            failed += 1;
        }
    }
    const std::size_t count = sizeof(conformance_scenarios) / sizeof(conformance_scenarios[0]);
    if (failed != 0) {
        std::cout << failed << " of " << count << " failed\n";
        return EXIT_FAILURE;
    }
    std::cout << "all " << count << " passed\n";
    return EXIT_SUCCESS;
}
"#;
