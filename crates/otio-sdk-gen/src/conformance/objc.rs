//! The conformance scenarios, as Objective-C.
//!
//! They land in `sdk/objc/tests/conformance.m`, which the Makefile builds
//! into the test program with every other source in `tests/`, so `make
//! check` in the Objective-C job runs them. The suite there is a program
//! with no framework, so this file brings its own list: every scenario is a
//! function, and `RunConformanceScenarios` runs them all from a table
//! rendered beside them. The hand-written `tests.m` calls that entry point
//! once, and cannot leave a scenario out by forgetting to list it.

use std::fmt::Write as _;
use std::path::PathBuf;

use otio_sdk_model::Api;
use otio_sdk_model::conformance::{self, Attempt, Expect, Failure, Kind, Scenario, Step};
use otio_sdk_model::names;

use super::{comment, number, quoted};
use crate::emit::File;

/// Objective-C hides the document, so it runs every scenario.
const HIDES_DOCUMENT: bool = true;

/// Four spaces, which is what Cocoa indents with.
const TAB: &str = "    ";

/// Renders every scenario Objective-C runs into one source file of the test
/// program.
///
/// # Errors
///
/// Fails if a scenario names a status the library does not have.
pub fn render(api: &Api) -> Result<File, String> {
    let mut out = String::new();
    out.push_str(
        "// Code generated by otio-sdk-gen from crates/otio-sdk-model/src/conformance.rs. DO NOT EDIT.\n\n\
         // The conformance scenarios: what every SDK has to agree on, stated once\n\
         // and rendered into each language's own tests. A failure here means this\n\
         // SDK disagrees with the others about what the library does.\n\
         //\n\
         // tests.m runs them by calling RunConformanceScenarios once, which runs\n\
         // every scenario in the table at the bottom of this file.\n\n\
         #import <Foundation/Foundation.h>\n\n\
         #import <OpenTimelineIO/OpenTimelineIO.h>\n\n\
         /// Runs every scenario, printing each one's name, and answers how many\n\
         /// failed.\n\
         int RunConformanceScenarios(void);\n",
    );
    out.push_str(HELPERS);
    let scenarios: Vec<&Scenario> = conformance::for_target(HIDES_DOCUMENT).collect();
    for scenario in &scenarios {
        out.push('\n');
        out.push_str(&test(api, scenario)?);
    }
    out.push_str(
        "\n#pragma mark - Running\n\n\
         typedef BOOL (*ConformanceBody)(void);\n\n\
         typedef struct {\n\
         \x20   const char *name;\n\
         \x20   ConformanceBody body;\n\
         } ConformanceScenario;\n\n\
         static const ConformanceScenario scenarios[] = {\n",
    );
    for scenario in &scenarios {
        let _ = writeln!(
            out,
            "{TAB}{{{}, {}}},",
            quoted(scenario.name),
            function_name(scenario)
        );
    }
    out.push_str(
        "};\n\n\
         int RunConformanceScenarios(void) {\n\
         \x20   int failed = 0;\n\
         \x20   size_t howMany = sizeof(scenarios) / sizeof(scenarios[0]);\n\
         \x20   for (size_t slot = 0; slot < howMany; slot++) {\n\
         \x20       printf(\"  %s\\n\", scenarios[slot].name);\n\
         \x20       @autoreleasepool {\n\
         \x20           if (!scenarios[slot].body()) {\n\
         \x20               failed += 1;\n\
         \x20           }\n\
         \x20       }\n\
         \x20   }\n\
         \x20   printf(\"  %zu conformance scenarios ran\\n\", howMany);\n\
         \x20   return failed;\n\
         }\n",
    );
    Ok(File {
        path: PathBuf::from("sdk/objc/tests/conformance.m"),
        contents: out,
    })
}

/// The function a scenario is rendered as.
fn function_name(scenario: &Scenario) -> String {
    format!("Conformance{}", names::pascal(scenario.name))
}

/// One scenario as one function, answering whether it passed. The first
/// failed expectation reports and returns, as the scenario says it should.
fn test(api: &Api, scenario: &Scenario) -> Result<String, String> {
    let name = function_name(scenario);
    let mut out = String::new();
    let _ = writeln!(out, "/// The scenario {}.", quoted(scenario.name));
    out.push_str("///\n");
    for line in comment(scenario, "/// ", 80) {
        out.push_str(&line);
        out.push('\n');
    }
    let _ = writeln!(out, "static BOOL {name}(void) {{");
    let _ = writeln!(out, "{TAB}NSError *error = nil;");
    for step in scenario.steps {
        for line in step_lines(api, step)? {
            if line.is_empty() {
                out.push('\n');
            } else {
                out.push_str(TAB);
                out.push_str(&line);
                out.push('\n');
            }
        }
    }
    let _ = writeln!(out, "{TAB}return YES;\n}}");
    Ok(out)
}

/// An Objective-C string literal.
fn text(value: &str) -> String {
    format!("@{}", quoted(value))
}

/// The Objective-C for one step.
fn step_lines(api: &Api, step: &Step) -> Result<Vec<String>, String> {
    // A call that has to work, and what to say if it does not.
    let must = |call: String, what: String| {
        vec![
            format!("if (!{call}) {{"),
            format!("{TAB}return ConformanceUnexpected({}, error);", text(&what)),
            "}".to_string(),
        ]
    };
    // A constructor, which answers nil when it fails.
    let built = |var: &str, kind: Kind, call: String, what: String| {
        vec![
            format!("OTIO{} *{var} = {call};", kind.schema()),
            format!("if ({var} == nil) {{"),
            format!("{TAB}return ConformanceUnexpected({}, error);", text(&what)),
            "}".to_string(),
        ]
    };
    Ok(match *step {
        Step::NewTimeline { var, name, .. } => built(
            var,
            Kind::Timeline,
            format!(
                "[OTIOTimeline timelineWithName:{} error:&error]",
                text(name)
            ),
            format!("building the timeline {var}"),
        ),
        Step::Tracks { var, of } => vec![
            format!("OTIOSerializableObject *{var}Node = [{of} tracks:&error];"),
            format!("if ({var}Node == nil) {{"),
            format!(
                "{TAB}return ConformanceUnexpected({}, error);",
                text(&format!("asking {of} for its tracks"))
            ),
            "}".to_string(),
            format!("if (![{var}Node isKindOfClass:[OTIOStack class]]) {{"),
            format!(
                "{TAB}return ConformanceFail({});",
                text(&format!("{of}'s tracks are not a stack"))
            ),
            "}".to_string(),
            format!("OTIOStack *{var} = (OTIOStack *){var}Node;"),
        ],
        Step::NewTrack {
            var, name, kind, ..
        } => built(
            var,
            Kind::Track,
            format!(
                "[OTIOTrack trackWithName:{} kind:{} error:&error]",
                text(name),
                text(kind)
            ),
            format!("building the track {var}"),
        ),
        Step::NewClip { var, name, .. } => built(
            var,
            Kind::Clip,
            format!("[OTIOClip clipWithName:{} error:&error]", text(name)),
            format!("building the clip {var}"),
        ),
        Step::SetSourceRange {
            item,
            start,
            duration,
            rate,
        } => must(
            format!(
                "[{item} setSourceRange:OTIOTimeRangeMake({}, {}) error:&error]",
                time(start, rate),
                time(duration, rate)
            ),
            format!("{item}.setSourceRange"),
        ),
        Step::Append { parent, child } => must(
            format!("[{parent} appendChild:{child} error:&error]"),
            format!("{parent}.appendChild({child})"),
        ),
        Step::Remove { var } => must(
            format!("[{var} removeFromTimeline:&error]"),
            format!("{var}.removeFromTimeline"),
        ),
        Step::Release { var } => vec![format!("[{var} close];")],
        Step::Expect(expect) => expect_lines(expect),
        Step::Refused { attempt, failure } => {
            // Whether the attempt worked, which it must not have.
            let (worked, what) = match attempt {
                Attempt::Name { var } => {
                    (format!("[{var} name:&error] != nil"), format!("{var}.name"))
                }
                Attempt::Append { parent, child } => (
                    format!("[{parent} appendChild:{child} error:&error]"),
                    format!("{parent}.appendChild({child})"),
                ),
                Attempt::Detach { parent, child } => (
                    format!("[{parent} detachChild:{child} error:&error]"),
                    format!("{parent}.detachChild({child})"),
                ),
                Attempt::FlattenTracks { tracks } => (
                    format!("OTIOFlattenTracks(@[{}], &error) != nil", tracks.join(", ")),
                    format!("OTIOFlattenTracks({})", tracks.join(", ")),
                ),
                Attempt::Insert {
                    item,
                    composition,
                    time: at,
                    rate,
                    fill_template,
                } => (
                    format!(
                        "OTIOInsert({item}, {composition}, {}, NO, {fill_template}, &error)",
                        time(at, rate)
                    ),
                    format!("OTIOInsert({item}, {composition}, {fill_template})"),
                ),
            };
            let check = match failure {
                Failure::OtherTimeline => {
                    format!("ConformanceForeign({}, worked, error)", text(&what))
                }
                Failure::Status(status) => format!(
                    "ConformanceRefused({}, worked, error, {})",
                    text(&what),
                    status_constant(api, status)?
                ),
            };
            vec![
                "error = nil;".to_string(),
                "{".to_string(),
                format!("{TAB}BOOL worked = {worked};"),
                format!("{TAB}if (!{check}) {{"),
                format!("{TAB}{TAB}return NO;"),
                format!("{TAB}}}"),
                "}".to_string(),
            ]
        }
    })
}

/// The Objective-C for one expectation, in a block of its own so that each
/// can call its answer `got`.
fn expect_lines(expect: Expect) -> Vec<String> {
    let (ask, differs, what, want) = match expect {
        Expect::Name { var, is } => (
            vec![format!("NSString *got = [{var} name:&error];")],
            format!("got == nil || ![got isEqualToString:{}]", text(is)),
            format!("{var}.name"),
            text(is),
        ),
        Expect::ChildCount { var, is } => (
            vec!["NSUInteger got = 0;".to_string()],
            format!("![{var} getChildCount:&got error:&error] || got != {is}"),
            format!("{var}.childCount"),
            text(&is.to_string()),
        ),
        Expect::Duration { var, value, rate } => (
            vec!["OTIORationalTime got = OTIORationalTimeMake(0, 0);".to_string()],
            format!(
                "![{var} getDuration:&got error:&error] || got.value != {} || got.rate != {}",
                number(value),
                number(rate)
            ),
            format!("{var}.duration"),
            text(&format!("{} at {}", number(value), number(rate))),
        ),
        Expect::Json { var, is } => (
            vec![format!("NSString *got = [{var} toJSON:4 error:&error];")],
            format!("got == nil || ![got isEqualToString:{}]", text(is)),
            format!("{var}.toJSON(4)"),
            text("the scenario's JSON"),
        ),
    };
    let got = match expect {
        Expect::Name { .. } | Expect::Json { .. } => "got",
        Expect::ChildCount { .. } => "[NSString stringWithFormat:@\"%lu\", (unsigned long)got]",
        Expect::Duration { .. } => "[NSString stringWithFormat:@\"%g at %g\", got.value, got.rate]",
    };
    // The error is cleared first, so one left by an earlier refusal cannot
    // be mistaken for this question failing.
    let mut lines = vec!["error = nil;".to_string(), "{".to_string()];
    for line in ask {
        lines.push(format!("{TAB}{line}"));
    }
    lines.push(format!("{TAB}if ({differs}) {{"));
    lines.push(format!(
        "{TAB}{TAB}return ConformanceWrong({}, {got}, {want}, error);",
        text(&what)
    ));
    lines.push(format!("{TAB}}}"));
    lines.push("}".to_string());
    lines
}

/// A time literal.
fn time(value: f64, rate: f64) -> String {
    format!("OTIORationalTimeMake({}, {})", number(value), number(rate))
}

/// The Objective-C constant for a status, checked against the library's own
/// enum so a scenario cannot name one that does not exist, and spelled the
/// way the backend spells every enum constant.
fn status_constant(api: &Api, status: &str) -> Result<String, String> {
    let statuses = api.enumeration("OtioStatus").ok_or_else(|| {
        "the description has no `OtioStatus`, so no failure can be checked".to_string()
    })?;
    if !statuses
        .variants
        .iter()
        .any(|variant| variant.name == status)
    {
        return Err(format!(
            "a conformance scenario expects the status `{status}`, which `OtioStatus` does not have"
        ));
    }
    Ok(crate::objc::variant_name(&statuses.name, status))
}

/// What every rendered scenario leans on.
const HELPERS: &str = r#"
#pragma mark - Checking

/// Reports a failure and answers NO, so a scenario can return it.
static BOOL ConformanceFail(NSString *what) {
    printf("    FAIL %s\n", what.UTF8String);
    return NO;
}

/// A call that had to work failed.
static BOOL ConformanceUnexpected(NSString *what, NSError *_Nullable error) {
    return ConformanceFail([NSString stringWithFormat:@"%@ failed: %@", what,
                                                      error.localizedDescription]);
}

/// An answer was not the one the scenario insists on, or the question failed,
/// which is what an error says.
static BOOL ConformanceWrong(
    NSString *what, NSString *_Nullable got, NSString *want, NSError *_Nullable error) {
    if (error != nil || got == nil) {
        return ConformanceUnexpected(what, error);
    }
    return ConformanceFail([NSString stringWithFormat:@"%@ is\n%@\nwhere the scenario wants %@",
                                                      what, got, want]);
}

/// Insists the library refused with one status, and that it was the library
/// refusing rather than this binding turning away another timeline's object.
static BOOL ConformanceRefused(
    NSString *what, BOOL worked, NSError *_Nullable error, OTIOStatus want) {
    if (worked || error == nil || ![error.domain isEqualToString:OTIOErrorDomain]
        || error.code != (NSInteger)want || OTIOIsOtherTimeline(error)) {
        return ConformanceFail([NSString
            stringWithFormat:@"%@: worked %d with %@, where it should fail with status %@",
                             what, (int)worked, error, OTIOStatusCName(want)]);
    }
    return YES;
}

/// Insists the binding refused an object from another timeline before asking
/// the library, rather than letting the library fail.
static BOOL ConformanceForeign(NSString *what, BOOL worked, NSError *_Nullable error) {
    if (worked || !OTIOIsOtherTimeline(error)) {
        return ConformanceFail([NSString
            stringWithFormat:@"%@: worked %d with %@, where it should be refused as another "
                             @"timeline's object",
                             what, (int)worked, error]);
    }
    return YES;
}
"#;
