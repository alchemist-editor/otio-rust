//! The conformance scenarios, as Zig tests.
//!
//! They land in `sdk/zig/test/conformance.zig`, beside the hand-written
//! suite. `zig build test` compiles one root, `test/suite.zig`, and a Zig
//! test runs only if the file it is in is reached from there, so the suite
//! imports this file once, from a `test` block of its own. That one import
//! reaches every test in the file, so a scenario added to the data runs
//! without anything listing it by name.
//!
//! Zig keeps the document visible, so it runs only the scenarios every
//! target runs, and a scenario's timelines are documents here: one per name
//! the scenario uses, made before its first step, with every object built in
//! the one its step names. Each is released by a `defer`, except one the
//! scenario releases itself, which is held as an optional that the release
//! empties so the `defer` does not free it a second time.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

use otio_sdk_model::Api;
use otio_sdk_model::conformance::{self, Attempt, Expect, Failure, Scenario, Step};

use super::{comment, number, quoted};
use crate::emit::File;

/// Zig keeps the document visible, so it runs only what every target runs.
const HIDES_DOCUMENT: bool = false;

/// The names the rendered file declares for itself, which a scenario's
/// variable or document may not shadow: Zig refuses a local that does.
const RESERVED: &[&str] = &[
    "std",
    "otio",
    "allocator",
    "doomed",
    "tracksOf",
    "expectName",
    "expectDuration",
    "expectJson",
];

/// Renders every scenario Zig runs into one test file.
///
/// # Errors
///
/// Fails if a scenario names a status the library does not have, builds an
/// object in no timeline, releases a timeline twice, flattens no tracks, or
/// uses a name the rendered file cannot declare.
pub fn render(api: &Api) -> Result<File, String> {
    let mut out = String::new();
    out.push_str(
        "// Code generated by otio-sdk-gen from crates/otio-sdk-model/src/conformance.rs. DO NOT EDIT.\n\n\
         //! The conformance scenarios: what every SDK has to agree on, stated once\n\
         //! and rendered into each language's own tests. A failure here means this\n\
         //! SDK disagrees with the others about what the library does.\n\
         //!\n\
         //! Zig keeps the document visible, so it runs the scenarios every target\n\
         //! runs, each timeline a scenario names being a document of its own.\n\
         //! `test/suite.zig` imports this file, which runs every test in it.\n\n\
         const std = @import(\"std\");\n\
         const otio = @import(\"otio\");\n\n\
         const allocator = std.testing.allocator;\n",
    );
    for scenario in conformance::for_target(HIDES_DOCUMENT) {
        out.push('\n');
        out.push_str(&test(api, scenario)?);
    }
    out.push_str(HELPERS);
    Ok(File {
        path: PathBuf::from("sdk/zig/test/conformance.zig"),
        contents: out,
    })
}

/// How one scenario's documents are spelled, and which of them it releases.
struct Documents<'a> {
    scenario: &'a Scenario,
    /// The Zig variable for each timeline name, in the order they appear.
    names: Vec<(&'static str, String)>,
    /// The timelines the scenario releases itself.
    released: BTreeSet<&'static str>,
}

impl Documents<'_> {
    /// The document an object was built in, as an expression.
    fn of(&self, var: &str) -> Result<String, String> {
        let timeline = conformance::timeline_of(self.scenario, var).ok_or_else(|| {
            format!(
                "the conformance scenario `{}` uses `{var}`, which no step builds in a timeline",
                self.scenario.name
            )
        })?;
        self.named(timeline)
    }

    /// A document by its timeline's name, as an expression: unwrapped, for
    /// one held as an optional because the scenario releases it.
    fn named(&self, timeline: &str) -> Result<String, String> {
        let name = self.variable(timeline)?;
        Ok(if self.released.contains(timeline) {
            format!("{name}.?")
        } else {
            name.to_string()
        })
    }

    /// The variable holding a timeline's document.
    fn variable(&self, timeline: &str) -> Result<&str, String> {
        self.names
            .iter()
            .find(|(each, _)| *each == timeline)
            .map(|(_, name)| name.as_str())
            .ok_or_else(|| {
                format!(
                    "the conformance scenario `{}` names the timeline `{timeline}` but builds nothing in it",
                    self.scenario.name
                )
            })
    }
}

/// One scenario as one test.
fn test(api: &Api, scenario: &Scenario) -> Result<String, String> {
    let variables: Vec<&str> = conformance::variables(scenario)
        .into_iter()
        .map(|(var, _)| var)
        .collect();
    let documents = documents(scenario, &variables)?;

    let mut out = String::new();
    let _ = writeln!(out, "// The scenario {}.", quoted(scenario.name));
    out.push_str("//\n");
    for line in comment(scenario, "// ", 80) {
        out.push_str(&line);
        out.push('\n');
    }
    let _ = writeln!(
        out,
        "test {} {{",
        quoted(&format!("conformance: {}", scenario.name))
    );
    for (timeline, name) in &documents.names {
        if documents.released.contains(timeline) {
            let _ = writeln!(
                out,
                "    var {name}: ?*otio.Document = try otio.Document.init();"
            );
            let _ = writeln!(out, "    defer if ({name}) |doomed| doomed.deinit();");
        } else {
            let _ = writeln!(out, "    const {name} = try otio.Document.init();");
            let _ = writeln!(out, "    defer {name}.deinit();");
        }
    }
    if !documents.names.is_empty() {
        out.push('\n');
    }

    let used = used(scenario);
    let mut released = BTreeSet::new();
    for step in scenario.steps {
        for line in step_lines(api, &documents, &mut released, step)? {
            out.push_str("    ");
            out.push_str(&line);
            out.push('\n');
        }
        // Zig refuses a local nothing reads, and a scenario may build an
        // object only to show what building it does.
        if let Some(var) = introduced(step)
            && !used.contains(var)
        {
            let _ = writeln!(out, "    _ = {var};");
        }
    }
    out.push_str("}\n");
    Ok(out)
}

/// Spells each of a scenario's timelines as a document variable, and notes
/// which it releases.
///
/// A document is named after its timeline, which reads best at the call that
/// builds into it: `otio.Track.init(here, "V1", "Video")`. Where that name is
/// already one of the scenario's variables, it gets a `_document` suffix.
fn documents<'a>(scenario: &'a Scenario, variables: &[&str]) -> Result<Documents<'a>, String> {
    let mut names = Vec::new();
    for timeline in conformance::timelines(scenario) {
        let name = if variables.contains(&timeline) {
            format!("{timeline}_document")
        } else {
            timeline.to_string()
        };
        names.push((timeline, name));
    }

    let mut declared: Vec<&str> = variables.to_vec();
    declared.extend(names.iter().map(|(_, name)| name.as_str()));
    for (index, name) in declared.iter().enumerate() {
        if RESERVED.contains(name) || declared[..index].contains(name) {
            return Err(format!(
                "the conformance scenario `{}` would declare `{name}` twice in Zig; rename a \
                 variable or a timeline",
                scenario.name
            ));
        }
    }

    let mut released = BTreeSet::new();
    for step in scenario.steps {
        if let Step::Release { var } = *step {
            let timeline = conformance::timeline_of(scenario, var).ok_or_else(|| {
                format!(
                    "the conformance scenario `{}` releases `{var}`, which no step builds in a timeline",
                    scenario.name
                )
            })?;
            released.insert(timeline);
        }
    }
    Ok(Documents {
        scenario,
        names,
        released,
    })
}

/// The variable a step introduces, if it introduces one.
fn introduced(step: &Step) -> Option<&'static str> {
    match *step {
        Step::NewTimeline { var, .. }
        | Step::Tracks { var, .. }
        | Step::NewTrack { var, .. }
        | Step::NewClip { var, .. } => Some(var),
        _ => None,
    }
}

/// The variables the rendered Zig reads.
///
/// A release names an object only to say which document to free, and the
/// Zig frees the document without reading the object, so it does not count.
fn used(scenario: &Scenario) -> BTreeSet<&'static str> {
    let mut used = BTreeSet::new();
    for step in scenario.steps {
        match *step {
            Step::NewTimeline { .. }
            | Step::NewTrack { .. }
            | Step::NewClip { .. }
            | Step::Release { .. } => {}
            Step::Tracks { of, .. } => {
                used.insert(of);
            }
            Step::SetSourceRange { item, .. } => {
                used.insert(item);
            }
            Step::Append { parent, child } => {
                used.insert(parent);
                used.insert(child);
            }
            Step::Remove { var } => {
                used.insert(var);
            }
            Step::Expect(
                Expect::Name { var, .. }
                | Expect::ChildCount { var, .. }
                | Expect::Duration { var, .. }
                | Expect::Json { var, .. },
            ) => {
                used.insert(var);
            }
            Step::Refused { attempt, .. } => match attempt {
                Attempt::Name { var } => {
                    used.insert(var);
                }
                Attempt::Append { parent, child } | Attempt::Detach { parent, child } => {
                    used.insert(parent);
                    used.insert(child);
                }
                Attempt::FlattenTracks { tracks } => used.extend(tracks.iter().copied()),
            },
        }
    }
    used
}

/// The Zig for one step.
fn step_lines(
    api: &Api,
    documents: &Documents<'_>,
    released: &mut BTreeSet<&'static str>,
    step: &Step,
) -> Result<Vec<String>, String> {
    Ok(match *step {
        Step::NewTimeline { var, name, .. } => vec![format!(
            "const {var} = try otio.Timeline.init({}, {});",
            documents.of(var)?,
            quoted(name)
        )],
        Step::Tracks { var, of } => vec![format!("const {var} = try tracksOf({of});")],
        Step::NewTrack {
            var, name, kind, ..
        } => vec![format!(
            "const {var} = try otio.Track.init({}, {}, {});",
            documents.of(var)?,
            quoted(name),
            quoted(kind)
        )],
        Step::NewClip { var, name, .. } => vec![format!(
            "const {var} = try otio.Clip.init({}, {});",
            documents.of(var)?,
            quoted(name)
        )],
        Step::SetSourceRange {
            item,
            start,
            duration,
            rate,
        } => vec![
            format!("try {item}.setSourceRange(.{{"),
            format!("    .start_time = {},", time(start, rate)),
            format!("    .duration = {},", time(duration, rate)),
            "});".to_string(),
        ],
        Step::Append { parent, child } => {
            vec![format!("try {parent}.appendChild({child}.asNode());")]
        }
        Step::Remove { var } => vec![format!(
            "try {}.removeNode({var}.asNode());",
            documents.of(var)?
        )],
        Step::Release { var } => {
            let timeline = conformance::timeline_of(documents.scenario, var)
                .ok_or_else(|| format!("`{var}` was built in no timeline"))?;
            if !released.insert(timeline) {
                return Err(format!(
                    "the conformance scenario `{}` releases the timeline `{timeline}` twice",
                    documents.scenario.name
                ));
            }
            let name = documents.variable(timeline)?;
            vec![format!("{name}.?.deinit();"), format!("{name} = null;")]
        }
        Step::Expect(expect) => expect_lines(expect),
        Step::Refused { attempt, failure } => {
            let call = match attempt {
                Attempt::Name { var } => format!("{var}.name(allocator)"),
                Attempt::Append { parent, child } => {
                    format!("{parent}.appendChild({child}.asNode())")
                }
                Attempt::Detach { parent, child } => {
                    format!("{parent}.detachChild({child}.asNode())")
                }
                Attempt::FlattenTracks { tracks } => {
                    // The call is the document's, so it is made in the one
                    // the first track was built in.
                    let first = tracks.first().ok_or_else(|| {
                        format!(
                            "the conformance scenario `{}` flattens no tracks, which gives Zig \
                             no document to ask",
                            documents.scenario.name
                        )
                    })?;
                    let list: Vec<String> = tracks
                        .iter()
                        .map(|track| format!("{track}.asNode()"))
                        .collect();
                    format!(
                        "{}.flattenTracks(allocator, &.{{ {} }})",
                        documents.of(first)?,
                        list.join(", ")
                    )
                }
            };
            let error = match failure {
                Failure::OtherTimeline => "ForeignObject".to_string(),
                Failure::Status(status) => status_error(api, status)?,
            };
            vec![format!(
                "try std.testing.expectError(error.{error}, {call});"
            )]
        }
    })
}

/// The Zig for one expectation.
fn expect_lines(expect: Expect) -> Vec<String> {
    match expect {
        Expect::Name { var, is } => vec![format!("try expectName({var}, {});", quoted(is))],
        Expect::ChildCount { var, is } => vec![format!(
            "try std.testing.expectEqual(@as(usize, {is}), try {var}.childCount());"
        )],
        Expect::Duration { var, value, rate } => vec![format!(
            "try expectDuration({var}, {}, {});",
            number(value),
            number(rate)
        )],
        Expect::Json { var, is } if is.chars().any(|c| c.is_control() && c != '\n') => {
            // A multiline literal cannot hold any other control character.
            vec![format!("try expectJson({var}, {});", quoted(is))]
        }
        Expect::Json { var, is } => {
            // A multiline literal, so the expected file reads as the file.
            // It joins its lines with `\n` and adds none after the last, so
            // a text that ends in one ends in an empty line here.
            let mut lines = vec![format!("try expectJson({var},")];
            lines.extend(is.split('\n').map(|line| format!("    \\\\{line}")));
            lines.push(");".to_string());
            lines
        }
    }
}

/// A time literal.
fn time(value: f64, rate: f64) -> String {
    format!(
        ".{{ .value = {}, .rate = {} }}",
        number(value),
        number(rate)
    )
}

/// The Zig error for a status, checked against the library's own enum so a
/// scenario cannot name one that does not exist. The package's error set
/// spells each status as its variant, which is how the scenario names it.
fn status_error(api: &Api, status: &str) -> Result<String, String> {
    let known = api.enumeration("OtioStatus").is_some_and(|statuses| {
        statuses
            .variants
            .iter()
            .any(|variant| variant.name == status)
    });
    if !known {
        return Err(format!(
            "a conformance scenario expects the status `{status}`, which `OtioStatus` does not have"
        ));
    }
    Ok(status.to_string())
}

/// What every rendered test leans on.
const HELPERS: &str = "
/// The stack a timeline holds its tracks in, which a new one arrives with.
fn tracksOf(timeline: otio.Timeline) !otio.Stack {
    const held = (try timeline.tracks()) orelse {
        std.debug.print(\"the timeline holds no tracks\\n\", .{});
        return error.TestUnexpectedResult;
    };
    return held.asStack() orelse {
        std.debug.print(\"the tracks are held as a {}\\n\", .{try held.schemaKind()});
        return error.TestUnexpectedResult;
    };
}

/// Insists an object has this name.
fn expectName(object: anytype, want: []const u8) !void {
    const got = try object.name(allocator);
    defer allocator.free(got);
    try std.testing.expectEqualStrings(want, got);
}

/// Insists an item lasts exactly `value` at `rate`.
fn expectDuration(item: anytype, value: f64, rate: f64) !void {
    const got = try item.duration();
    try std.testing.expectEqual(value, got.value);
    try std.testing.expectEqual(rate, got.rate);
}

/// Insists an object writes exactly this OpenTimelineIO JSON, indented by
/// four spaces.
fn expectJson(object: anytype, want: []const u8) !void {
    const got = try object.toJson(allocator, 4);
    defer allocator.free(got);
    try std.testing.expectEqualStrings(want, got);
}
";
