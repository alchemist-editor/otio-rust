//! The conformance scenarios, as TypeScript test cases.
//!
//! They land in `crates/otio-wasm/ts/test/conformance.ts` as one array of
//! cases, in the shape the hand-written `test/suite.ts` already uses. The
//! suite spreads that array into its own, once, so both of its runners — Node
//! (`npm test`) and Chromium (`npm run test:browser`) — run every scenario
//! with everything else, and a scenario added here reaches both without
//! anyone listing it.
//!
//! The file sits under `test/`, which `tsconfig.json` includes, so `npm run
//! typecheck` holds it to the SDK's types: a status spelled wrongly is a type
//! error as well as a generation error.

use std::fmt::Write as _;

use otio_sdk_model::Api;
use otio_sdk_model::conformance::{self, Attempt, Expect, Failure, Scenario, Step};

use super::{comment, number, quoted};
use crate::ts::emit::{Artifact, variant_name_of};

/// TypeScript hides the document, so it runs every scenario.
const HIDES_DOCUMENT: bool = true;

/// Renders every scenario TypeScript runs into one test module.
///
/// It is an [`Artifact`] like the rest of the backend's output, placed
/// relative to `crates/otio-wasm`, so `ts::generate` lists it beside them.
///
/// # Errors
///
/// Fails if a scenario names a status the library does not have.
pub fn render(api: &Api) -> Result<Artifact, String> {
    let mut out = String::from(
        "// Generated by `cargo run -p otio-sdk-gen` from\n\
         // `crates/otio-sdk-model/src/conformance.rs`.\n\
         // Do not edit: change the scenarios there and run the generator instead.\n\n\
         /**\n\
         \x20* The conformance scenarios: what every SDK has to agree on, stated once\n\
         \x20* in `crates/otio-sdk-model/src/conformance.rs` and rendered into each\n\
         \x20* language's own tests. A failure here means this SDK disagrees with the\n\
         \x20* others about what the library does.\n\
         \x20*\n\
         \x20* `suite.ts` runs every case in `conformance`, in Node and in Chromium.\n\
         \x20*/\n\n\
         import type { Status } from \"../src/index.js\";\n\
         import type { Case, Otio } from \"./suite.js\";\n\n\
         /** Every scenario, in the order they are written. */\n\
         export const conformance: readonly Case[] = [\n",
    );
    for scenario in conformance::for_target(HIDES_DOCUMENT) {
        out.push_str(&case(api, scenario)?);
    }
    out.push_str("];\n");
    out.push_str(HELPERS);
    Ok(Artifact {
        path: "ts/test/conformance.ts".to_string(),
        text: out,
    })
}

/// One scenario as one case.
fn case(api: &Api, scenario: &Scenario) -> Result<String, String> {
    let mut out = String::new();
    let _ = writeln!(out, "  // The scenario {}.", quoted(scenario.name));
    out.push_str("  //\n");
    for line in comment(scenario, "  // ", 80) {
        out.push_str(&line);
        out.push('\n');
    }
    out.push_str("  {\n");
    let _ = writeln!(
        out,
        "    name: {},",
        quoted(&format!("conformance: {}", scenario.name))
    );
    out.push_str("    run(api) {\n");
    for step in scenario.steps {
        for line in step_lines(api, step)? {
            out.push_str("      ");
            out.push_str(&line);
            out.push('\n');
        }
    }
    out.push_str("    },\n  },\n");
    Ok(out)
}

/// The TypeScript for one step.
fn step_lines(api: &Api, step: &Step) -> Result<Vec<String>, String> {
    Ok(match *step {
        Step::NewTimeline { var, name, .. } => vec![format!(
            "const {var} = new api.Timeline({{ name: {} }});",
            quoted(name)
        )],
        Step::Tracks { var, of } => vec![
            format!("const {var} = {of}.tracks;"),
            format!("if (!({var} instanceof api.Stack)) {{"),
            format!(
                "  throw new Error({});",
                quoted(&format!("{of}'s tracks are not a stack"))
            ),
            "}".to_string(),
        ],
        Step::NewTrack {
            var, name, kind, ..
        } => vec![format!(
            "const {var} = new api.Track({{ name: {}, kind: {} }});",
            quoted(name),
            quoted(kind)
        )],
        Step::NewClip { var, name, .. } => vec![format!(
            "const {var} = new api.Clip({{ name: {} }});",
            quoted(name)
        )],
        Step::SetSourceRange {
            item,
            start,
            duration,
            rate,
        } => vec![format!(
            "{item}.sourceRange = new api.TimeRange({}, {});",
            time(start, rate),
            time(duration, rate)
        )],
        Step::Append { parent, child } => vec![format!("{parent}.appendChild({child});")],
        Step::Remove { var } => vec![format!("{var}.remove();")],
        Step::Release { var } => vec![format!("{var}.dispose();")],
        Step::Expect(expect) => vec![expect_line(expect)],
        Step::Refused { attempt, failure } => {
            // The call is also what the failure message names it by.
            let call = match attempt {
                Attempt::Name { var } => format!("{var}.name"),
                Attempt::Append { parent, child } => format!("{parent}.appendChild({child})"),
                Attempt::Detach { parent, child } => format!("{parent}.detachChild({child})"),
                Attempt::FlattenTracks { tracks } => {
                    format!("api.algorithms.flattenTracks([{}])", tracks.join(", "))
                }
            };
            vec![match failure {
                Failure::OtherTimeline => {
                    format!("conformanceForeign(api, {}, () => {call});", quoted(&call))
                }
                Failure::Status(status) => format!(
                    "conformanceRefused(api, {}, () => {call}, {});",
                    quoted(&call),
                    quoted(&status_name(api, status)?)
                ),
            }]
        }
    })
}

/// The TypeScript for one expectation.
fn expect_line(expect: Expect) -> String {
    match expect {
        Expect::Name { var, is } => format!(
            "conformanceIs({var}.name, {}, {});",
            quoted(is),
            quoted(&format!("{var}.name"))
        ),
        Expect::ChildCount { var, is } => format!(
            "conformanceIs({var}.childCount(), {is}, {});",
            quoted(&format!("{var}.childCount()"))
        ),
        Expect::Duration { var, value, rate } => format!(
            "conformanceTime({var}.duration(), {}, {}, {});",
            number(value),
            number(rate),
            quoted(&format!("{var}.duration()"))
        ),
        Expect::Json { var, is } => format!(
            "conformanceIs({var}.toJson(4), {}, {});",
            quoted(is),
            quoted(&format!("{var}.toJson(4)"))
        ),
    }
}

/// A time literal.
fn time(value: f64, rate: f64) -> String {
    format!("new api.RationalTime({}, {})", number(value), number(rate))
}

/// The TypeScript spelling of a status, checked against the library's own
/// enum so a scenario cannot name one that does not exist, and spelled by the
/// function that spells the `Status` union in `generated/types.ts`.
fn status_name(api: &Api, status: &str) -> Result<String, String> {
    let known = api.enumeration("OtioStatus").is_some_and(|statuses| {
        statuses
            .variants
            .iter()
            .any(|variant| variant.name == status)
    });
    if !known {
        return Err(format!(
            "a conformance scenario expects the status `{status}`, which `OtioStatus` does not have"
        ));
    }
    Ok(variant_name_of(status))
}

/// What every rendered case leans on.
const HELPERS: &str = "
/** Fails the scenario unless two values are the same. */
function conformanceIs<T>(found: T, wanted: T, what: string): void {
  if (!Object.is(found, wanted)) {
    throw new Error(
      `${what}: expected ${JSON.stringify(wanted)}, found ${JSON.stringify(found)}`,
    );
  }
}

/** Fails the scenario unless a time is exactly `value` at `rate`. */
function conformanceTime(
  found: { readonly value: number; readonly rate: number },
  value: number,
  rate: number,
  what: string,
): void {
  if (found.value !== value || found.rate !== rate) {
    throw new Error(
      `${what}: expected ${value} at ${rate}, found ${found.value} at ${found.rate}`,
    );
  }
}

/** What `body` threw, failing the scenario if it threw nothing. */
function conformanceThrown(what: string, body: () => unknown): unknown {
  try {
    body();
  } catch (thrown) {
    return thrown;
  }
  throw new Error(`${what}: nothing was thrown`);
}

/** Insists the library refused with one status. */
function conformanceRefused(
  api: Otio,
  what: string,
  body: () => unknown,
  status: Status,
): void {
  const thrown = conformanceThrown(what, body);
  if (!(thrown instanceof api.OtioError) || thrown.status !== status) {
    throw new Error(
      `${what}: threw ${String(thrown)}, want an OtioError with status ${status}`,
      { cause: thrown },
    );
  }
}

/**
 * Insists the binding refused an object from another timeline before asking
 * the library, rather than letting the library fail.
 */
function conformanceForeign(api: Otio, what: string, body: () => unknown): void {
  const thrown = conformanceThrown(what, body);
  if (!(thrown instanceof api.OtherTimelineError)) {
    throw new Error(`${what}: threw ${String(thrown)}, want an OtherTimelineError`, {
      cause: thrown,
    });
  }
}
";
