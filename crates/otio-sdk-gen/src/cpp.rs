//! The C++ SDK.
//!
//! C++ is the one target where upstream OpenTimelineIO is not a binding but
//! the core itself, so there is a real surface to match rather than a
//! convention to guess at: `otio::Clip`, `source_range()`,
//! `set_source_range()`, `find_clips()`, members in `snake_case` and types
//! in `PascalCase`.
//!
//! What it copies from upstream:
//!
//! - **A class per schema, deriving as the schemas derive**, so a `Clip` has
//!   every member of `Item`, `Composable` and `SerializableObject`.
//! - **`snake_case` members**, which is how upstream's own headers spell
//!   them, rather than the `camelCase` the Swift SDK uses.
//! - **Value types are structs** with public fields and `==`.
//! - **Compositions are not containers**: `children()` and fallible
//!   `append_child`/`insert_child`/`remove_child`, because re-parenting can
//!   fail and has side effects.
//!
//! Where it departs, and why, is in `docs/adr/0003-sdk-generation.md`. The
//! two that matter: failure is an exception rather than upstream's
//! `ErrorStatus *` out-parameter, and an object is a value of two words —
//! the document it lives in and a handle into that document's arena — rather
//! than a retained pointer, so `is<Clip>()` and `as<Clip>()` ask the library
//! what an object is instead of asking the compiler with `dynamic_cast`.

