use crate::emit::File;

/// Where the C++ package lives, relative to the workspace root.
const DIR: &str = "sdk/cpp";

/// Where the generated headers go inside it.
const HEADERS: &str = "include/opentimelineio";

/// The root of the OTIO schema ladder, which C++ spells as upstream does.
const ROOT: &str = "SerializableObject";

/// Four spaces, which is what this writes C++ with.
const TAB: &str = "    ";

/// The local a fallible call's message is written into. Every generated call
/// declares its own, so no two calls, and no two threads, share one; the name
/// is the C parameter's, which no argument of the C++ surface is called.
const ERROR_LOCAL: &str = "out_error";

/// Generates every file of the C++ package.
///
/// # Errors
///
/// Fails if two calls would end up with the same name on one C++ type, or if
/// a call cannot be written mechanically and is not hand-written here.
pub fn generate(api: &Api) -> Result<Vec<File>, String> {
    let backend = Backend::new(api);
    backend.check_names()?;
    let objects = backend.objects()?;
    let calls = backend.calls()?;
    let values = backend.values()?;
    Ok(vec![
        plain("CMakeLists.txt", CMAKE),
        plain(".gitignore", BUILD_GITIGNORE),
        plain("lib/.gitignore", LIB_GITIGNORE),
        plain("README.md", README),
        header("otio.hpp", UMBRELLA),
        header("enums.hpp", &backend.enums()),
        header("runtime.hpp", RUNTIME),
        header("values.hpp", &values),
        header("objects.hpp", &objects),
        header("calls.hpp", &calls),
    ])
}

/// A file whose contents do not depend on the description.
fn plain(name: &str, contents: &str) -> File {
    File {
        path: PathBuf::from(DIR).join(name),
        contents: contents.to_string(),
    }
}

/// A header, with the note saying not to edit it.
fn header(name: &str, body: &str) -> File {
    let mut out =
        String::from("// Code generated by otio-sdk-gen from crates/otio-capi. DO NOT EDIT.\n\n");
    out.push_str("#pragma once\n\n");
    out.push_str(body.trim_end());
    out.push('\n');
    File {
        path: PathBuf::from(DIR).join(HEADERS).join(name),
        contents: out,
    }
}

/// The state a backend carries while it writes.
struct Backend<'a> {
    api: &'a Api,
    /// How each interface symbol is spelled in C++, for the documentation.
    spellings: BTreeMap<String, String>,
}

impl<'a> Backend<'a> {
    fn new(api: &'a Api) -> Self {
        let mut spellings = BTreeMap::new();
        for group in &api.groups {
            for function in &group.functions {
                spellings.insert(function.symbol.clone(), member_name(group, function));
            }
        }
        for item in &api.enums {
            let spelled = enum_name(&item.name);
            let prefix = shared_prefix(item);
            for variant in &item.variants {
                spellings.insert(
                    variant.c_name.clone(),
                    format!("{spelled}::{}", constant_name(&variant.c_name, &prefix)),
                );
            }
        }
        Self { api, spellings }
    }

    /// Fails if two calls would land on one C++ type with the same name.
    ///
    /// C++ can overload, but two members that differ only in their arguments
    /// read as one call with two shapes and can be ambiguous where either
    /// has a default, so this asks for distinct names — and a name clashes
    /// on a derived class too, since a member declared on `Item` is reachable
    /// on a `Clip` and one redeclared there hides it.
    fn check_names(&self) -> Result<(), String> {
        let mut placed: Vec<(String, String, String)> = Vec::new();
        for (owner, name) in RESERVED {
            placed.push(((*owner).to_string(), (*name).to_string(), String::new()));
        }
        for item in &self.api.structs {
            if item.plumbing || item.name == "OtioNode" {
                continue;
            }
            // A value struct's own fields are members of it too, and a
            // getter named after one would be a redeclaration.
            for field in &item.fields {
                placed.push((value_name(&item.name), field.name.clone(), String::new()));
            }
        }
        let mut clashes = Vec::new();
        for group in &self.api.groups {
            for function in &group.functions {
                if self.skipped(function) {
                    continue;
                }
                let owner = self.owner_of(group, function);
                let name = member_name(group, function);
                for (other_owner, other_name, other_symbol) in &placed {
                    if *other_name != name || !self.meet(&owner, other_owner) {
                        continue;
                    }
                    let first = if other_symbol.is_empty() {
                        format!("the hand-written {other_owner}::{other_name}")
                    } else {
                        format!("`{other_symbol}`")
                    };
                    clashes.push(format!(
                        "{first} and `{}` are both {name} on {owner}",
                        function.symbol
                    ));
                }
                placed.push((owner, name, function.symbol.clone()));
            }
        }
        if clashes.is_empty() {
            return Ok(());
        }
        Err(format!(
            "the C++ names collide:\n  {}\n\nGive one of each pair another name in \
             `otio-sdk-model/src/overrides.rs`.",
            clashes.join("\n  ")
        ))
    }

    /// Whether this backend leaves a call out of the generated surface.
    fn skipped(&self, function: &Function) -> bool {
        let _ = self;
        matches!(function.role, Role::Plumbing | Role::Destructor) || hidden(&function.symbol)
    }

    /// Whether two owners are places a caller could reach the same name
    /// from, which for a class is anywhere on its line of descent.
    fn meet(&self, left: &str, right: &str) -> bool {
        if left == right {
            return true;
        }
        let (Some(one), Some(other)) =
            (left.strip_prefix("object:"), right.strip_prefix("object:"))
        else {
            return false;
        };
        self.api
            .ancestry(one)
            .iter()
            .any(|schema| schema.name == other)
            || self
                .api
                .ancestry(other)
                .iter()
                .any(|schema| schema.name == one)
    }

    /// The C++ type a call hangs off, or `otio` for a free function.
    fn owner_of(&self, group: &Group, function: &Function) -> String {
        if let Some((owner, _)) = rehomed(&function.symbol) {
            return owner.to_string();
        }
        match (&group.receiver, function.role) {
            (Receiver::None, _) => "otio".to_string(),
            // Nothing hangs off the document, because there is no document
            // to hang it off: what is left is a free function of `otio`.
            (Receiver::Document, _) => "otio".to_string(),
            (Receiver::Node(schema), Role::Constructor) => {
                if takes_a_document(function) {
                    // A static member of the class it builds. C++ hides an
                    // inherited static behind one of the same name, so
                    // `Clip::create` and `Item::create` do not collide the
                    // way two ordinary members on one line of descent would.
                    format!("constructor:{schema}")
                } else {
                    format!("object:{ROOT}")
                }
            }
            (Receiver::Node(schema), _) => {
                if group.view {
                    group.name.clone()
                } else {
                    format!("object:{schema}")
                }
            }
            // A C++ enum holds no members, so the calls on one are free
            // functions named after it.
            (Receiver::Value(what), _) if self.api.enumeration(what).is_some() => {
                "otio".to_string()
            }
            (Receiver::Value(what), _) => value_name(what),
        }
    }
}

/// Whether a call is given a document to work in.
fn takes_a_document(function: &Function) -> bool {
    function
        .params
        .iter()
        .any(|param| matches!(param.role, ParamRole::DocumentIn | ParamRole::DocumentMut))
}

/// Whether a call leaves the document it is given as it found it.
fn reads_only(function: &Function) -> bool {
    !function
        .params
        .iter()
        .any(|param| param.role == ParamRole::DocumentMut)
}

/// What a call is called in C++.
fn member_name(group: &Group, function: &Function) -> String {
    if let Some((_, name)) = rehomed(&function.symbol) {
        return name.to_string();
    }
    match (&group.receiver, function.role) {
        // A constructor is a static member of the class it builds, so it
        // does not have to say which class that was.
        (Receiver::Node(_), Role::Constructor) if takes_a_document(function) => {
            renamed(&function.name).to_string()
        }
        // A call on an enum is a free function, so it carries the enum's name.
        (Receiver::Value(what), _) if what.starts_with("Otio") && is_enum_name(what) => {
            format!("{}_{}", snake(&enum_name(what)), renamed(&function.name))
        }
        _ => renamed(&function.name).to_string(),
    }
}

/// Whether a C name is one of the interface's enums rather than a struct.
///
/// The names are disjoint, so the spelling is enough and the description
/// does not have to be threaded through every naming helper.
fn is_enum_name(c_name: &str) -> bool {
    ENUM_NAMES.contains(&c_name)
}

/// Every enum the C interface declares, so that a name can be classified
/// without the description in hand. The generator checks this list against
/// the description and fails if it has fallen behind.
const ENUM_NAMES: &[&str] = &[
    "OtioDropFrame",
    "OtioEdlStyle",
    "OtioFormat",
    "OtioMissingFramePolicy",
    "OtioNeighborGapPolicy",
    "OtioNodeKind",
    "OtioReferencePoint",
    "OtioStatus",
    "OtioValueKind",
];

/// The C++ name of an enum: `OtioNodeKind` becomes `NodeKind`.
fn enum_name(c_name: &str) -> String {
    names::respell(
        c_name.strip_prefix("Otio").unwrap_or(c_name),
        names::INITIALISMS,
    )
}

/// The C++ name of a value struct: `OtioRationalTime` becomes
/// `RationalTime`.
fn value_name(c_name: &str) -> String {
    enum_name(c_name)
}

/// The prefix every constant of one enum shares, such as `OTIO_STATUS_`.
fn shared_prefix(item: &Enum) -> String {
    let constants: Vec<String> = item
        .variants
        .iter()
        .map(|variant| variant.c_name.clone())
        .collect();
    names::shared_prefix(&constants)
}

/// Names a constant cannot take. A macro beats every declaration, so an enum
/// constant spelled `NULL` is replaced by the preprocessor before the compiler
/// ever sees it.
const UNSPELLABLE: &[&str] = &["NULL", "EOF", "TRUE", "FALSE"];

/// The C++ name of an enum's constant, which is the C one without the prefix
/// its type already says: `OTIO_STATUS_NO_VALUE` becomes `NO_VALUE`. Where the
/// short name is one a macro has taken, a segment of the prefix goes back on
/// until it is the constant's own: `OTIO_VALUE_NULL` is `VALUE_NULL`.
fn constant_name(c_name: &str, prefix: &str) -> String {
    let short = c_name.strip_prefix(prefix).unwrap_or(c_name);
    if !UNSPELLABLE.contains(&short) {
        return short.to_string();
    }
    let segments: Vec<&str> = prefix.trim_end_matches('_').split('_').collect();
    for taken in 1..=segments.len() {
        let name = format!("{}_{short}", segments[segments.len() - taken..].join("_"));
        if !UNSPELLABLE.contains(&name.as_str()) {
            return name;
        }
    }
    c_name.to_string()
}

/// A `PascalCase` name in `snake_case`: `ExternalReference` becomes
/// `external_reference`.
fn snake(name: &str) -> String {
    names::split_pascal(name)
        .iter()
        .map(|word| word.to_lowercase())
        .collect::<Vec<_>>()
        .join("_")
}

/// The C++ type a value has.
fn cpp_type(ty: &Type) -> String {
    match ty {
        Type::Bool => "bool".to_string(),
        Type::Double => "double".to_string(),
        Type::Int64 => "std::int64_t".to_string(),
        Type::Uint64 => "std::uint64_t".to_string(),
        Type::Int32 => "std::int32_t".to_string(),
        Type::Uint32 => "std::uint32_t".to_string(),
        Type::Size => "std::size_t".to_string(),
        Type::Text => "std::string".to_string(),
        Type::Bytes => "std::vector<std::uint8_t>".to_string(),
        Type::Node => ROOT.to_string(),
        // A call that makes a document hands back what the document is
        // about, since the document itself is not part of the surface.
        Type::Document => ROOT.to_string(),
        Type::Struct(name) => value_name(name),
        Type::Enum(name) => enum_name(name),
        Type::List(inner) => format!("std::vector<{}>", cpp_type(inner)),
    }
}

/// The C type a value crosses the boundary as.
fn c_type(ty: &Type) -> String {
    match ty {
        Type::Bool => "bool".to_string(),
        Type::Double => "double".to_string(),
        Type::Int64 => "int64_t".to_string(),
        Type::Uint64 => "uint64_t".to_string(),
        Type::Int32 => "int32_t".to_string(),
        Type::Uint32 => "uint32_t".to_string(),
        Type::Size => "size_t".to_string(),
        Type::Text | Type::Bytes => "OtioBuffer".to_string(),
        Type::Node => "OtioNode".to_string(),
        Type::Document => "OtioDocument *".to_string(),
        Type::Struct(name) | Type::Enum(name) => name.clone(),
        Type::List(inner) => c_type(inner),
    }
}

/// Whether a C++ parameter of this type is worth taking by reference.
fn by_reference(ty: &Type) -> bool {
    matches!(
        ty,
        Type::Text | Type::Bytes | Type::Struct(_) | Type::List(_) | Type::Node
    )
}

/// The answer a call that cannot fail gives when it is handed an object from
/// another document and has no way to report the mistake.
fn cpp_zero(ty: &Type) -> Result<String, String> {
    Ok(match ty {
        Type::Bool => "false".to_string(),
        Type::Double | Type::Int64 | Type::Uint64 | Type::Int32 | Type::Uint32 | Type::Size => {
            "0".to_string()
        }
        Type::Text => "std::string()".to_string(),
        Type::Bytes | Type::List(_) => format!("{}()", cpp_type(ty)),
        other => {
            return Err(format!(
                "a call that cannot fail answers with a `{}`, which has no value to stand for \
                 an object from another document",
                other.c_name()
            ));
        }
    })
}

/// Turns the C value a call gave back into a C++ one.
///
/// `owner` is the document a handle belongs to, since an object in C++
/// carries the document it can be resolved against rather than making its
/// caller remember.
fn from_c(ty: &Type, value: &str, holder: &str) -> String {
    match ty {
        Type::Node => format!("{ROOT}(detail::Adopt{{}}, {holder}, {value})"),
        Type::Document => format!("detail::root_of({value})"),
        Type::Text => format!("detail::text({value})"),
        Type::Enum(name) => format!(
            "static_cast<{}>(static_cast<std::int32_t>({value}))",
            enum_name(name)
        ),
        Type::Struct(name) => format!("{}({value})", value_name(name)),
        _ => value.to_string(),
    }
}

/// Turns a C++ value into the C one a call wants.
fn to_c(ty: &Type, value: &str) -> String {
    match ty {
        Type::Node => format!("{value}.handle()"),
        Type::Enum(name) => format!("static_cast<{name}>(static_cast<int32_t>({value}))"),
        Type::Struct(_) => format!("{value}.c_value()"),
        _ => value.to_string(),
    }
}

/// Words C++ will not let a member be called, and what to call them instead.
const RENAMED: &[(&str, &str)] = &[("new", "create"), ("delete", "remove"), ("this", "self")];

/// What a member is called in C++, once the language's own words are out of
/// the way.
fn renamed(name: &str) -> &str {
    for (taken, instead) in RENAMED {
        if name == *taken {
            return instead;
        }
    }
    name
}

/// The entry points this SDK does not write, and why.
///
/// Every one of them is the arena showing through. With the document hidden
/// there is nothing for a caller to ask them, and the headers ask them
/// themselves where the answer is still needed: reading a file ends in
/// `otio_document_root`, writing one begins with `otio_document_set_root`,
/// and putting an object into a timeline it did not come from is
/// `otio_document_absorb`.
const HIDDEN: &[(&str, &str)] = &[
    (
        "otio_document_absorb",
        "how an object built on its own joins a timeline, which appending it does",
    ),
    (
        "otio_document_clone",
        "copying an object is `deep_clone`, which is the question a caller has",
    ),
    (
        "otio_document_new",
        "an arena is made for each object built",
    ),
    ("otio_document_node_count", "how big the arena is"),
    ("otio_document_root", "what reading a file answers with"),
    (
        "otio_document_set_root",
        "where writing starts, which is the object given",
    ),
    (
        "otio_document_to_json",
        "`to_json`, which serialises from wherever it is pointed",
    ),
];

/// Whether the headers write a call at all.
fn hidden(symbol: &str) -> bool {
    HIDDEN.iter().any(|(name, _)| *name == symbol)
}

/// Where a call the C ABI hangs off the document belongs once the document
/// is out of sight, and what it is called there.
///
/// Each of these is really about the object it is handed rather than about
/// the arena holding it. `contains` becomes `is_live`, because "is this
/// object in its document" is how a caller with no document asks whether it
/// is still there.
const REHOMED: &[(&str, &str, &str)] = &[
    (
        "otio_document_contains",
        "object:SerializableObject",
        "is_live",
    ),
    (
        "otio_document_deep_clone",
        "object:SerializableObject",
        "deep_clone",
    ),
    (
        "otio_document_remove",
        "object:SerializableObject",
        "remove_from_timeline",
    ),
    (
        "otio_document_remove_recursive",
        "object:SerializableObject",
        "remove_from_timeline_recursive",
    ),
];

/// Which parameter a call is anchored on, which is the description's answer.
fn anchor_index(function: &Function) -> Result<usize, String> {
    function
        .params
        .iter()
        .position(|param| param.anchor)
        .ok_or_else(|| {
            format!(
                "`{}` is about one of the objects it is handed, and the description does not \
                 say which",
                function.symbol
            )
        })
}

/// What a rehomed call becomes, if it is one.
fn rehomed(symbol: &str) -> Option<(&'static str, &'static str)> {
    REHOMED
        .iter()
        .find(|(name, _, _)| *name == symbol)
        .map(|(_, owner, name)| (*owner, *name))
}

/// Members this SDK writes by hand, which a generated one may not take.
const RESERVED: &[(&str, &str)] = &[
    ("otio", "open"),
    ("otio", "save"),
    ("object:SerializableObject", "arena"),
    ("object:SerializableObject", "close"),
    ("object:SerializableObject", "handle"),
    ("object:SerializableObject", "is"),
    ("object:SerializableObject", "as"),
    ("object:SerializableObject", "is_a"),
    ("object:SerializableObjectWithMetadata", "metadata"),
];

/// Where a call gets the arena it is made in, now that a caller no longer
/// hands one over.
///
/// The description says which object the call is anchored on — see
/// `Param::anchor` — and this is what that looks like in C++.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Anchor {
    /// The call is a member, and happens where its object is.
    Receiver(String),
    /// The call is a member of an object the C ABI passes as an ordinary
    /// argument. The argument is the receiver and not a parameter.
    Argument(usize),
    /// The call is a free function, made in the arena of one of the objects
    /// it is handed.
    Named(String),
    /// The same, for a function handed a list of objects.
    List(String),
    /// The call writes a document out and is handed no object to say which.
    /// It takes one, and writing starts there.
    Root,
    /// The call builds something, so it makes an arena to build it in.
    Fresh,
    /// The call touches no arena at all.
    None,
}

/// One call, being written into one place.
struct Site<'a> {
    api: &'a Api,
    function: &'a Function,
    /// The C++ expression for the document the call works in, which is also
    /// the document anything it hands back belongs to. `nullptr` for a call
    /// that has none.
    owner: String,
    /// The C++ expression naming the arena an object the call hands back
    /// belongs to. An object holds the arena itself, not the raw pointer
    /// `owner` is, so the two are spelled differently.
    holder: String,
    /// Where that arena comes from.
    anchor: Anchor,
    /// The C++ expression for the handle or value the call is about.
    receiver: String,
    /// The class a constructor's handle should be handed back as, so that
    /// `document.new_clip` answers with a `Clip` rather than a bare object.
    wrap: Option<String>,
    /// What the call is called, which names its result struct where it has
    /// more than one answer.
    member: String,
}

/// A call, written out.
struct Rendered {
    /// The parameters as the declaration spells them, defaults included.
    params: Vec<String>,
    /// The same parameters as the definition spells them, which in C++ is
    /// without the defaults.
    plain: Vec<String>,
    /// What the call answers with, or the empty string for nothing.
    result: String,
    /// The struct a call with several answers hands back, if it has one.
    nested: Vec<String>,
    /// That struct's name, which the definition has to say the scope of.
    nested_name: Option<String>,
    /// The lines of the body, at no indentation.
    body: Vec<String>,
}

/// Adds a parameter to both spellings of the signature.
fn push_param(params: &mut Vec<(String, Option<String>)>, decl: &str, fallback: Option<&str>) {
    params.push((decl.to_string(), fallback.map(ToString::to_string)));
}

/// Spells the parameters twice: as the declaration wants them and as the
/// definition does.
///
/// C++ only allows a default where every parameter after it has one too, and
/// the C ABI orders its arguments by what they mean rather than by which of
/// them are optional — `otio_marker_new` takes an optional name and then a
/// range it insists on. So a default survives only in the run of them that
/// reaches the end of the list.
fn spell(params: &[(String, Option<String>)]) -> (Vec<String>, Vec<String>) {
    let mut keep = params.len();
    while keep > 0 && params[keep - 1].1.is_some() {
        keep -= 1;
    }
    let declared = params
        .iter()
        .enumerate()
        .map(|(index, (decl, fallback))| match fallback {
            Some(value) if index >= keep => format!("{decl} = {value}"),
            _ => decl.clone(),
        })
        .collect();
    let plain = params.iter().map(|(decl, _)| decl.clone()).collect();
    (declared, plain)
}

impl Site<'_> {
    /// The line that finds the arena this call is made in.
    fn reach(&self) -> Vec<String> {
        let found = |what: String| vec![format!("const detail::Site at = {what};")];
        match &self.anchor {
            Anchor::None => Vec::new(),
            Anchor::Receiver(object) => found(format!("detail::locate({object})")),
            // The argument became the receiver, so it is `*this` by the time
            // the definition is written.
            Anchor::Argument(_) => found("detail::locate(*this)".to_string()),
            Anchor::Named(name) => found(format!("detail::locate({name})")),
            Anchor::List(name) => found(format!("detail::locate_all({name})")),
            Anchor::Root => found("detail::rooted_at(root)".to_string()),
            Anchor::Fresh => found("detail::fresh()".to_string()),
        }
    }

    /// Writes the call out.
    #[allow(clippy::too_many_lines)]
    fn render(&self) -> Result<Rendered, String> {
        let function = self.function;
        let mut params: Vec<(String, Option<String>)> = Vec::new();
        let mut args: Vec<String> = Vec::new();
        let mut pre: Vec<String> = Vec::new();
        let mut results: Vec<(String, String, String)> = Vec::new();
        let mut lists: Vec<(String, String, Type)> = Vec::new();
        let mut length: Option<String> = None;
        // Each is the throwing check and the plain question it asks, since
        // a call that cannot fail has no way to report the mistake.
        let mut guarded: Vec<(String, String)> = Vec::new();

        for (index, param) in function.params.iter().enumerate() {
            let local = format!("c_{}", param.name);
            // The object the call is anchored on is the call's receiver in
            // C++, wherever the C ABI happens to put it.
            if self.anchor == Anchor::Argument(index) {
                args.push(self.receiver.clone());
                continue;
            }
            match param.role {
                ParamRole::DocumentIn | ParamRole::DocumentMut => {
                    if self.anchor == Anchor::Root {
                        push_param(&mut params, &format!("const {ROOT} &root"), None);
                    }
                    args.push(self.owner.clone());
                }
                ParamRole::DocumentTaken => {
                    return Err(format!(
                        "`{}` consumes a document, so it cannot be emitted mechanically; write \
                         it by hand and add it to `BY_HAND`",
                        function.symbol
                    ));
                }
                ParamRole::Receiver => args.push(self.receiver.clone()),
                ParamRole::Length => {
                    let taken = length.take().ok_or_else(|| {
                        format!(
                            "`{}` states a length with nothing before it",
                            function.symbol
                        )
                    })?;
                    args.push(taken);
                }
                ParamRole::ListCapacity => args.push("{capacity}".to_string()),
                ParamRole::OutputCount => args.push("&count".to_string()),
                ParamRole::Error => {
                    // The library writes the message beside the status it
                    // returns, so the exception is built from what this
                    // call said and not from anything a later one could
                    // touch. The buffer is released when it leaves scope,
                    // which covers the throw and the success alike.
                    pre.push(format!("detail::Buffer {ERROR_LOCAL};"));
                    args.push(format!("&{ERROR_LOCAL}.raw"));
                }
                ParamRole::OutputList => {
                    let Type::List(element) = &param.ty else {
                        return Err(format!("`{}` has a list that is not one", function.symbol));
                    };
                    let bare = param.name.strip_prefix("out_").unwrap_or(&param.name);
                    args.push(format!("{{list{}}}", lists.len()));
                    lists.push((
                        format!("list{}", lists.len()),
                        bare.to_string(),
                        (**element).clone(),
                    ));
                    results.push((
                        bare.to_string(),
                        format!("std::vector<{}>", cpp_type(element)),
                        format!("out_{bare}"),
                    ));
                }
                ParamRole::Output => {
                    let bare = param.name.strip_prefix("out_").unwrap_or(&param.name);
                    let out = format!("out_{bare}");
                    match &param.ty {
                        Type::Text | Type::Bytes => {
                            pre.push(format!("detail::Buffer {out};"));
                            args.push(format!("&{out}.raw"));
                        }
                        Type::Document => {
                            pre.push(format!("OtioDocument *{out} = nullptr;"));
                            args.push(format!("&{out}"));
                        }
                        ty => {
                            pre.push(format!("{} {out}{{}};", c_type(ty)));
                            args.push(format!("&{out}"));
                        }
                    }
                    let expression = match (&param.ty, self.wrap.as_deref()) {
                        (Type::Node, Some(class)) => {
                            format!("{class}(detail::Adopt{{}}, {}, {out})", self.holder)
                        }
                        (Type::Text, _) => format!("{out}.text()"),
                        (Type::Bytes, _) => format!("{out}.bytes()"),
                        (ty, _) => from_c(ty, &out, &self.holder),
                    };
                    let spelled = match (&param.ty, self.wrap.as_deref()) {
                        (Type::Node, Some(class)) => class.to_string(),
                        (ty, _) => cpp_type(ty),
                    };
                    results.push((bare.to_string(), spelled, expression));
                }
                ParamRole::Bytes => {
                    let name = param.name.clone();
                    push_param(
                        &mut params,
                        &format!("const std::vector<std::uint8_t> &{name}"),
                        None,
                    );
                    args.push(format!("{name}.data()"));
                    length = Some(format!("{name}.size()"));
                }
                ParamRole::Input => {
                    self.input(
                        param,
                        &local,
                        &mut params,
                        &mut pre,
                        &mut args,
                        &mut length,
                        &mut guarded,
                    )?;
                }
            }
        }

        match &function.result {
            CResult::Value(ty) => results.push((
                "value".to_string(),
                cpp_type(ty),
                from_c(ty, "value", &self.holder),
            )),
            CResult::StaticText => results.push((
                "value".to_string(),
                "std::string".to_string(),
                "detail::text(value)".to_string(),
            )),
            CResult::Void | CResult::Status => {}
        }

        let mut nested: (Option<String>, Vec<String>) = (None, Vec::new());
        let mut result = match results.len() {
            0 => String::new(),
            1 => results[0].1.clone(),
            _ => {
                let name = format!("{}Result", names::pascal(&self.member));
                nested
                    .1
                    .push(format!("/// What `{}` answers with.", self.member));
                nested.1.push(format!("struct {name} {{"));
                for (label, spelled, _) in &results {
                    nested.1.push(format!("{TAB}{spelled} {label};"));
                }
                nested.1.push("};".to_string());
                nested.0 = Some(name.clone());
                name
            }
        };
        if function.optional && !result.is_empty() {
            result = format!("std::optional<{result}>");
        }

        let mut lines: Vec<String> = self.reach();
        for (checked, asked) in &guarded {
            if function.fallible() {
                lines.push(format!("{checked};"));
                continue;
            }
            // A call that answers with a plain value has no error to hand
            // back, so an object from another document gets the answer it
            // deserves: no document contains one, and nothing equals one.
            let zero = match &function.result {
                CResult::Value(ty) => cpp_zero(ty)?,
                other => {
                    return Err(format!(
                        "`{}` takes an object and returns `{other:?}`, so it has no way to say \
                         the object came from another document",
                        function.symbol
                    ));
                }
            };
            lines.push(format!("if (!{asked}) {{"));
            lines.push(format!("{TAB}return {zero};"));
            lines.push("}".to_string());
        }
        lines.extend(pre);
        self.invoke(&mut lines, &args, &lists)?;
        match results.len() {
            0 => {}
            1 => lines.push(format!("return {};", results[0].2)),
            _ => {
                let fields: Vec<String> = results
                    .iter()
                    .map(|(_, _, expression)| expression.clone())
                    .collect();
                let name = format!("{}Result", names::pascal(&self.member));
                lines.push(format!("return {name}{{{}}};", fields.join(", ")));
            }
        }

        let (declared, plain) = spell(&params);
        Ok(Rendered {
            params: declared,
            plain,
            result,
            nested: nested.1,
            nested_name: nested.0,
            body: lines,
        })
    }

    /// Writes an argument the caller supplies.
    #[allow(clippy::too_many_arguments)]
    fn input(
        &self,
        param: &Param,
        local: &str,
        params: &mut Vec<(String, Option<String>)>,
        pre: &mut Vec<String>,
        args: &mut Vec<String>,
        length: &mut Option<String>,
        guarded: &mut Vec<(String, String)>,
    ) -> Result<(), String> {
        let name = param.name.clone();
        // What the call does with an object it is handed is the
        // description's answer and not this backend's: the same question
        // decides the same way in every binding that hides the document.
        // Getting it backwards is silent — moving an object the call was
        // only going to name swallows the timeline it came from.
        let bring = || match param.placement {
            Some(Placement::Adopt) => Ok("adopt"),
            Some(Placement::Require) => Ok("require_here"),
            None => Err(format!(
                "`{}` takes `{}` as an object and the description does not say what it does \
                 with it",
                self.function.symbol, param.name
            )),
        };
        if self.anchor != Anchor::None {
            match &param.ty {
                // A call that answers with a plain value has no exception to
                // throw, so it is asked the plain question instead and an
                // object from another timeline gets the answer it deserves.
                Type::Node if !self.function.fallible() => guarded.push((
                    format!("detail::require_here(at, {name})"),
                    format!("detail::here(at, {name})"),
                )),
                Type::List(inner) if **inner == Type::Node && !self.function.fallible() => {
                    guarded.push((
                        format!("detail::require_here_all(at, {name})"),
                        format!("detail::here_all(at, {name})"),
                    ));
                }
                _ => {}
            }
        }
        match (&param.ty, param.optional) {
            (Type::Node, false) if self.anchor != Anchor::None => {
                push_param(params, &format!("const {ROOT} &{name}"), None);
                args.push(format!("detail::{}(at, {name})", bring()?));
                return Ok(());
            }
            (Type::Node, true) if self.anchor != Anchor::None => {
                push_param(
                    params,
                    &format!("const std::optional<{ROOT}> &{name}"),
                    Some("std::nullopt"),
                );
                args.push(format!("detail::{}(at, {name})", bring()?));
                return Ok(());
            }
            (Type::List(inner), _) if **inner == Type::Node && self.anchor != Anchor::None => {
                push_param(params, &format!("const std::vector<{ROOT}> &{name}"), None);
                pre.push(format!(
                    "const std::vector<OtioNode> {local} = detail::{}_all(at, {name});",
                    bring()?
                ));
                args.push(format!("{local}.data()"));
                *length = Some(format!("{local}.size()"));
                return Ok(());
            }
            _ => {}
        }
        match (&param.ty, param.optional) {
            (Type::Text, true) => {
                push_param(
                    params,
                    &format!("const std::optional<std::string> &{name}"),
                    Some("std::nullopt"),
                );
                pre.push(format!(
                    "const char *{local} = {name} ? {name}->c_str() : nullptr;"
                ));
                args.push(local.to_string());
            }
            (Type::Text, false) => {
                push_param(params, &format!("const std::string &{name}"), None);
                args.push(format!("{name}.c_str()"));
            }
            (Type::Node, true) => {
                push_param(
                    params,
                    &format!("const std::optional<{ROOT}> &{name}"),
                    Some("std::nullopt"),
                );
                pre.push(format!(
                    "const OtioNode {local} = {name} ? {name}->handle() : otio_node_none();"
                ));
                args.push(local.to_string());
            }
            (Type::Node, false) => {
                push_param(params, &format!("const {ROOT} &{name}"), None);
                args.push(format!("{name}.handle()"));
            }
            (Type::Struct(c_name), true) => {
                push_param(
                    params,
                    &format!("const std::optional<{}> &{name}", value_name(c_name)),
                    Some("std::nullopt"),
                );
                pre.push(format!("{c_name} {local}_value{{}};"));
                pre.push(format!("const {c_name} *{local} = nullptr;"));
                pre.push(format!("if ({name}) {{"));
                pre.push(format!("{TAB}{local}_value = {name}->c_value();"));
                pre.push(format!("{TAB}{local} = &{local}_value;"));
                pre.push("}".to_string());
                args.push(local.to_string());
            }
            (Type::Struct(c_name), false) => {
                push_param(
                    params,
                    &format!("const {} &{name}", value_name(c_name)),
                    None,
                );
                args.push(format!("{name}.c_value()"));
            }
            (Type::List(element), _) => {
                push_param(
                    params,
                    &format!("const std::vector<{}> &{name}", cpp_type(element)),
                    None,
                );
                pre.push(format!("std::vector<{}> {local};", c_type(element)));
                pre.push(format!("{local}.reserve({name}.size());"));
                pre.push(format!("for (const auto &item : {name}) {{"));
                pre.push(format!(
                    "{TAB}{local}.push_back({});",
                    to_c(element, "item")
                ));
                pre.push("}".to_string());
                args.push(format!("{local}.data()"));
                *length = Some(format!("{local}.size()"));
            }
            (Type::Bytes | Type::Document, _) => {
                return Err(format!(
                    "`{}` takes a `{}` as an argument, which this does not write",
                    self.function.symbol,
                    param.ty.c_name()
                ));
            }
            (ty, _) => {
                let spelled = cpp_type(ty);
                let decl = if by_reference(ty) {
                    format!("const {spelled} &{name}")
                } else {
                    format!("{spelled} {name}")
                };
                push_param(params, &decl, None);
                args.push(to_c(ty, &name));
            }
        }
        Ok(())
    }

    /// Writes the call itself, and the two-pass dance where it answers with
    /// a list.
    fn invoke(
        &self,
        lines: &mut Vec<String>,
        args: &[String],
        lists: &[(String, String, Type)],
    ) -> Result<(), String> {
        let symbol = &self.function.symbol;

        if lists.is_empty() {
            let call = format!("{symbol}({})", args.join(", "));
            match &self.function.result {
                // A call with nothing to answer with has no optional to
                // answer an empty one with, so its no-value is thrown like
                // any other status and read off the error.
                CResult::Status if self.function.optional && self.answers() => {
                    lines.push(format!("const OtioStatus status = {call};"));
                    lines.push("if (detail::is_no_value(status)) {".to_string());
                    lines.push(format!("{TAB}return std::nullopt;"));
                    lines.push("}".to_string());
                    lines.push(self.check("status")?);
                }
                CResult::Status => lines.push(self.check(&call)?),
                CResult::Void => lines.push(format!("{call};")),
                CResult::Value(_) | CResult::StaticText => {
                    lines.push(format!("const auto value = {call};"));
                }
            }
            return Ok(());
        }

        lines.push("std::size_t count = 0;".to_string());
        let room = if let Some(sizer) = self.function.sized_by.as_deref() {
            // This call empties what it reports, so it cannot be asked
            // twice. Another call says how long the answer will be, and this
            // one is made once into a buffer that size.
            lines.push(format!(
                "// {symbol} answers and empties in one go, so the buffer is sized first."
            ));
            lines.push("std::size_t room = 0;".to_string());
            lines.push(self.check(&self.sizing_call(sizer)?)?);
            "room".to_string()
        } else {
            let sized: Vec<String> = args
                .iter()
                .map(|argument| {
                    if argument.starts_with("{list") {
                        "nullptr".to_string()
                    } else if argument == "{capacity}" {
                        "0".to_string()
                    } else {
                        argument.clone()
                    }
                })
                .collect();
            lines.push(self.check(&format!("{symbol}({})", sized.join(", ")))?);
            "count".to_string()
        };

        for (buffer, _, element) in lists {
            lines.push(format!(
                "std::vector<{}> {buffer}({room});",
                c_type(element)
            ));
        }
        let filled: Vec<String> = args
            .iter()
            .map(|argument| {
                if let Some(index) = argument
                    .strip_prefix("{list")
                    .and_then(|rest| rest.strip_suffix('}'))
                    .and_then(|digits| digits.parse::<usize>().ok())
                {
                    return format!("{}.data()", lists[index].0);
                }
                if argument == "{capacity}" {
                    return format!("{}.size()", lists[0].0);
                }
                argument.clone()
            })
            .collect();
        lines.push(self.check(&format!("{symbol}({})", filled.join(", ")))?);
        // A document does not change between the two calls, so this cannot
        // trip; it is here so that a mistaken count is a short vector rather
        // than a walk off the end of the buffer.
        lines.push(format!(
            "const std::size_t taken = count < {0}.size() ? count : {0}.size();",
            lists[0].0
        ));
        for (buffer, label, element) in lists {
            let spelled = cpp_type(element);
            lines.push(format!("std::vector<{spelled}> out_{label};"));
            lines.push(format!("out_{label}.reserve(taken);"));
            lines.push("for (std::size_t index = 0; index < taken; ++index) {".to_string());
            lines.push(format!(
                "{TAB}out_{label}.push_back({});",
                from_c(element, &format!("{buffer}[index]"), &self.holder)
            ));
            lines.push("}".to_string());
        }
        Ok(())
    }

    /// The line that throws unless a status is success, with the message the
    /// call wrote beside it.
    fn check(&self, status: &str) -> Result<String, String> {
        if self.function.error().is_none() {
            return Err(format!(
                "`{}` answers with a status but has nowhere to hand its message back",
                self.function.symbol
            ));
        }
        Ok(format!("detail::check({status}, {ERROR_LOCAL});"))
    }

    /// Whether the call hands anything back, which decides whether its
    /// no-value has an empty optional to be.
    fn answers(&self) -> bool {
        !self.function.outputs.is_empty()
            || matches!(
                self.function.result,
                CResult::Value(_) | CResult::StaticText
            )
    }

    /// Writes the call that says how long a consuming list call's answer
    /// will be.
    fn sizing_call(&self, sizer: &str) -> Result<String, String> {
        let function = self
            .api
            .functions()
            .find(|candidate| candidate.symbol == sizer)
            .ok_or_else(|| format!("`{sizer}` is not a call this library has"))?;
        let mut args = Vec::new();
        for param in &function.params {
            match param.role {
                ParamRole::DocumentIn | ParamRole::DocumentMut => args.push(self.owner.clone()),
                ParamRole::Receiver => args.push(self.receiver.clone()),
                ParamRole::Output => args.push("&room".to_string()),
                // The sizing call shares the buffer the call it sizes
                // declared. It is empty again by the time the second call
                // writes it, because a sizing call that failed has already
                // thrown and one that succeeded left nothing in it.
                ParamRole::Error if self.function.error().is_some() => {
                    args.push(format!("&{ERROR_LOCAL}.raw"));
                }
                _ => {
                    return Err(format!(
                        "`{sizer}` takes a `{}`, so it cannot size another call's answer",
                        param.name
                    ));
                }
            }
        }
        Ok(format!("{sizer}({})", args.join(", ")))
    }
}

/// One member of a type, or one free function: its documentation, how it is
/// declared, and how it is defined.
struct Member {
    doc: Vec<String>,
    nested: Vec<String>,
    decl: String,
    define: String,
    body: Vec<String>,
}

impl Backend<'_> {
    /// Rewrites a doc comment into C++'s shape: the interface's own symbols
    /// spelled the way this SDK spells them, `null` said as `absent`.
    fn doc(&self, docs: &Docs, notes: &[String], symbol: Option<&str>) -> Vec<String> {
        let mut paragraphs: Vec<String> = Vec::new();
        let summary = self.rewrite(&docs.summary);
        if summary.is_empty() {
            if symbol.is_some() {
                paragraphs.push("Wraps the interface's call of the same name.".to_string());
            }
        } else {
            paragraphs.push(summary);
        }
        for paragraph in &docs.body {
            paragraphs.push(self.rewrite(paragraph));
        }
        paragraphs.extend(notes.iter().cloned());
        for paragraph in &mut paragraphs {
            *paragraph = absent_for_null(paragraph);
        }
        if let Some(symbol) = symbol {
            paragraphs.push(format!("C: `{symbol}`"));
        }

        let mut lines = Vec::new();
        for (index, paragraph) in paragraphs.iter().enumerate() {
            if index > 0 {
                lines.push("///".to_string());
            }
            for line in wrap(paragraph, 72) {
                if line.is_empty() {
                    lines.push("///".to_string());
                } else {
                    lines.push(format!("/// {line}"));
                }
            }
        }
        lines
    }

    /// Replaces the interface's own names with this SDK's.
    fn rewrite(&self, text: &str) -> String {
        let mut out = text.to_string();
        // Longest first, so `otio_node_kind` is not half-replaced by a
        // shorter symbol that happens to be a prefix of it.
        let mut symbols: Vec<&String> = self.spellings.keys().collect();
        symbols.sort_by_key(|symbol| std::cmp::Reverse(symbol.len()));
        for symbol in symbols {
            if !out.contains(symbol.as_str()) {
                continue;
            }
            let spelled = &self.spellings[symbol];
            out = out.replace(&format!("`{symbol}`"), &format!("`{spelled}`"));
            out = out.replace(symbol.as_str(), spelled);
        }
        // Rust spells a link to another item `[`name`]`, which C++ has no
        // syntax for.
        out.replace("[`", "`").replace("`]", "`")
    }
}

/// Says what a C++ programmer says where the C interface's prose says
/// `null`, which for an argument this SDK takes as an optional is that the
/// argument is absent.
fn absent_for_null(text: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    for word in text.split(' ') {
        let trimmed = word.trim_end_matches(|character: char| !character.is_alphanumeric());
        if !trimmed.eq_ignore_ascii_case("null") {
            words.push(word.to_string());
            continue;
        }
        // "a null key" becomes "an absent key", not "a absent key".
        if let Some(article) = words.last_mut() {
            if article == "a" {
                *article = "an".to_string();
            } else if article == "A" {
                *article = "An".to_string();
            }
        }
        words.push(format!("absent{}", &word[trimmed.len()..]));
    }
    words.join(" ")
}

/// Wraps a paragraph at a width, on spaces.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines = Vec::new();
    let mut current = String::new();
    for word in text.split_whitespace() {
        if !current.is_empty() && current.len() + 1 + word.len() > width {
            lines.push(std::mem::take(&mut current));
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }
    if !current.is_empty() {
        lines.push(current);
    }
    if lines.is_empty() {
        lines.push(String::new());
    }
    lines
}

impl Backend<'_> {
    /// Writes one call as a member of one type, or as a free function where
    /// `into` is empty.
    #[allow(clippy::too_many_lines)]
    fn member_of(&self, group: &Group, function: &Function, into: &str) -> Result<Member, String> {
        let name = member_name(group, function);
        let mut is_static = false;
        let mut wrap_as: Option<String> = None;
        let mut lead: Vec<String> = Vec::new();
        // Where the object the call is about, and so the arena it is made
        // in, comes from. `at` is that object resolved: the arena holding it
        // now, that arena's document, and its handle there.
        let mut anchor = Anchor::None;

        let on_enum = matches!(&group.receiver, Receiver::Value(what)
            if self.api.enumeration(what).is_some());

        let (owner, receiver) = if on_enum {
            let Receiver::Value(what) = &group.receiver else {
                unreachable!("an enum receiver is a value receiver")
            };
            match function.receiver() {
                Some(_) => {
                    let spelled = enum_name(what);
                    let argument = snake(&spelled);
                    lead.push(format!("{spelled} {argument}"));
                    (
                        "nullptr".to_string(),
                        format!("static_cast<{what}>(static_cast<int32_t>({argument}))"),
                    )
                }
                None => ("nullptr".to_string(), String::new()),
            }
        } else {
            match (&group.receiver, function.role) {
                (Receiver::None, _) => ("nullptr".to_string(), String::new()),
                (Receiver::Document, Role::Constructor)
                | (Receiver::Document, Role::Free)
                | (Receiver::Value(_), Role::Constructor | Role::Free) => {
                    is_static = true;
                    ("nullptr".to_string(), String::new())
                }
                (Receiver::Document, _) if !takes_a_document(function) => {
                    is_static = true;
                    ("nullptr".to_string(), String::new())
                }
                (Receiver::Document, _) => {
                    match rehomed(&function.symbol) {
                        // A call the C ABI hangs off the document is about
                        // one of the objects it is handed, so in C++ it
                        // hangs off that.
                        Some(_) => anchor = Anchor::Argument(anchor_index(function)?),
                        None => {
                            is_static = true;
                            match function.params.iter().position(|param| param.anchor) {
                                Some(index) => {
                                    let named = function.params[index].name.clone();
                                    anchor = if matches!(function.params[index].ty, Type::List(_)) {
                                        Anchor::List(named)
                                    } else {
                                        Anchor::Named(named)
                                    };
                                }
                                // Writing is the one thing left that wants a
                                // whole document and is handed no object to
                                // find it by, so it takes one and starts
                                // there.
                                None => anchor = Anchor::Root,
                            }
                        }
                    }
                    ("at.pointer".to_string(), "at.handle".to_string())
                }
                // An object is built in an arena of its own, and moves into
                // a timeline's when it is put in one. That is what lets a
                // clip exist before the track it is going to sit on.
                (Receiver::Node(schema), Role::Constructor) if takes_a_document(function) => {
                    is_static = true;
                    wrap_as = Some(schema.clone());
                    anchor = Anchor::Fresh;
                    ("at.pointer".to_string(), String::new())
                }
                (Receiver::Node(_), Role::Constructor) => {
                    is_static = true;
                    ("nullptr".to_string(), String::new())
                }
                (Receiver::Node(_), _) if group.view => {
                    anchor = Anchor::Receiver("object_".to_string());
                    ("at.pointer".to_string(), "at.handle".to_string())
                }
                (Receiver::Node(_), _) => {
                    anchor = Anchor::Receiver("*this".to_string());
                    ("at.pointer".to_string(), "at.handle".to_string())
                }
                (Receiver::Value(_), _) => ("nullptr".to_string(), "c_value()".to_string()),
            }
        };

        let site = Site {
            api: self.api,
            function,
            holder: if anchor == Anchor::None {
                "std::shared_ptr<detail::Arena>()".to_string()
            } else {
                "at.arena".to_string()
            },
            owner,
            receiver,
            anchor,
            wrap: wrap_as,
            member: name.clone(),
        };
        let rendered = site.render()?;

        // Where the interface's prose already says an argument may be
        // absent, it is left to say it rather than said twice.
        let said = function.docs.summary.to_lowercase().contains("null")
            || function
                .docs
                .body
                .iter()
                .any(|paragraph| paragraph.to_lowercase().contains("null"));
        let mut notes = Vec::new();
        if !said {
            for param in function.inputs() {
                if !param.optional {
                    continue;
                }
                notes.push(format!("An absent `{}` means none.", param.name));
            }
        }
        let says_no_value = std::iter::once(&function.docs.summary)
            .chain(function.docs.body.iter())
            .any(|paragraph| paragraph.contains("NO_VALUE"));
        if function.optional && !says_no_value {
            notes.push(if rendered.result.is_empty() {
                "Where there was nothing to do this throws an `Error` whose status is \
                 `Status::NO_VALUE`, which is an answer rather than a failure."
                    .to_string()
            } else {
                "Where there is nothing to report this answers an empty optional, which is an \
                 answer rather than a failure."
                    .to_string()
            });
        }
        let doc = self.doc(&function.docs, &notes, Some(&function.symbol));

        let result = if rendered.result.is_empty() {
            "void".to_string()
        } else {
            rendered.result.clone()
        };
        // A free function has no `this` to qualify, and a call that edits the
        // document it is given cannot promise to leave the object alone.
        let mutates = takes_a_document(function) && !reads_only(function);
        let konst = if is_static || into.is_empty() || mutates {
            ""
        } else {
            " const"
        };
        let mut params: Vec<String> = lead.clone();
        params.extend(rendered.params.iter().cloned());
        let mut plain: Vec<String> = lead;
        plain.extend(rendered.plain.iter().cloned());

        // `static` on a member means "no object needed"; on a free function
        // it would mean internal linkage, which is not the same thing at all.
        let lead_word = if is_static && !into.is_empty() {
            "static "
        } else {
            ""
        };
        let decl = format!("{lead_word}{result} {name}({}){konst}", params.join(", "));
        let scope = if into.is_empty() {
            String::new()
        } else {
            format!("{into}::")
        };
        let spelled = match (&rendered.nested_name, rendered.result.is_empty()) {
            (_, true) => "void".to_string(),
            // A result struct is declared where the call is, so the
            // definition has to say where that was.
            (Some(name), false) => rendered
                .result
                .replace(name.as_str(), &format!("{scope}{name}")),
            (None, false) => rendered.result.clone(),
        };
        let define = format!(
            "inline {spelled} {scope}{name}({}){konst}",
            plain.join(", ")
        );

        Ok(Member {
            doc,
            nested: rendered.nested,
            decl,
            define,
            body: rendered.body,
        })
    }

    /// Every call of one group that a filter accepts, as members of a type.
    fn members(
        &self,
        group: &Group,
        into: &str,
        wanted: impl Fn(&Function) -> bool,
    ) -> Result<Vec<Member>, String> {
        let mut members = Vec::new();
        for function in &group.functions {
            if self.skipped(function) || !wanted(function) {
                continue;
            }
            members.push(self.member_of(group, function, into)?);
        }
        Ok(members)
    }
}

/// Writes the members of a class into its body.
fn write_declarations(out: &mut String, members: &[Member]) {
    for member in members {
        for line in &member.nested {
            let _ = writeln!(out, "{TAB}{line}");
        }
        if !member.nested.is_empty() {
            out.push('\n');
        }
        for line in &member.doc {
            let _ = writeln!(out, "{TAB}{line}");
        }
        let _ = writeln!(out, "{TAB}{};\n", member.decl);
    }
}

/// Writes the members of a class as definitions, at namespace scope.
fn write_definitions(out: &mut String, members: &[Member]) {
    for member in members {
        let _ = writeln!(out, "{} {{", member.define);
        for line in &member.body {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "{TAB}{line}");
            }
        }
        let _ = writeln!(out, "}}\n");
    }
}

/// Writes free functions' declarations, with any result struct beside them.
fn write_free_declarations(out: &mut String, members: &[Member]) {
    for member in members {
        for line in &member.nested {
            let _ = writeln!(out, "{line}");
        }
        if !member.nested.is_empty() {
            out.push('\n');
        }
        for line in &member.doc {
            let _ = writeln!(out, "{line}");
        }
        let _ = writeln!(out, "{};\n", member.decl);
    }
}

impl Backend<'_> {
    /// The enums, as real C++ enums with the C interface's own values.
    fn enums(&self) -> String {
        let mut out = String::from(ENUMS_HEAD);
        for item in &self.api.enums {
            let spelled = enum_name(&item.name);
            let prefix = shared_prefix(item);
            for line in self.doc(&item.docs, &[], None) {
                let _ = writeln!(out, "{line}");
            }
            let _ = writeln!(out, "enum class {spelled} : std::int32_t {{");
            for (index, variant) in item.variants.iter().enumerate() {
                if index > 0 {
                    out.push('\n');
                }
                for line in self.doc(&variant.docs, &[], None) {
                    let _ = writeln!(out, "{TAB}{line}");
                }
                let _ = writeln!(
                    out,
                    "{TAB}{} = {},",
                    constant_name(&variant.c_name, &prefix),
                    variant.value
                );
            }
            let _ = writeln!(out, "}};\n");

            let _ = writeln!(out, "/// The name the C interface spells a value by.");
            let _ = writeln!(out, "inline const char *to_string({spelled} value) {{");
            let _ = writeln!(out, "{TAB}switch (value) {{");
            for variant in &item.variants {
                let _ = writeln!(
                    out,
                    "{TAB}case {spelled}::{}:\n{TAB}{TAB}return \"{}\";",
                    constant_name(&variant.c_name, &prefix),
                    variant.c_name
                );
            }
            let _ = writeln!(out, "{TAB}}}");
            let _ = writeln!(out, "{TAB}return \"\";");
            let _ = writeln!(out, "}}\n");
        }
        out.push_str(NAMESPACE_END);
        out
    }

    /// The value structs, in an order where each is declared after whatever
    /// it holds.
    fn ordered_structs(&self) -> Vec<&Struct> {
        let mut wanted: Vec<&Struct> = self
            .api
            .structs
            .iter()
            .filter(|item| !item.plumbing && item.name != "OtioNode")
            .collect();
        let mut ordered: Vec<&Struct> = Vec::new();
        while !wanted.is_empty() {
            let before = wanted.len();
            wanted.retain(|item| {
                let ready = item.fields.iter().all(|field| match &field.ty {
                    Type::Struct(name) => ordered.iter().any(|done| done.name == *name),
                    _ => true,
                });
                if ready {
                    ordered.push(item);
                }
                !ready
            });
            if wanted.len() == before {
                // Nothing became ready, so two structs hold each other,
                // which C++ cannot declare and the C ABI cannot have.
                ordered.append(&mut wanted);
            }
        }
        ordered
    }

    /// The value structs and their members' declarations.
    fn values(&self) -> Result<String, String> {
        let mut out = String::from(VALUES_HEAD);
        for item in self.ordered_structs() {
            let spelled = value_name(&item.name);
            for line in self.doc(&item.docs, &[], None) {
                let _ = writeln!(out, "{line}");
            }
            let _ = writeln!(out, "struct {spelled} {{");
            for field in &item.fields {
                for line in self.doc(&field.docs, &[], None) {
                    let _ = writeln!(out, "{TAB}{line}");
                }
                let _ = writeln!(out, "{TAB}{} {}{{}};\n", cpp_type(&field.ty), field.name);
            }
            // Every field after the first defaults to zero in an options
            // struct, so a field added later is not a break for a caller
            // that names the ones before it. The first has none, which would
            // make this constructor and the one above ambiguous.
            let arguments: Vec<String> = item
                .fields
                .iter()
                .enumerate()
                .map(|(index, field)| {
                    let spelled = cpp_type(&field.ty);
                    let default = if index > 0 && item.fields_default_to_zero() {
                        " = {}"
                    } else {
                        ""
                    };
                    if by_reference(&field.ty) {
                        format!("const {spelled} &{}{default}", field.name)
                    } else {
                        format!("{spelled} {}{default}", field.name)
                    }
                })
                .collect();
            let _ = writeln!(out, "{TAB}/// Makes one with every field at its zero.");
            let _ = writeln!(out, "{TAB}{spelled}() = default;\n");
            let _ = writeln!(out, "{TAB}/// Makes one from its parts.");
            let _ = writeln!(out, "{TAB}{spelled}({});\n", arguments.join(", "));
            let _ = writeln!(
                out,
                "{TAB}/// Reads one out of the C interface. This is the plumbing."
            );
            let _ = writeln!(
                out,
                "{TAB}explicit {spelled}(const {} &value);\n",
                item.name
            );
            let _ = writeln!(
                out,
                "{TAB}/// Spells the value the way the C interface wants it. This is the\n\
                 {TAB}/// plumbing, and anything of variable length in the answer is borrowed\n\
                 {TAB}/// from this value, so the answer lives no longer than it does."
            );
            let _ = writeln!(out, "{TAB}{} c_value() const;\n", item.name);

            for group in &self.api.groups {
                if group.receiver != Receiver::Value(item.name.clone()) {
                    continue;
                }
                let members = self.members(group, &spelled, |_| true)?;
                write_declarations(&mut out, &members);
            }
            let _ = writeln!(out, "}};\n");

            let comparisons: Vec<String> = item
                .fields
                .iter()
                .map(|field| format!("left.{0} == right.{0}", field.name))
                .collect();
            let _ = writeln!(out, "/// Whether two are the same in every field.");
            let _ = writeln!(
                out,
                "inline bool operator==(const {spelled} &left, const {spelled} &right) {{"
            );
            let _ = writeln!(out, "{TAB}return {};", comparisons.join("\n        && "));
            let _ = writeln!(out, "}}\n");
            let _ = writeln!(out, "/// Whether two differ in any field.");
            let _ = writeln!(
                out,
                "inline bool operator!=(const {spelled} &left, const {spelled} &right) {{"
            );
            let _ = writeln!(out, "{TAB}return !(left == right);");
            let _ = writeln!(out, "}}\n");
        }
        out.push_str(NAMESPACE_END);
        Ok(out)
    }

    /// The classes: the objects in a document, the document itself, and the
    /// metadata every named object carries.
    #[allow(clippy::too_many_lines)]
    fn objects(&self) -> Result<String, String> {
        let mut out = String::from(OBJECTS_HEAD);
        for schema in &self.api.schema {
            if schema.name == ROOT {
                continue;
            }
            let _ = writeln!(out, "class {};", schema.name);
        }
        out.push('\n');

        out.push_str(OBJECT_HEAD);
        for group in &self.api.groups {
            if group.receiver == Receiver::Node(ROOT.to_string()) && !group.view {
                let members = self.members(group, ROOT, |_| true)?;
                write_declarations(&mut out, &members);
            }
        }
        // The handful the C ABI hangs off the document that are really about
        // an object: taking one out of its timeline, copying it, asking
        // whether it is still there.
        for group in &self.api.groups {
            if group.receiver == Receiver::Document {
                let members =
                    self.members(group, ROOT, |function| rehomed(&function.symbol).is_some())?;
                write_declarations(&mut out, &members);
            }
        }
        out.push_str(OBJECT_TAIL);

        for schema in &self.api.schema {
            let Some(parent) = schema.parent.as_deref() else {
                continue;
            };
            for line in self.doc(&schema.docs, &[], None) {
                let _ = writeln!(out, "{line}");
            }
            let _ = writeln!(out, "class {} : public {parent} {{", schema.name);
            let _ = writeln!(out, " public:");
            let _ = writeln!(out, "{TAB}using {parent}::{parent};\n");
            for group in &self.api.groups {
                if group.view {
                    let Receiver::Node(on) = &group.receiver else {
                        continue;
                    };
                    if on == &schema.name {
                        let _ = writeln!(out, "{METADATA_MEMBER}");
                    }
                    continue;
                }
                if group.receiver != Receiver::Node(schema.name.clone()) {
                    continue;
                }
                let members = self.members(group, &schema.name, |_| true)?;
                write_declarations(&mut out, &members);
            }
            let _ = writeln!(out, "}};\n");
        }

        for group in &self.api.groups {
            if !group.view {
                continue;
            }
            for line in self.doc(&group.docs, &[], None) {
                let _ = writeln!(out, "{line}");
            }
            let _ = writeln!(out, "class {} {{", group.name);
            let _ = writeln!(out, " public:");
            let _ = writeln!(
                out,
                "{TAB}/// Reads an object's metadata. This is the plumbing; ask an object\n\
                 {TAB}/// for its own with `metadata()`."
            );
            let _ = writeln!(
                out,
                "{TAB}explicit {}(const {ROOT} &object) : object_(object) {{}}\n",
                group.name
            );
            let members = self.members(group, &group.name, |_| true)?;
            write_declarations(&mut out, &members);
            let _ = writeln!(out, " private:");
            let _ = writeln!(out, "{TAB}{ROOT} object_;");
            let _ = writeln!(out, "}};\n");
        }

        out.push_str("namespace detail {\n\n");
        let _ = writeln!(
            out,
            "/// The `NodeKind` a class stands for, so that `is<Clip>()` can ask the\n\
             /// library what an object really is.\n\
             template <class T>\n\
             struct schema_of;\n"
        );
        for schema in &self.api.schema {
            let _ = writeln!(
                out,
                "template <>\nstruct schema_of<{}> {{\n{TAB}static constexpr NodeKind kind = \
                 NodeKind::{};\n}};\n",
                schema.name,
                self.kind_of(&schema.kind)?
            );
        }
        let _ = writeln!(
            out,
            "/// The schema a schema derives from, for walking the ladder.\n\
             std::optional<NodeKind> schema_parent(NodeKind kind);\n"
        );
        out.push_str(SITE_DECL);
        out.push_str("}  // namespace detail\n\n");

        for group in &self.api.groups {
            let free = group.receiver == Receiver::None
                || group.receiver == Receiver::Document
                || matches!(&group.receiver, Receiver::Value(what)
                    if self.api.enumeration(what).is_some());
            if !free {
                continue;
            }
            let members =
                self.members(group, "", |function| rehomed(&function.symbol).is_none())?;
            write_free_declarations(&mut out, &members);
        }
        out.push_str(WHOLE_FILE_DECL);

        out.push_str(NAMESPACE_END);
        Ok(out)
    }

    /// The C++ name of a `NodeKind` constant.
    fn kind_of(&self, c_name: &str) -> Result<String, String> {
        let item = self
            .api
            .enumeration("OtioNodeKind")
            .ok_or_else(|| "the interface has no `OtioNodeKind`".to_string())?;
        let prefix = shared_prefix(item);
        let variant = item
            .variants
            .iter()
            .find(|variant| variant.name == c_name || variant.c_name == c_name)
            .ok_or_else(|| format!("`{c_name}` is not a node kind this library has"))?;
        Ok(constant_name(&variant.c_name, &prefix))
    }

    /// Every member's definition, which in a header-only package is where
    /// the work actually is.
    fn calls(&self) -> Result<String, String> {
        let mut out = String::from(CALLS_HEAD);

        let _ = writeln!(
            out,
            "inline std::optional<NodeKind> detail::schema_parent(NodeKind kind) {{"
        );
        let _ = writeln!(out, "{TAB}switch (kind) {{");
        for schema in &self.api.schema {
            let Some(parent) = schema.parent.as_deref() else {
                continue;
            };
            let Some(above) = self.api.schema.iter().find(|item| item.name == parent) else {
                continue;
            };
            let _ = writeln!(
                out,
                "{TAB}case NodeKind::{}:\n{TAB}{TAB}return NodeKind::{};",
                self.kind_of(&schema.kind)?,
                self.kind_of(&above.kind)?
            );
        }
        let _ = writeln!(out, "{TAB}default:");
        let _ = writeln!(out, "{TAB}{TAB}break;");
        let _ = writeln!(out, "{TAB}}}");
        let _ = writeln!(out, "{TAB}return std::nullopt;");
        let _ = writeln!(out, "}}\n");

        for item in self.ordered_structs() {
            let spelled = value_name(&item.name);
            let arguments: Vec<String> = item
                .fields
                .iter()
                .map(|field| {
                    let ty = cpp_type(&field.ty);
                    if by_reference(&field.ty) {
                        format!("const {ty} &{}", field.name)
                    } else {
                        format!("{ty} {}", field.name)
                    }
                })
                .collect();
            let initialisers: Vec<String> = item
                .fields
                .iter()
                .map(|field| format!("{0}({0})", field.name))
                .collect();
            let _ = writeln!(
                out,
                "inline {spelled}::{spelled}({})\n{TAB}: {} {{}}\n",
                arguments.join(", "),
                initialisers.join(", ")
            );

            let read: Vec<String> = item
                .fields
                .iter()
                .map(|field| {
                    let source = format!("value.{}", field.name);
                    format!("{}({})", field.name, from_c(&field.ty, &source, "nullptr"))
                })
                .collect();
            let _ = writeln!(
                out,
                "inline {spelled}::{spelled}(const {} &value)\n{TAB}: {} {{}}\n",
                item.name,
                read.join(", ")
            );

            let _ = writeln!(out, "inline {} {spelled}::c_value() const {{", item.name);
            let _ = writeln!(out, "{TAB}{} out{{}};", item.name);
            for field in &item.fields {
                let value = match &field.ty {
                    Type::Text => format!("{0}.empty() ? nullptr : {0}.c_str()", field.name),
                    ty => to_c(ty, &field.name),
                };
                let _ = writeln!(out, "{TAB}out.{} = {value};", field.name);
            }
            let _ = writeln!(out, "{TAB}return out;");
            let _ = writeln!(out, "}}\n");

            for group in &self.api.groups {
                if group.receiver != Receiver::Value(item.name.clone()) {
                    continue;
                }
                let members = self.members(group, &spelled, |_| true)?;
                write_definitions(&mut out, &members);
            }
        }

        for group in &self.api.groups {
            let Receiver::Node(schema) = &group.receiver else {
                continue;
            };
            let into = if group.view { &group.name } else { schema };
            if group.view {
                let _ = writeln!(
                    out,
                    "inline {0} {schema}::metadata() const {{\n{TAB}return {0}(*this);\n}}\n",
                    group.name
                );
            }
            let members = self.members(group, into, |_| true)?;
            write_definitions(&mut out, &members);
        }

        for group in &self.api.groups {
            if group.receiver == Receiver::Document {
                let members =
                    self.members(group, ROOT, |function| rehomed(&function.symbol).is_some())?;
                write_definitions(&mut out, &members);
            }
        }

        for group in &self.api.groups {
            let free = group.receiver == Receiver::None
                || group.receiver == Receiver::Document
                || matches!(&group.receiver, Receiver::Value(what)
                    if self.api.enumeration(what).is_some());
            if !free {
                continue;
            }
            let members =
                self.members(group, "", |function| rehomed(&function.symbol).is_none())?;
            write_definitions(&mut out, &members);
        }
        out.push_str(WHOLE_FILE_DEFN);

        out.push_str(NAMESPACE_END);
        Ok(out)
    }
}

